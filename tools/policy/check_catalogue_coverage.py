#!/usr/bin/env python3
"""Every catalogue a unit ships says every word its source catalogue says,
and nothing its source does not.

A unit's source language is `en-US`, the file its crate or package is written
in; the files beside it are translations. A message a translation lacks reads
in the source language for that string alone, which is the fallback every
lookup has (docs/designs/app-language/i18n.md) — one string, never a surface.
What this check finds is both shapes of drift: a catalogue that is partly
translated, so one window reads in two languages at once, and a translation
that adds a word its source has no original for, which reads in a translation
inside a window speaking the source language.

A locale may add messages of its own: the arrival screen's German jokes are
written for German speakers and have no English source. Those are not drift —
they are listed in [`LOCALE_ONLY`], and the source needs nothing.

A key a catalogue defines twice is not drift either: Fluent keeps one message
per key, so the second one breaks the whole file at load. It fails here, in
every mode, because no listing of keys should hide it.

The registry `tilo-app` generates beside the catalog (`src/locales.rs`)
registers the app's catalogs, and an unregistered one never loads: a window
that ships it reads in the source language. `tilo-app check` only compares
the app it is pointed at, so every generated registry is compared here too.

  check_catalogue_coverage.py            fail on every drifted or repeated key
  check_catalogue_coverage.py --list     print the drift, `unit locale key`, and pass
  check_catalogue_coverage.py --staged   fail on the drift this commit's catalogues add
  check_catalogue_coverage.py --range BASE..HEAD
                                         fail on the drift this range's catalogues add
"""

from __future__ import annotations

import os
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from check_copy_language import messages  # noqa: E402
from judged import STAGED_FLAG, git, judged  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
SOURCE_LOCALE = "en-US"
# The generated registry `tilo-app` owns, and the header that marks it: a
# registry without it is the app's own setup, which this check leaves alone.
REGISTRY = "src/locales.rs"
REGISTRY_HEADER = "// @generated by tilo-app; locale registry.\n"
# The catalogs a generated registry loads, read from the code that loads them
# (`ui::embedded_catalog!(pub static CATALOG, ["de-DE", "en-US"]);`) rather than
# from a comment beside it.
DECLARATION = re.compile(
    r"ui::embedded_catalog!\(\s*pub\s+static\s+CATALOG\s*,\s*\[([^\]]*)\]\s*\);"
)
LOCALE = re.compile(r'"([A-Za-z][A-Za-z0-9-]*)"')

# Keys a locale adds on purpose: copy written for speakers of that language,
# with no source-language original.
LOCALE_ONLY: dict[tuple[str, str], set[str]] = {}


def catalogues(root: Path) -> list[Path]:
    """Every catalogue in the tree, the source languages and the translations."""
    return sorted(
        path
        for path in root.rglob("locales/*.ftl")
        if "target" not in path.relative_to(root).parts
        and not any(part.startswith(".") for part in path.relative_to(root).parts)
    )


def unit_of(root: Path, catalogue: Path) -> str:
    """The crate or package that ships `catalogue`: the directory holding `locales/`."""
    return catalogue.parents[1].relative_to(root).as_posix()


def keys_in(text: str) -> dict[str, int]:
    """The message and attribute keys `text` defines, each by its line."""
    return {message.key: message.line for message in messages(text)}


def keys_of(catalogue: Path) -> dict[str, int]:
    """The message and attribute keys `catalogue` defines, each by its line."""
    return keys_in(catalogue.read_text())


def duplicated(root: Path) -> list[tuple[Path, str, int, int]]:
    """Per (catalogue, key, first line, repeated line), the keys it defines twice.

    Fluent holds one message per key: a second definition is a parse failure for
    everything that loads the catalogue, so it is not a word to translate but a
    broken file. Indexing the entries by key, as the rest of this check does,
    would read only the last and pass."""
    found = []
    for catalogue in catalogues(root):
        first: dict[str, int] = {}
        for message in messages(catalogue.read_text()):
            if message.key in first:
                found.append((catalogue, message.key, first[message.key], message.line))
            else:
                first[message.key] = message.line
    return found


def untranslated(root: Path) -> list[tuple[str, str, Path, str, int]]:
    """Per (unit, locale, catalogue, key, source line), the keys a translation lacks."""
    units: dict[str, dict[str, Path]] = {}
    for catalogue in catalogues(root):
        units.setdefault(unit_of(root, catalogue), {})[catalogue.stem] = catalogue
    missing = []
    for unit, locales in sorted(units.items()):
        defined = {locale: keys_of(path) for locale, path in locales.items()}
        source = defined.get(SOURCE_LOCALE)
        if source is None:
            continue
        for key, line in source.items():
            for locale, keys in sorted(defined.items()):
                if locale != SOURCE_LOCALE and key not in keys:
                    missing.append((unit, locale, locales[locale], key, line))
    return missing


def unnamed(root: Path) -> list[tuple[str, str, Path, str, int]]:
    """Per (unit, locale, catalogue, key, line), the keys a translation adds."""
    units: dict[str, dict[str, Path]] = {}
    for catalogue in catalogues(root):
        units.setdefault(unit_of(root, catalogue), {})[catalogue.stem] = catalogue
    extra = []
    for unit, locales in sorted(units.items()):
        defined = {locale: keys_of(path) for locale, path in locales.items()}
        source = defined.get(SOURCE_LOCALE)
        if source is None:
            continue
        for locale, keys in sorted(defined.items()):
            if locale == SOURCE_LOCALE:
                continue
            allowed = LOCALE_ONLY.get((unit, locale), set())
            for key, line in keys.items():
                if key not in source and key not in allowed:
                    extra.append((unit, locale, locales[locale], key, line))
    return extra


def stale_registries(root: Path) -> list[tuple[str, Path, str, str]]:
    """Per (unit, registry, what is behind, how to fix it), the generated registries a catalog left stale.

    `tilo-app` owns the file, so every difference here is one an edit of the
    catalogs left behind: the commit that edited them is the one that should
    have carried the registry. A locale its catalog set has and the registry
    does not is the one case a person adds, with `tilo-app add locale`; every
    other is `tilo-app locale sync`."""
    found = []
    for catalogue in catalogues(root):
        if catalogue.stem != SOURCE_LOCALE:
            continue
        unit = catalogue.parents[1]
        registry = unit / REGISTRY
        if not registry.is_file():
            continue
        text = registry.read_text()
        if not text.startswith(REGISTRY_HEADER):
            continue
        declaration = DECLARATION.search(text)
        registered = LOCALE.findall(declaration.group(1)) if declaration else []
        catalogs = sorted(path.stem for path in (unit / "locales").glob("*.ftl"))
        unregistered = [locale for locale in catalogs if locale not in registered]
        if unregistered:
            found.append((unit, registry,
                          f"locales/{unregistered[0]}.ftl is not registered",
                          f"tilo-app add locale {unregistered[0]}"))
            continue
        missing = [locale for locale in registered if locale not in catalogs]
        if missing:
            found.append((unit, registry,
                          f"registered locale {missing[0]!r} has no locales/{missing[0]}.ftl",
                          "tilo-app locale sync"))
    return found


def tree_texts(root: Path, revision: str, relatives: list[Path]) -> dict[Path, str]:
    """The text each of `relatives` holds in `revision`.

    One `git cat-file` for the lot, as `judged` reads a commit's own blobs, so
    a commit of many catalogues costs one process. A path `revision` does not
    hold (a catalogue the other side of a change adds) is left out, and its
    reader sees an empty catalogue."""
    wanted = [relative for relative in relatives if "\n" not in relative.as_posix()]
    if not wanted:
        return {}
    query = b"".join(
        os.fsencode(revision) + b":" + os.fsencode(relative.as_posix()) + b"\n"
        for relative in wanted
    )
    output = git(root, "cat-file", "--batch", input=query)
    texts: dict[Path, str] = {}
    offset = 0
    for relative in wanted:
        end = output.index(b"\n", offset)
        header = output[offset:end].split()
        offset = end + 1
        if len(header) != 3:
            continue
        _oid, kind, size = header
        if kind != b"blob":
            continue
        length = int(size)
        texts[relative] = output[offset : offset + length].decode("utf-8", "replace")
        offset += length + 1
    return texts


def tree_catalogues(root: Path, revision: str, units: list[Path]) -> list[Path]:
    """Every catalogue `revision` holds in `units`, relative to the root."""
    if not units:
        return []
    listing = git(root, "ls-tree", "-r", "--name-only", "-z", revision, "--",
                  *[unit.as_posix() for unit in units]).split(b"\0")
    return sorted(
        relative
        for relative in (Path(os.fsdecode(name)) for name in listing if name)
        if relative.suffix == ".ftl" and relative.parent.name == "locales"
    )


def drift_in(touched: list[Path], catalogues: list[Path],
             after: dict[Path, str], before: dict[Path, str]) -> list[str]:
    """The drift `touched` introduces, judged in what `after` and `before` hold.

    `after` is the tree the change leaves and `before` the one it finds; only
    the units of `touched` are compared. Two shapes are drift: a key `after`
    defines in a source catalogue that `before` did not and a translation lacks,
    and a key `after` adds to a translation with no source original. A key
    `after` defines twice is not a word to translate but a broken file, so it
    fails here as it does in the whole tree.
    """
    problems: list[str] = []
    for relative in touched:
        first: dict[str, int] = {}
        for message in messages(after.get(relative, "")):
            if message.key in first:
                problems.append(
                    f"{relative.as_posix()}:{message.line}: {message.key} is defined again; "
                    f"line {first[message.key]} already defines it"
                )
            else:
                first[message.key] = message.line

    for unit in sorted({relative.parents[1] for relative in touched}):
        files = [catalogue for catalogue in catalogues if catalogue.parents[1] == unit]
        now = {catalogue.stem: keys_in(after.get(catalogue, "")) for catalogue in files}
        was = {catalogue.stem: keys_in(before.get(catalogue, "")) for catalogue in files}
        source = now.get(SOURCE_LOCALE)
        if source is None:
            continue
        source_name = f"{unit.as_posix()}/locales/{SOURCE_LOCALE}.ftl"
        for key, line in sorted(source.items(), key=lambda item: item[1]):
            if key in was.get(SOURCE_LOCALE, {}):
                continue
            for locale, keys in sorted(now.items()):
                if locale != SOURCE_LOCALE and key not in keys:
                    problems.append(f"{source_name}:{line}: {key} has no {locale} text")
        for locale, keys in sorted(now.items()):
            if locale == SOURCE_LOCALE:
                continue
            allowed = LOCALE_ONLY.get((unit.as_posix(), locale), set())
            name = f"{unit.as_posix()}/locales/{locale}.ftl"
            for key, line in sorted(keys.items(), key=lambda item: item[1]):
                if key in was.get(locale, {}):
                    continue
                if key not in source and key not in allowed:
                    problems.append(f"{name}:{line}: {key} has no {SOURCE_LOCALE} text")
    return problems


def staged_drift(root: Path) -> list[str]:
    """The drift a commit introduces in the catalogues it stages, in path order.

    Only the units whose `locales/*.ftl` files the commit stages are judged,
    and each is judged as the commit leaves it: its index blob where it is
    staged, HEAD where it is not. What the commit leaves alone was already
    judged by CI.
    """
    staged = judged(root, staged=True)
    touched = [
        relative
        for relative in staged.files(Path("."), suffixes=(".ftl",))
        if relative.parent.name == "locales"
    ]
    if not touched:
        return []
    units = sorted({relative.parents[1] for relative in touched})
    catalogues = sorted({
        catalogue.relative_to(root)
        for unit in units
        for catalogue in (root / unit / "locales").glob("*.ftl")
    })
    after: dict[Path, str] = {
        catalogue: staged.read(catalogue)
        for catalogue in catalogues
        if staged.is_staged(catalogue)
    }
    after.update(tree_texts(root, "HEAD", [c for c in catalogues if c not in after]))
    before = tree_texts(root, "HEAD", catalogues)
    return drift_in(touched, catalogues, after, before)


def range_drift(root: Path, base: str, head: str) -> list[str]:
    """The drift a range introduces in the catalogues it changes, in path order.

    A cherry-pick or a rebase writes commits no hook sees its `--staged` run
    through, so a push judges the range as one change: only the units whose
    `locales/*.ftl` files differ between `base` and `head` are judged, each as
    `head` leaves it against `base`. What the range leaves alone was judged by
    CI, and a key a commit of the range added and a later one fixed is not
    drift.
    """
    changed = git(root, "diff", "--name-only", "-z", "--diff-filter=ACMRT",
                  f"{base}..{head}", "--").split(b"\0")
    touched = [
        relative
        for relative in (Path(os.fsdecode(name)) for name in changed if name)
        if relative.suffix == ".ftl" and relative.parent.name == "locales"
    ]
    if not touched:
        return []
    units = sorted({relative.parents[1] for relative in touched})
    catalogues = sorted(
        set(tree_catalogues(root, head, units)) | set(tree_catalogues(root, base, units))
    )
    after = tree_texts(root, head, catalogues)
    before = tree_texts(root, base, catalogues)
    return drift_in(sorted(touched), catalogues, after, before)


def named(root: Path, path: Path) -> str:
    return path.relative_to(root).as_posix()


def report_change(problems: list[str], subject: str) -> int:
    """Print the drift a change adds and refuse it; `subject` names the change."""
    for problem in problems:
        print(problem)
    if problems:
        print(f"{len(problems)} keys {subject} adds are untranslated or unnamed; a "
              "catalogue is translated whole or it reads in two languages at once",
              file=sys.stderr)
        return 1
    print(f"catalogue coverage: {subject} adds no key a translation lacks", file=sys.stderr)
    return 0


def main(argv: list[str]) -> int:
    arguments = argv[1:]
    if arguments[:1] == ["--range"] and len(arguments) == 2:
        base, _, head = arguments[1].partition("..")
        if not base or not head:
            print(__doc__.split("\n\n")[-1].strip(), file=sys.stderr)
            return 2
        return report_change(range_drift(ROOT, base, head), "this range")
    if arguments not in ([], ["--list"], [STAGED_FLAG]):
        print(__doc__.split("\n\n")[-1].strip(), file=sys.stderr)
        return 2
    if arguments == [STAGED_FLAG]:
        return report_change(staged_drift(ROOT), "this commit")
    missing = untranslated(ROOT)
    extra = unnamed(ROOT)
    twice = duplicated(ROOT)
    stale = stale_registries(ROOT)
    listing = argv[1:] == ["--list"]
    for unit, locale, _, key, line in missing:
        if listing:
            print(unit, locale, key)
        else:
            print(f"{unit}/locales/{SOURCE_LOCALE}.ftl:{line}: {key} has no {locale} text")
    for unit, locale, _, key, line in extra:
        if listing:
            print(unit, locale, key)
        else:
            print(f"{unit}/locales/{locale}.ftl:{line}: {key} has no {SOURCE_LOCALE} text")
    for catalogue, key, first, line in twice:
        print(f"{named(ROOT, catalogue)}:{line}: {key} is defined again; line {first} "
              "already defines it", file=sys.stderr)
    for _, registry, reason, fix in stale:
        print(f"{named(ROOT, registry)}: {reason}; run `{fix}`", file=sys.stderr)
    if twice:
        print(f"{len(twice)} keys are defined twice; a catalogue holds one message per key",
              file=sys.stderr)
        return 1
    if stale:
        print(f"{len(stale)} generated locale "
              f"registr{'y is' if len(stale) == 1 else 'ies are'} behind its source catalogue",
              file=sys.stderr)
        return 1
    if listing:
        return 0
    if missing or extra:
        print(f"{len(missing) + len(extra)} keys are untranslated or unnamed; a catalogue is "
              "translated whole or it reads in two languages at once", file=sys.stderr)
        return 1
    print("catalogue coverage OK (every translation says every word of its source, no more, "
          "and every generated registry registers its catalogs)", file=sys.stderr)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
