#!/usr/bin/env python3
"""Keep the ``shell`` crate's layers from growing new upward edges.

``crates/session/shell`` is one crate whose modules can all ``use`` each
other, and it is being split into smaller crates one subsystem at a time.
Every extraction first has to undo the edges that tie the subsystem to the
compositor, so this check stops new ones while the split proceeds. It guards
three things, all from source text and manifests (nothing is compiled, and
``cargo`` is not run):

* **Service modules stay below the compositor.** The workspace model,
  persistence, the collaboration broker, the network bridge, the identity
  broker and the compositor-free runtime host (``SERVICE_MODULES``) must not
  name the compositor, the chrome/launch/overlay modules above them, or a
  renderer/windowing crate (``FORBIDDEN_*``). Paths are read from ``use``
  trees (grouped ``use crate::{compositor::state::State, shell::frame}``
  included) and from inline paths; ``self::``/``super::`` are resolved against
  the file's module and any inline ``mod`` blocks. Items under
  ``#[cfg(test)]``/``#[cfg(all(test, …))]`` and files named ``tests.rs`` or
  ``*_tests.rs`` (or under a ``*_tests/`` directory) are skipped: test
  fixtures may build a compositor state.
  Glob imports and renamed modules are not followed.
* **Extracted crates do not depend back up.** A crate carved out of the shell
  (``[extracted].crates``) must not reach ``shell``, the toolkit, the drawn
  desktop or a renderer/windowing crate (``EXTRACTED_FORBIDDEN``) through its
  own dependencies or any workspace crate it depends on. Normal and build
  dependencies of every target count, optional ones included; dev-dependencies
  do not. Registry crates are leaves: what a third-party crate pulls in is not
  followed. A reached crate needs a reasoned ``[extracted.allow]`` entry.
* **The shell's graph does not grow unnoticed.** Every workspace crate with a
  non-dev dependency on ``shell`` is listed with its reason
  (``[shell_dependants]``), and so is every direct non-dev dependency of
  ``shell``: those that predate the check in
  ``[shell_dependencies].grandfathered``, later additions in
  ``[shell_dependencies.added]`` with a reason made in review.

The baseline (``shell_layers_baseline.toml``) only shrinks: an entry the code
no longer needs fails as stale, so removing an edge or a dependency also
removes its line. ``--write-baseline`` drops stale entries for you; it never
records a new edge or dependency, except on the first run, when there is no
baseline yet and the current state is recorded.
"""

