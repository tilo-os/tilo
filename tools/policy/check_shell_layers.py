class BaselineError(Exception):
    pass


@dataclass(frozen=True)
class Edge:
    file: str  # relative to the shell crate
    target: str
    line: int


# --- Reading Rust source -----------------------------------------------------


def item_end(text: str, start: int) -> int:
    """Offset past the item starting at ``start``: its body block or its ``;``."""
    i, depth = start, 0
    while i < len(text):
        c = text[i]
        if c == "#" and depth == 0:
            bracket = text.find("[", i)
            if bracket >= 0 and not text[i + 1 : bracket].strip(" \t\n!"):
                i = matching(text, bracket)
                continue
        if c in "([":
            depth += 1
        elif c in ")]":
            depth -= 1
        elif c == ";" and depth == 0:
            return i + 1
        elif c == "{" and depth == 0:
            return matching(text, i)
        i += 1
    return i


def module_path(relative: str) -> list[str]:
    """``src/shell/state/apply.rs`` -> ``['crate', 'shell', 'state', 'apply']``."""
    parts = Path(relative).with_suffix("").parts[1:]  # drop "src"
    if parts and parts[-1] == "mod":
        parts = parts[:-1]
    if parts in (("lib",), ("main",)):
        parts = ()
    return ["crate", *parts]


def inline_modules(text: str) -> list[tuple[int, int, str]]:
    return [
        (match.end() - 1, matching(text, match.end() - 1), match.group(1))
        for match in INLINE_MOD.finditer(text)
    ]


def module_at(base: list[str], spans: list[tuple[int, int, str]], offset: int) -> list[str]:
    return base + [name for start, end, name in spans if start < offset < end]


def resolve(segments: list[str], module: list[str]) -> list[str] | None:
    """An absolute path for ``segments`` used inside ``module``, or None."""
    if not segments:
        return None
    head = segments[0]
    if head == "crate" or head in FORBIDDEN_CRATES:
        return segments
    if head == "self":
        return module + segments[1:]
    if head == "super":
        resolved = list(module)
        rest = list(segments)
        while rest and rest[0] == "super":
            if len(resolved) <= 1:
                return None
            resolved.pop()
            rest.pop(0)
        return resolved + rest
    return None


def use_paths(tree: str) -> list[list[str]]:
    """Every path a ``use`` tree names: ``a::{b, c::d}`` -> ``[a, b]``, ``[a, c, d]``."""
    tokens = USE_TOKEN.findall(tree)
    position = 0

    def parse(prefix: list[str]) -> list[list[str]]:
        nonlocal position
        segments = list(prefix)
        while position < len(tokens):
            token = tokens[position]
            if token == "::":
                position += 1
            elif token == "{":
                position += 1
                found: list[list[str]] = []
                while position < len(tokens) and tokens[position] != "}":
                    if tokens[position] == ",":
                        position += 1
                        continue
                    found += parse(segments)
                position += 1  # "}"
                return found
            elif token == "*":
                position += 1
                return [segments]
            elif token in (",", "}"):
                break
            elif token == "as":
                position += 2  # the alias
                break
            else:
                if token != "self" or not segments:
                    segments.append(token)
                position += 1
        return [segments]

    return [path for path in parse([]) if path]


def referenced_paths(text: str, relative: str) -> list[tuple[list[str], int]]:
    """Absolute paths referenced in production code, with their offsets."""
    clean = code_only(text)
    if CFG_TEST_INNER.match(clean):
        return []
    source = blank_test_items(clean)
    base = module_path(relative)
    spans = inline_modules(source)
    found: list[tuple[list[str], int]] = []
    chars = list(source)
    for match in USE.finditer(source):
        end = item_end(source, match.end())
        module = module_at(base, spans, match.start())
        for path in use_paths(source[match.end() : end].rstrip(";")):
            if (absolute := resolve(path, module)) is not None:
                found.append((absolute, match.start()))
        for k in range(match.start(), end):
            if chars[k] != "\n":
                chars[k] = " "
    remaining = "".join(chars)
    for match in INLINE_PATH.finditer(remaining):
        segments = [match.group(1), *re.findall(IDENT, match.group(2))]
        module = module_at(base, spans, match.start())
        if (absolute := resolve(segments, module)) is not None:
            found.append((absolute, match.start(1)))
    return found


def forbidden_target(path: list[str]) -> str | None:
    if path[0] in FORBIDDEN_CRATES:
        return path[0]
    for tree in FORBIDDEN_TREES:
        if tuple(path[: len(tree)]) == tree:
            return "::".join(path[: len(tree) + 1])
    if len(path) >= 3 and path[:2] == ["crate", "shell"] and path[2] in FORBIDDEN_SHELL_MODULES:
        return "::".join(path[:3])
    return None


def is_service(relative: str) -> bool:
    if relative in SERVICE_EXEMPT:
        return False
    stems = [Path(part).stem for part in Path(relative).parts]
    if any(stem == "tests" or stem.endswith("_tests") for stem in stems):
        return False
    parents = [parent.as_posix() for parent in Path(relative).parents]
    for pattern in SERVICE_MODULES:
        if pattern.endswith("/"):
            if any(fnmatch.fnmatchcase(parent, pattern.rstrip("/")) for parent in parents):
                return True
        elif fnmatch.fnmatchcase(relative, pattern):
            return True
    return False


def service_files(root: Path = ROOT) -> list[Path]:
    shell = root / SHELL
    return [
        path for path in sorted((shell / "src").rglob("*.rs"))
        if is_service(path.relative_to(shell).as_posix())
    ]


def module_edges(root: Path = ROOT) -> list[Edge]:
    shell = root / SHELL
    edges: dict[tuple[str, str], Edge] = {}
    for path in service_files(root):
        relative = path.relative_to(shell).as_posix()
        text = path.read_text(encoding="utf-8")
        for segments, offset in referenced_paths(text, relative):
            target = forbidden_target(segments)
            if target is None:
                continue
            key = (relative, target)
            if key not in edges:
                edges[key] = Edge(relative, target, text.count("\n", 0, offset) + 1)
    return sorted(edges.values(), key=lambda edge: (edge.file, edge.target))


# --- Reading manifests -------------------------------------------------------


def dependency_tables(manifest: dict) -> list[dict]:
    """Normal and build dependency tables, every target included."""
    kinds = ("dependencies", "build-dependencies")
    tables = [manifest.get(kind, {}) for kind in kinds]
    for target in manifest.get("target", {}).values():
        tables += [target.get(kind, {}) for kind in kinds]
    return tables


@dataclass(frozen=True)
class Workspace:
    root: Path
    manifests: dict[str, dict]  # package name -> manifest
    shared: dict  # [workspace.dependencies]

    def package_of(self, key: str, spec: object) -> str:
        if isinstance(spec, dict):
            if spec.get("workspace"):
                shared = self.shared.get(key, {})
                if isinstance(shared, dict) and "package" in shared:
                    return shared["package"]
                return key
            return spec.get("package", key)
        return key

    def dependencies(self, package: str) -> set[str]:
        """Package names ``package`` depends on (normal and build, any target)."""
        names = set()
        for table in dependency_tables(self.manifests[package]):
            for key, spec in table.items():
                names.add(self.package_of(key, spec))
        return names - IGNORED_PACKAGES

    def reached(self, package: str) -> dict[str, list[str]]:
        """Every package reached through workspace crates, with one path to it."""
        paths: dict[str, list[str]] = {package: [package]}
        queue = [package]
        while queue:
            current = queue.pop(0)
            for dependency in sorted(self.dependencies(current)):
                if dependency in paths:
                    continue
                paths[dependency] = paths[current] + [dependency]
                if dependency in self.manifests:
                    queue.append(dependency)
        del paths[package]
        return paths


def load_workspace(root: Path = ROOT) -> Workspace:
    with (root / "Cargo.toml").open("rb") as handle:
        top = tomllib.load(handle)
    workspace = top.get("workspace", {})
    manifests = {}
    for member in workspace.get("members", []):
        path = root / member / "Cargo.toml"
        if not path.is_file():
            continue
        with path.open("rb") as handle:
            manifest = tomllib.load(handle)
        if "package" in manifest:
            manifests[manifest["package"]["name"]] = manifest
    return Workspace(root, manifests, workspace.get("dependencies", {}))


# --- Baseline ----------------------------------------------------------------


@dataclass
class Baseline:
    modules: dict[str, list[str]]
    extracted: list[str]
    extracted_allow: dict[str, dict[str, str]]
    shell_dependants: dict[str, str]
    grandfathered: list[str]
    added: dict[str, str]


def load_baseline(path: Path = BASELINE) -> Baseline | None:
    if not path.is_file():
        return None
    try:
        with path.open("rb") as handle:
            data = tomllib.load(handle)
    except tomllib.TOMLDecodeError as error:
        raise BaselineError(f"{path}: {error}") from error
    extracted = data.get("extracted", {})
    dependencies = data.get("shell_dependencies", {})
    baseline = Baseline(
        modules={file: list(targets) for file, targets in data.get("modules", {}).items()},
        extracted=list(extracted.get("crates", [])),
        extracted_allow={
            crate: dict(allowed) for crate, allowed in extracted.get("allow", {}).items()
        },
        shell_dependants=dict(data.get("shell_dependants", {})),
        grandfathered=list(dependencies.get("grandfathered", [])),
        added=dict(dependencies.get("added", {})),
    )
    reasons = [
        *(f"[shell_dependants] {name}" for name, why in baseline.shell_dependants.items()
          if not str(why).strip()),
        *(f"[shell_dependencies.added] {name}" for name, why in baseline.added.items()
          if not str(why).strip()),
        *(f"[extracted.allow.{crate}] {name}" for crate, allowed in baseline.extracted_allow.items()
          for name, why in allowed.items() if not str(why).strip()),
    ]
    if reasons:
        raise BaselineError(f"{path}: entries need a reason: {', '.join(reasons)}")
    both = sorted(set(baseline.grandfathered) & set(baseline.added))
    if both:
        raise BaselineError(f"{path}: listed as grandfathered and added: {', '.join(both)}")
    return baseline


def quote(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def string_list(values: list[str], indent: str = "    ") -> str:
    if not values:
        return "[]"
    return "[\n" + "".join(f"{indent}{quote(value)},\n" for value in values) + "]"


def group_comment(file: str) -> str | None:
    for prefix, comment in MODULE_GROUPS:
        if file.startswith(prefix):
            return comment
    return None


def render_baseline(baseline: Baseline) -> str:
    lines = [
        "# Layering of the `shell` crate split, checked by tools/policy/check_shell_layers.py",
        f"# ({POLICY}). Every list only shrinks: an entry the code no longer needs",
        "# fails as stale, and a new edge or dependency fails until it is removed or",
        "# argued for in review. `check_shell_layers.py --write-baseline` drops stale",
        "# entries; it never adds one.",
        "",
        "# Service modules (paths relative to crates/session/shell) and the compositor,",
        "# chrome or renderer paths they still reach.",
        "[modules]",
    ]
    order = {prefix: index for index, (prefix, _) in enumerate(MODULE_GROUPS)}

    def rank(file: str) -> tuple[int, str]:
        for prefix, index in order.items():
            if file.startswith(prefix):
                return index, file
        return len(order), file

    previous = None
    for file in sorted(baseline.modules, key=rank):
        comment = group_comment(file)
        if comment != previous and comment is not None:
            lines += ["", *(f"# {line}" for line in wrap(comment))]
            previous = comment
        lines.append(f"{quote(file)} = {string_list(sorted(baseline.modules[file]))}")
    lines += [
        "",
        "# Crates carved out of the shell. They must not reach the shell, the toolkit,",
        "# the drawn desktop or a renderer through any workspace dependency.",
        "[extracted]",
        f"crates = {string_list(sorted(baseline.extracted))}",
        "",
        "# What an extracted crate may reach anyway, and why.",
        "[extracted.allow]",
    ]
    for crate in sorted(baseline.extracted_allow):
        allowed = baseline.extracted_allow[crate]
        entries = ", ".join(f"{quote(name)} = {quote(allowed[name])}" for name in sorted(allowed))
        lines.append(f"{quote(crate)} = {{ {entries} }}")
    lines += [
        "",
        "# Workspace crates with a non-dev dependency on the shell, and why.",
        "[shell_dependants]",
        *(f"{quote(name)} = {quote(why)}" for name, why in sorted(baseline.shell_dependants.items())),
        "",
        "# The shell's direct normal and build dependencies (package names). Remove a line",
        "# when a dependency goes; a new one is an [shell_dependencies.added] entry with",
        "# its reason, or belongs in a smaller crate.",
        "[shell_dependencies]",
        f"grandfathered = {string_list(sorted(baseline.grandfathered))}",
        "",
        "[shell_dependencies.added]",
        *(f"{quote(name)} = {quote(why)}" for name, why in sorted(baseline.added.items())),
    ]
    return "\n".join(lines) + "\n"


def wrap(text: str, width: int = 86) -> list[str]:
    lines, current = [], ""
    for word in text.split():
        if current and len(current) + 1 + len(word) > width:
            lines.append(current)
            current = word
        else:
            current = f"{current} {word}".strip()
    return lines + [current] if current else lines


# --- The check ---------------------------------------------------------------


@dataclass
class Observed:
    edges: list[Edge]
    shell_dependants: set[str]
    shell_dependencies: set[str]
    extracted_reached: dict[str, dict[str, list[str]]]


def observe(root: Path, extracted: list[str]) -> tuple[Observed, list[str]]:
    workspace = load_workspace(root)
    problems = []
    if SHELL_PACKAGE not in workspace.manifests:
        problems.append(f"the workspace has no `{SHELL_PACKAGE}` package; this check cannot see it")
    dependants = {
        name for name in workspace.manifests
        if name != SHELL_PACKAGE and SHELL_PACKAGE in workspace.dependencies(name)
    }
    shell_dependencies = (
        workspace.dependencies(SHELL_PACKAGE) if SHELL_PACKAGE in workspace.manifests else set()
    )
    reached = {}
    for crate in extracted:
        if crate not in workspace.manifests:
            problems.append(f"[extracted] lists {crate}, which is not a workspace package")
            continue
        reached[crate] = {
            name: path for name, path in workspace.reached(crate).items()
            if name in EXTRACTED_FORBIDDEN
        }
    if not service_files(root):
        problems.append(f"no service module found under {SHELL}/src; this check cannot see them")
    edges = module_edges(root)
    return Observed(edges, dependants, shell_dependencies, reached), problems


def check(root: Path = ROOT, baseline_path: Path = BASELINE) -> list[str]:
    """Every violation and stale baseline entry, as a printable line."""
    baseline = load_baseline(baseline_path)
    if baseline is None:
        return [f"{baseline_path} is missing; run check_shell_layers.py --write-baseline"]
    observed, problems = observe(root, baseline.extracted)
    shown = baseline_path.relative_to(root).as_posix() if baseline_path.is_relative_to(root) \
        else str(baseline_path)

    found = {(edge.file, edge.target): edge for edge in observed.edges}
    allowed = {(file, target) for file, targets in baseline.modules.items() for target in targets}
    for key in sorted(set(found) - allowed):
        edge = found[key]
        problems.append(
            f"{SHELL}/{edge.file}:{edge.line}: a service module reaches {edge.target}; "
            "move the code that needs it above the service layer or pass it in through a trait"
        )
    for file, target in sorted(allowed - set(found)):
        problems.append(
            f"{SHELL}/{file} no longer reaches {target}: remove it from [modules] in {shown}"
        )

    for crate, reached in sorted(observed.extracted_reached.items()):
        permitted = baseline.extracted_allow.get(crate, {})
        for name, path in sorted(reached.items()):
            if name not in permitted:
                problems.append(
                    f"extracted crate {crate} reaches {name} ({' -> '.join(path)}); "
                    "a crate carved out of the shell must not depend back up"
                )
        for name in sorted(set(permitted) - set(reached)):
            problems.append(
                f"extracted crate {crate} no longer reaches {name}: "
                f"remove it from [extracted.allow] in {shown}"
            )
    for crate in sorted(set(baseline.extracted_allow) - set(baseline.extracted)):
        problems.append(f"[extracted.allow] names {crate}, which [extracted] does not list")

    for name in sorted(observed.shell_dependants - set(baseline.shell_dependants)):
        problems.append(
            f"{name} depends on {SHELL_PACKAGE}; depend on the crate that owns what you need "
            f"(or argue for it as a [shell_dependants] entry in {shown})"
        )
    for name in sorted(set(baseline.shell_dependants) - observed.shell_dependants):
        problems.append(
            f"{name} no longer depends on {SHELL_PACKAGE}: remove it from [shell_dependants] in {shown}"
        )

    listed = set(baseline.grandfathered) | set(baseline.added)
    for name in sorted(observed.shell_dependencies - listed):
        problems.append(
            f"{SHELL_PACKAGE} gains the dependency {name}; put the code in a smaller crate, or "
            f"argue for it as a [shell_dependencies.added] entry in {shown}"
        )
    for name in sorted(listed - observed.shell_dependencies):
        problems.append(
            f"{SHELL_PACKAGE} no longer depends on {name}: remove it from [shell_dependencies] in {shown}"
        )
    return problems


def write_baseline(root: Path = ROOT, baseline_path: Path = BASELINE) -> Baseline:
    """Drop stale entries; on the first run, record the current state."""
    previous = load_baseline(baseline_path)
    extracted = previous.extracted if previous else []
    observed, _ = observe(root, extracted)
    current: dict[str, list[str]] = {}
    for edge in observed.edges:
        current.setdefault(edge.file, []).append(edge.target)
    if previous is None:
        baseline = Baseline(current, [], {}, {name: "predates the layering check"
                                              for name in observed.shell_dependants},
                            sorted(observed.shell_dependencies), {})
    else:
        modules = {
            file: [target for target in targets if target in current.get(file, [])]
            for file, targets in previous.modules.items()
        }
        baseline = Baseline(
            modules={file: targets for file, targets in modules.items() if targets},
            extracted=previous.extracted,
            extracted_allow={
                crate: {
                    name: why for name, why in allowed.items()
                    if name in observed.extracted_reached.get(crate, {})
                }
                for crate, allowed in previous.extracted_allow.items()
            },
            shell_dependants={
                name: why for name, why in previous.shell_dependants.items()
                if name in observed.shell_dependants
            },
            grandfathered=[
                name for name in previous.grandfathered if name in observed.shell_dependencies
            ],
            added={
                name: why for name, why in previous.added.items()
                if name in observed.shell_dependencies
            },
        )
        baseline.extracted_allow = {
            crate: allowed for crate, allowed in baseline.extracted_allow.items() if allowed
        }
    baseline_path.write_text(render_baseline(baseline), encoding="utf-8")
    return baseline


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--write-baseline",
        action="store_true",
        help="drop stale baseline entries (records the current state if there is no baseline)",
    )
    args = parser.parse_args(argv)
    try:
        if args.write_baseline:
            baseline = write_baseline()
            count = sum(len(targets) for targets in baseline.modules.values())
            print(f"Wrote {BASELINE.relative_to(ROOT)}: {count} module edges.")
            return 0
        problems = check()
        baseline = load_baseline()
    except BaselineError as error:
        print(f"  {error}")
        return 1
    for problem in problems:
        print(f"  {problem}")
    if problems:
        print(f"The shell's layers only shrink ({POLICY}).")
        return 1
    assert baseline is not None
    edges = sum(len(targets) for targets in baseline.modules.values())
    dependencies = len(baseline.grandfathered) + len(baseline.added)
    print(
        f"Shell layers: {edges} baselined service-module edges, "
        f"{len(baseline.extracted)} extracted crates clean, "
        f"{dependencies} direct shell dependencies; none new."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
