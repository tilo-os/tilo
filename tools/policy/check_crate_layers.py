#!/usr/bin/env python3
"""Keep the crates that own a boundary reachable only through their API.

``crate_layers.toml`` names a crate whose use is a boundary, why it is one,
and which packages may depend on it, each with the reason it may. From that,
and from ``cargo metadata`` and the ``use`` paths of the tree, three kinds of
finding follow:

* a workspace crate that declares a dependency on a rule's crate and that the
  rule does not allow. Normal, build and dev dependencies all count, optional
  ones included: a dev-dependency also compiles the crate into that package's
  tests.
* an allowance marked ``tests`` whose package depends on the crate outside its
  dev-dependencies. Such a package may read the crate back in its tests only;
  its manifest is recorded separately from the edge, so that a package whose
  test use is recorded cannot quietly grow a production one.
* an allowance with ``paths`` whose package names the crate in a file outside
  them: the session's compositor code may speak smithay while the rest of the
  shell may not.

``workspace-unify`` is not a package anyone writes: ``cargo hakari``
generates it and it depends on every workspace crate by construction.

What breaks a rule today is recorded in ``crate_layers_baseline.toml`` --
edges and files being removed -- and the list only shrinks: a finding the
baseline does not record fails, and so does an entry the code no longer
needs. ``--write-baseline`` drops stale entries, and records the current
state when there is no baseline yet; it never records a new finding.
``--list`` prints the findings alone.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tomllib
from dataclasses import dataclass
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from rust_source import is_test_file, lex, production_source  # noqa: E402


ROOT = Path(__file__).resolve().parents[2]
RULES = Path("tools/policy/crate_layers.toml")
BASELINE = Path("tools/policy/crate_layers_baseline.toml")
# Generated by `cargo hakari`, which gives it an edge to every workspace crate.
GENERATED = frozenset({"workspace-unify"})
KINDS = {None: "dependency", "dev": "dev-dependency", "build": "build-dependency"}
HEADER = """\
# Edges and `use` paths that break a rule in crate_layers.toml and are still
# there. The list only shrinks: an entry the code no longer needs fails as
# stale, and anything it does not record fails. `check_crate_layers.py
# --write-baseline` drops stale entries; it never records a new one.
"""


@dataclass(frozen=True)
class Allowance:
    package: str
    why: str
    tests: bool = False
    paths: tuple[str, ...] = ()


@dataclass(frozen=True)
class Rule:
    crate: str
    reason: str
    allow: tuple[Allowance, ...]


@dataclass(frozen=True)
class Package:
    """A workspace crate: its manifest and the dependencies it declares."""

    name: str
    manifest: str
    # The crate's root, relative to the tree.
    root: str
    # Crate name -> KINDS values, for every dependency of any target.
    dependencies: dict[str, frozenset[str]]


@dataclass(frozen=True)
class Finding:
    rule: str
    package: str
    # The manifest, or the source file that names the crate.
    file: str
    message: str
    line: int | None = None
    # The source file, when the finding is a `use` path rather than a dependency.
    source: str | None = None

    @property
    def key(self) -> tuple[str, str, str]:
        return (self.rule, self.package, self.source or "")

    def __str__(self) -> str:
        where = self.file if self.line is None else f"{self.file}:{self.line}"
        return f"{where}: {self.message}"


@dataclass(frozen=True)
class Baseline:
    # Every recorded key, in the order the file lists them, with its block.
    blocks: dict[tuple[str, str, str], str]
    header: str

    @property
    def keys(self) -> frozenset[tuple[str, str, str]]:
        return frozenset(self.blocks)


def load_rules(path: Path) -> list[Rule]:
    data = tomllib.loads(path.read_text(encoding="utf-8"))
    rules = []
    for entry in data.get("rule", []):
        unknown = set(entry) - {"crate", "reason", "allow"}
        if unknown:
            raise ValueError(f"{path}: rule {entry.get('crate')!r} has unknown fields {sorted(unknown)}")
        allow = []
        for allowed in entry.get("allow", []):
            unknown = set(allowed) - {"package", "why", "tests", "paths"}
            if unknown:
                raise ValueError(
                    f"{path}: rule {entry['crate']!r} allows {allowed.get('package')!r} "
                    f"with unknown fields {sorted(unknown)}"
                )
            paths = tuple(allowed.get("paths", ()))
            for prefix in paths:
                if not prefix.endswith("/"):
                    raise ValueError(
                        f"{path}: rule {entry['crate']!r} allows {allowed['package']!r} "
                        f"at {prefix!r}, which is not a directory ending in '/'"
                    )
            allow.append(Allowance(allowed["package"], allowed["why"], bool(allowed.get("tests")), paths))
        for field in (entry["reason"], *(allowed.why for allowed in allow)):
            if not field.strip():
                raise ValueError(f"{path}: rule {entry['crate']!r} has an empty reason")
        rules.append(Rule(entry["crate"], entry["reason"], tuple(allow)))
    names = [rule.crate for rule in rules]
    if len(names) != len(set(names)):
        raise ValueError(f"{path}: two rules name the same crate")
    return rules


def workspace(root: Path) -> list[Package]:
    result = subprocess.run(
        ["cargo", "metadata", "--locked", "--format-version", "1", "--no-deps"],
        cwd=root,
        capture_output=True,
        text=True,
        check=False,
    )
    if result.returncode != 0:
        raise RuntimeError(f"cargo metadata failed:\n{result.stderr}")
    packages = []
    for package in json.loads(result.stdout)["packages"]:
        manifest = Path(package["manifest_path"])
        dependencies: dict[str, set[str]] = {}
        for dependency in package["dependencies"]:
            dependencies.setdefault(dependency["name"], set()).add(KINDS[dependency["kind"]])
        packages.append(
            Package(
                name=package["name"],
                manifest=manifest.relative_to(root).as_posix(),
                root=manifest.parent.relative_to(root).as_posix(),
                dependencies={name: frozenset(kinds) for name, kinds in dependencies.items()},
            )
        )
    return packages


def named(code: str, ident: str) -> list[int]:
    """The lines of the lexed `code` that name `ident` as a path root."""
    pattern = re.compile(rf"(?<![\w:])(?:::)?{re.escape(ident)}\s*::")
    return [code.count("\n", 0, match.start()) + 1 for match in pattern.finditer(code)]


def source_findings(rule: Rule, package: Package, allowance: Allowance, root: Path) -> list[Finding]:
    """The production files of `package` that name the crate outside the allowance's paths.

    Test files and items under ``#[cfg(test)]`` are exempt, as in the other
    layering checks: a fixture may hold what production code may not.
    """
    ident = rule.crate.replace("-", "_")
    found = []
    for path in sorted((root / package.root).rglob("*.rs")):
        relative = path.relative_to(root)
        if "target" in path.relative_to(root / package.root).parts or is_test_file(relative):
            continue
        posix = relative.as_posix()
        within = posix[len(package.root) + 1 :]
        if any(within.startswith(prefix) for prefix in allowance.paths):
            continue
        source, _ = lex(production_source(path.read_text(encoding="utf-8", errors="replace")))
        lines = named(source, ident)
        if not lines:
            continue
        found.append(
            Finding(
                rule.crate,
                package.name,
                posix,
                f"{package.name} names {rule.crate} here; it may name it only in "
                f"{', '.join(allowance.paths)} ({allowance.why})",
                lines[0],
                within,
            )
        )
    return found


def violations(rules: list[Rule], packages: list[Package], root: Path = ROOT) -> list[Finding]:
    found = []
    by_name = {package.name: package for package in packages}
    for rule in rules:
        allowed = {allowance.package: allowance for allowance in rule.allow}
        for name, allowance in sorted(allowed.items()):
            if name not in by_name:
                raise ValueError(
                    f"{RULES.as_posix()}: rule {rule.crate!r} allows {name!r}, which is no workspace crate"
                )
            if rule.crate not in by_name[name].dependencies:
                found.append(
                    Finding(
                        rule.crate,
                        name,
                        RULES.as_posix(),
                        f"{name} is allowed to depend on {rule.crate} ({allowance.why}), "
                        "but it does not; drop the allowance",
                    )
                )
        for package in packages:
            if package.name in GENERATED or rule.crate not in package.dependencies:
                continue
            kinds = package.dependencies[rule.crate]
            production = sorted(kinds - {"dev-dependency"})
            # A production edge is recorded against the manifest, a dev-only
            # one without a path: an edge recorded for a package's tests that
            # grows into production fails instead of passing quietly.
            source = "Cargo.toml" if production else None
            allowance = allowed.get(package.name)
            if allowance is None:
                with_ = f" a {' and a '.join(production)}" if production else " a dev-dependency"
                found.append(
                    Finding(
                        rule.crate,
                        package.name,
                        package.manifest,
                        f"{package.name} takes{with_} on {rule.crate}: {rule.reason}",
                        None,
                        source,
                    )
                )
                continue
            if allowance.tests and production:
                found.append(
                    Finding(
                        rule.crate,
                        package.name,
                        package.manifest,
                        f"{package.name} has a {' and a '.join(production)} on {rule.crate}; "
                        f"only its tests may ({allowance.why})",
                        None,
                        "Cargo.toml",
                    )
                )
            if allowance.paths:
                found.extend(source_findings(rule, package, allowance, root))
    return found


def load_baseline(path: Path) -> Baseline:
    """The file's entries with the comments that introduce each of them."""
    if not path.exists():
        return Baseline({}, HEADER)
    lines = path.read_text(encoding="utf-8").splitlines()
    starts = [index for index, line in enumerate(lines) if line.startswith("[[violation]]")]
    if not starts:
        return Baseline({}, "\n".join(lines).rstrip("\n") + "\n")
    # The comment lines directly above the first entry introduce it, not the file.
    begin = starts[0]
    while begin > 0 and lines[begin - 1].lstrip().startswith("#"):
        begin -= 1
    blocks: dict[tuple[str, str, str], str] = {}
    pending: list[str] = lines[begin : starts[0]]
    for position, start in enumerate(starts):
        end = starts[position + 1] if position + 1 < len(starts) else len(lines)
        # The comment lines directly above the next entry introduce it, not this one.
        tail = end
        while tail - 1 > start and lines[tail - 1].lstrip().startswith("#"):
            tail -= 1
        block = [line for line in [*pending, *lines[start:tail]] if line.strip()]
        pending = lines[tail:end]
        if not block:
            continue
        entry = tomllib.loads("\n".join(block))["violation"][0]
        blocks[(entry["rule"], entry["package"], entry.get("path", ""))] = "\n".join(block) + "\n"
    return Baseline(blocks, "\n".join(lines[:begin]).rstrip("\n") + "\n")


def entry_block(key: tuple[str, str, str]) -> str:
    rule, package, path = key
    block = f'[[violation]]\nrule = "{rule}"\npackage = "{package}"\n'
    return block + (f'path = "{path}"\n' if path else "")


def reshape(block: str, key: tuple[str, str, str]) -> str:
    """An entry's block, its comments kept, recording `key` instead."""
    comments = [line for line in block.splitlines() if line.lstrip().startswith("#")]
    return "\n".join([*comments, entry_block(key).rstrip("\n")]) + "\n"


def write_baseline(path: Path, baseline: Baseline, findings: list[Finding]) -> None:
    """Keep what the baseline records, reshaped where the finding moved, drop the rest.

    An entry whose package still breaks the rule but differently (a dependency
    that became a production one, a `use` path that moved) is rewritten with
    the finding's key and its comments kept: recording a violation is what
    this file does, and it only ever records fewer.
    """
    if not baseline.blocks:
        path.write_text(
            baseline.header + "\n" + "\n\n".join(entry_block(f.key) for f in sorted(findings, key=lambda f: f.key)),
            encoding="utf-8",
        )
        return
    current = {finding.key for finding in findings}
    by_package = {(finding.rule, finding.package): finding.key for finding in findings}
    blocks, written = [], set()
    for key, block in baseline.blocks.items():
        if key in current:
            blocks.append(block)
            written.add(key)
        elif (moved := by_package.get((key[0], key[1]))) is not None:
            blocks.append(reshape(block, moved))
            written.add(moved)
    path.write_text(baseline.header + "\n" + "\n\n".join(blocks), encoding="utf-8")


def reconcile(
    findings: list[Finding], baseline: Baseline
) -> tuple[list[Finding], list[tuple[str, str, str]]]:
    """The findings the baseline does not record, and the entries it no longer needs."""
    keys = baseline.keys
    reported = [finding for finding in findings if finding.key not in keys]
    moved = {(finding.rule, finding.package) for finding in reported}
    stale = [
        key
        for key in sorted(keys - {finding.key for finding in findings})
        # A package recorded here that still breaks the rule, differently, is
        # the reported finding above: the entry is reshaped, not dropped.
        if (key[0], key[1]) not in moved
    ]
    return reported, stale


def report(findings: list[Finding], baseline: Baseline) -> bool:
    """Print the findings the baseline does not record and the entries it no longer needs."""
    reported, stale = reconcile(findings, baseline)
    for finding in sorted(reported, key=str):
        print(finding)
    for rule, package, path in stale:
        where = f"{package} ({path})" if path else package
        print(f"{BASELINE.as_posix()}: {where} no longer breaks {rule}; drop the entry with --write-baseline")
    return bool(reported or stale)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--list", action="store_true", help="print the findings alone")
    parser.add_argument("--write-baseline", action="store_true", help="drop stale baseline entries")
    args = parser.parse_args(argv)
    root = args.root.resolve()
    try:
        rules = load_rules(root / RULES)
        found = violations(rules, workspace(root), root)
    except (OSError, ValueError, tomllib.TOMLDecodeError, RuntimeError, KeyError) as error:
        print(f"crate layers check failed: {error}", file=sys.stderr)
        return 1
    baseline = load_baseline(root / BASELINE)
    if args.list:
        print("\n".join(str(finding) for finding in found))
        return 0
    if args.write_baseline:
        write_baseline(root / BASELINE, baseline, found)
        baseline = load_baseline(root / BASELINE)
    if report(found, baseline):
        print(
            "\nan edge or a `use` path breaks a crate layer: the rule and the reason it holds are in "
            f"{RULES.as_posix()}.",
            file=sys.stderr,
        )
        return 1
    print(
        f"Crate layers OK ({len(rules)} rules, {len(baseline.keys)} recorded edge(s) left, none new)",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
