#!/usr/bin/env python3
"""Generate docs/codemap.md: one line per workspace crate, grouped by directory.

The map is where to look first for "where does X live". Each line is the crate's
path below its group, its package name when that differs from the directory, and
what it owns: the `description` in its Cargo.toml, or else the first sentence of
its crate-level `//!` docs. Write a better description in Cargo.toml rather than
editing the map.

    python3 tools/docs/codemap.py          rewrite docs/codemap.md
    python3 tools/docs/codemap.py --check  fail when docs/codemap.md is stale
"""

from __future__ import annotations

import argparse
import re
import sys
import tomllib
from pathlib import Path


ROOT = Path(__file__).resolve().parents[2]
OUTPUT = "docs/codemap.md"
# Group depth below the root: apps/<app>, crates/<domain>/<crate>, examples/<kind>/<crate>.
GROUP_DEPTH = {"apps": 1, "crates": 2, "examples": 2}
MAX_SUMMARY = 64
# Words every line would repeat; dropping them keeps the map cheap to read.
BOILERPLATE = [
    re.compile(r"\s*\((?:CRDT-native|retained-mode)[^)]*\)", re.I),
    re.compile(r",?\s*(?:built )?on the (?:Tilo |CRDT-native )?`ui` toolkit", re.I),
    re.compile(r"\b(?:thin binary entry point|library root(?: for the)?|tilo native app|"
               r"standard tilo application entry point|all logic lives in the library)\b\.?:?", re.I),
    re.compile(r"\s+(?:for|in) Tilo$"),
    re.compile(r"^(?:an?\s+|the\s+)?(?:Tilo\s+native\s+|CRDT-native\s+|Tilo\s+)", re.I),
]
LINK = re.compile(r"\[([^\]]+)\]\([^)]*\)|\[`?([^\]`]+)`?\]")
SENTENCE_END = re.compile(r"(?<=[.!?])\s")

HEADER = """# Code map

Where things live: every workspace crate by package name, grouped by directory, with what it owns.
A crate's directory is its package name without `tilo-` or `example-`, unless shown as `directory` (package).
Generated by `python3 tools/docs/codemap.py` from each crate's Cargo.toml `description`
(or its first `//!` sentence); improve a line there, not here. Search inside the crate from here.
"""


def members() -> list[Path]:
    workspace = tomllib.loads((ROOT / "Cargo.toml").read_text())["workspace"]
    found: set[Path] = set()
    for pattern in workspace["members"]:
        for path in ROOT.glob(pattern):
            if (path / "Cargo.toml").is_file():
                found.add(path.relative_to(ROOT))
    return sorted(found)


def doc_paragraphs(crate: Path) -> list[str]:
    """The leading `//!` paragraphs of lib.rs, then main.rs: often the first is only a title."""
    paragraphs: list[str] = []
    for source in ("src/lib.rs", "src/main.rs"):
        path = ROOT / crate / source
        if not path.is_file():
            continue
        current: list[str] = []
        attribute_depth = 0
        for line in path.read_text(errors="replace").splitlines()[:120]:
            stripped = line.strip()
            if attribute_depth or stripped.startswith("#!["):
                attribute_depth += stripped.count("[") - stripped.count("]")
                continue
            if stripped.startswith("//!"):
                text = stripped[3:].strip()
                if text and not text.startswith(("#", "```")):
                    current.append(text)
                elif current:
                    paragraphs.append(" ".join(current))
                    current = []
            elif stripped.startswith("//") or not stripped:
                continue
            else:
                break
        if current:
            paragraphs.append(" ".join(current))
    return paragraphs


def summarize(text: str, name: str = "") -> str:
    text = LINK.sub(lambda m: m.group(1) or m.group(2), " ".join(text.split()))
    text = SENTENCE_END.split(text, maxsplit=1)[0].rstrip(".")
    for pattern in BOILERPLATE:
        text = pattern.sub("", text)
    text = " ".join(text.split()).strip(" —–-:,")
    # "Calculator — a calculator": the label already names the crate.
    for separator in (" — ", ": "):
        head, sep, rest = text.partition(separator)
        title = head.lower().replace(" ", "-") in name
        if sep and (title or (separator == " — " and len(head.split()) <= 2)):
            text = BOILERPLATE[-1].sub("", rest.strip(" —–-:,"))
    text = re.sub(r"^(?:an?|the)\s+", "", text, flags=re.I)
    if text.lower().replace(" ", "-") in name:
        return ""
    if text[1:2].islower():
        text = text[:1].upper() + text[1:]
    if len(text) > MAX_SUMMARY:
        text = text[: MAX_SUMMARY - 1].rsplit(" ", 1)[0].rstrip(",;:—-– ") + "…"
    return text


def entry(crate: Path) -> tuple[str, str, str]:
    manifest = tomllib.loads((ROOT / crate / "Cargo.toml").read_text())
    package = manifest.get("package", {})
    name = package.get("name", crate.name)
    description = package.get("description")
    candidates = [description] if isinstance(description, str) else []
    summary = next(
        (text for text in (summarize(c, crate.name) for c in candidates + doc_paragraphs(crate)) if text), "")
    depth = GROUP_DEPTH.get(crate.parts[0], 1)
    group = "/".join(crate.parts[:depth]) if len(crate.parts) > depth else crate.parts[0]
    local = "/".join(crate.parts[depth:]) or crate.name
    directory = local.rsplit("/", 1)[-1]
    label = f"`{name}`" if "/" not in local and directory in (name, name.removeprefix("tilo-"), name.removeprefix("example-")) else f"`{local}` ({name})"
    return group, label, summary


def render() -> str:
    groups: dict[str, list[str]] = {}
    missing: list[str] = []
    for crate in members():
        group, label, summary = entry(crate)
        if not summary:
            missing.append(str(crate))
        groups.setdefault(group, []).append(f"- {label}: {summary}" if summary else f"- {label}")
    if missing:
        sys.exit("no description beyond the crate's name: " + ", ".join(missing) + "\nadd a `description` to its Cargo.toml")
    body = [HEADER]
    for group in sorted(groups):
        body.append(f"\n## {group}")
        body.extend(groups[group])
    return "\n".join(body) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the map is stale")
    args = parser.parse_args()
    text = render()
    path = ROOT / OUTPUT
    if args.check:
        if not path.is_file() or path.read_text() != text:
            print(f"{OUTPUT} is stale. Regenerate it: python3 tools/docs/codemap.py", file=sys.stderr)
            return 1
        return 0
    path.write_text(text)
    print(f"wrote {OUTPUT}: {len(text)} chars, ~{len(text) // 4} tokens")
    return 0


if __name__ == "__main__":
    sys.exit(main())
