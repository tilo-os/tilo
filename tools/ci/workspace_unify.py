#!/usr/bin/env python3
"""Writes crates/dev/workspace-unify, the package that makes every member of a cargo family's build
build with one feature set, whatever selection of its packages pulls it in.

Cargo unifies a member's features over the packages a command selects, so `-p shell` and `-p notes`
build `tilo-ui` with different features, and each is a distinct unit: compiled again, cached apart.
The workspace hack does this for third-party crates; it can't for members, which all depend on it.
workspace-unify depends on every library the `test` family's whole build builds, with the
features cargo plans for it there (dev-dependencies' included, and the features
tools/ci/package_features.py gives a package's tests and lints, which reach a cargo family's build
through it alone): those built into the workspace's programs as its dependencies, those
built for the host (proc macros, build scripts' dependencies) as its build-dependencies, each
architecture's under a table of its own, resolved on a machine of that architecture as the cargo
families run cargo there, with no `--target`. Nothing depends on it. A run of a family that asks
for a few of its packages names it besides them (t's `[[cargo]] unify`), and every member of that
selection then resolves as in the family's whole build. Its one target needs a feature nothing
enables, so it adds no unit: it only takes part in resolving features.

  workspace_unify.py --write   regenerate this architecture's tables
  workspace_unify.py --check   fail if they are not what --write would write, or if another
                               architecture's table names a version Cargo.lock no longer resolves
"""
from __future__ import annotations

import argparse
import json
import os
import platform
import re
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import tomllib

sys.path.insert(0, str(Path(__file__).resolve().parent))
import package_features  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
NAME = "workspace-unify"
HAKARI = "workspace-hack"
DIR = ROOT / "crates" / "dev" / NAME
# The cargo family whose build this package unifies: its whole build selects `--workspace
# --exclude` what its t.toml entry excludes (tools/ci/nextest.sh adds its packages' test features
# as `--features`), and a run that asks for a few of its packages builds those beside this one.
FAMILY = "test"
T_TOML = ROOT / "t.toml"
# What each architecture CI runs cargo families on resolves: a feature only one of them enables
# goes under that architecture's table.
TARGETS = {"x86_64": "x86_64-unknown-linux-gnu", "aarch64": "aarch64-unknown-linux-gnu"}
ARCH = platform.machine()
NEVER = "never"
LIBRARY = {"lib", "rlib", "dylib", "proc-macro"}

EMPTY = f"""[package]
name = "{NAME}"
version = "0.0.0"
edition = "2024"
publish = false
description = "Makes every member resolve its features as the whole workspace does, whatever selection builds it; builds nothing"

[features]
{NEVER} = []

[[bin]]
name = "{NAME}"
path = "main.rs"
required-features = ["{NEVER}"]
test = false
bench = false
doc = false
"""

HEADER = """# Generated by tools/ci/workspace_unify.py: run `python3 tools/ci/workspace_unify.py --write`.
# Every library the test family's build builds, its members' and the crates they use, with the
# features the family's whole build resolves for it, so that a run that asks for a few of its
# packages, which names this package too, builds each as one unit.
"""

MAIN = "fn main() {}\n"
# Its build script builds only with its target, which never builds: it is there so that cargo
# takes its build-dependencies, the host's packages, into resolving features.
BUILD = "fn main() {}\n"


def family_excluded() -> list[str]:
    """The members the `test` family's whole build leaves out, its `exclude` in t.toml: its build
    is `--workspace --exclude` each of them (tools/ci/nextest.sh), so exactly the others are the
    packages whose features this package resolves. It leaves out this package too, but the plan
    keeps it: as the seeds a family's build states as `--features`, its demands are the only way
    those features reach the plan, and a run of one member names it beside it."""
    families = tomllib.loads(T_TOML.read_text())["cargo"]
    return [name for name in next(family for family in families if family["name"] == FAMILY).get("exclude", [])
            if name != NAME]


def planned(root: Path) -> tuple[dict[str, set[str]], dict[str, set[str]]]:
    """The features of every library unit the `test` family's whole build at `root` makes for its
    tests on this machine, by package id: those built into its programs, and those built for the
    host (proc macros, build scripts' dependencies, and what they use), which cargo resolves
    apart. Exactly as cargo plans the build (`--unit-graph`) the way the family runs it, as
    `--workspace --exclude` its t.toml entry excludes (this package beside them, see
    [`family_excluded`]) and with no `--target`, so that a package built alike for both is one
    unit, as there. The features
    tools/ci/package_features.py gives a package's tests come from workspace-unify itself
    (`seeded`), as they do in a cargo family's build, never from `--features`: `--features
    tilo-media/decode` also turns on every optional dependency named tilo-media of the packages
    selected, and gives tilo-media those features where it is built for the host as well, so a
    member resolved differently whether tilo-media was selected beside it or not."""
    command = ["cargo", "test", "--no-run", "--offline", "--workspace"]
    for name in family_excluded():
        command += ["--exclude", name]
    command += ["--unit-graph", "-Z", "unstable-options"]
    out = subprocess.run(
        command, cwd=root, check=True, capture_output=True, text=True,
        env={**os.environ, "RUSTC_BOOTSTRAP": "1"}).stdout
    units = json.loads(out)["units"]
    proc_macro = [("proc-macro" in u["target"]["kind"]) for u in units]
    # A build script's own compile, and a proc macro, use what they depend on on the host.
    for_host = [p or (u["mode"] == "build" and "custom-build" in u["target"]["kind"]) for u, p in zip(units, proc_macro)]
    depended = {d["index"] for u in units for d in u["dependencies"]}
    host: set[int] = set()
    built: set[int] = set()
    todo = [(i, False) for i in range(len(units)) if i not in depended]
    while todo:
        i, on_host = todo.pop()
        on_host = on_host or proc_macro[i]
        seen = host if on_host else built
        if i in seen:
            continue
        seen.add(i)
        todo.extend((d["index"], on_host or for_host[i]) for d in units[i]["dependencies"])

    def features(indexes: set[int]) -> dict[str, set[str]]:
        out: dict[str, set[str]] = {}
        for i in indexes:
            u = units[i]
            if u["mode"] == "build" and LIBRARY & set(u["target"]["kind"]):
                out.setdefault(u["pkg_id"], set()).update(u["features"])
        return out
    return features(built), features(host)


def resolved(root: Path, target: str) -> tuple[dict[str, str], dict[str, str]]:
    """The dependency line of every library the whole workspace at `root` builds on `target`,
    by its key: the members by name, with their features, and the crates they use, each version
    under a key of its own, with the features the workspace gives it; those built for the target,
    and those built for the host. Third-party crates are the workspace hack's too, but a selection
    resolves them with only its own packages' dev-dependencies, which the whole workspace has all
    of."""
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--offline", "--format-version", "1", "--filter-platform", target],
        cwd=root, check=True, capture_output=True, text=True).stdout)
    packages = {p["id"]: p for p in meta["packages"]}
    members = set(meta["workspace_members"])
    built, host = planned(root)
    return (lines(packages, members, root, lambda package_id, _: built.get(package_id)),
            lines(packages, members, root, lambda package_id, _: host.get(package_id)))


def lines(packages: dict, members: set[str], root: Path, features_of) -> dict[str, str]:
    """A dependency line, by key, of each library package in `packages` (id → metadata) that
    `features_of(package)` gives features for (None: left out)."""
    result = {}
    for package_id, package in packages.items():
        # The workspace hack unifies third-party crates itself; cargo-hakari keeps it a dependency
        # of the members it manages alone.
        if package["name"] in (NAME, HAKARI) or not any(LIBRARY & set(t["crate_types"]) for t in package["targets"]):
            continue
        features = features_of(package_id, package)
        if features is None:
            continue
        name = package["name"]
        listed = ", ".join(json.dumps(f) for f in sorted(features))
        source = package.get("source")
        if package_id in members or source is None:
            directory = Path(package["manifest_path"]).parent.relative_to(root.resolve())
            key = name if package_id in members else f"{name}-{package['version']}"
            where = f'path = "../../../{directory}"'
        elif source.startswith("registry+"):
            key = f"{name}-{package['version']}"
            where = f'version = "^{package["version"]}"'
        else:
            raise SystemExit(f"{name} {package['version']} comes from {source}, which workspace_unify.py can't name")
        key = mangled(key)
        rename = "" if key == name else f'package = "{name}", '
        result[key] = f'{json.dumps(key)} = {{ {rename}{where}, default-features = false, features = [{listed}] }}\n'
    return result


# A dependency line's package, which it names when its key is not the package's name; the version
# it asks for, which a line naming a path does not; and its feature list, which only the
# architecture that resolved the line can compute.
PACKAGE = re.compile(r'package = "([^"]+)"')
VERSION = re.compile(r'version = "\^([^"]+)"')
FEATURES = re.compile(r'(features = )(\[[^\]\n]*\])')


def mangled(key: str) -> str:
    """A dependency line's key: a package's name, or its name and the version it resolves."""
    return re.sub(r"[^A-Za-z0-9_-]", "_", key)


def with_features(line: str, features: str) -> str:
    """`line`, enabling `features` instead of its own: another architecture's, which this machine
    does not resolve."""
    return FEATURES.sub(lambda match: match.group(1) + features, line, count=1)


def retargeted(line: str, name: str, version: str) -> str:
    """`line`, naming `name` at `version`: one lock resolves one version of a package for every
    architecture, so a line a version moved past takes that version without a machine of its own."""
    renamed = re.sub(r'^"[^"]+"', lambda _: json.dumps(mangled(f"{name}-{version}")), line, count=1)
    return VERSION.sub(lambda _: f'version = "^{version}"', renamed, count=1)


def header(arch: str, kind: str) -> str:
    return f"[target.'cfg(all(target_os = \"linux\", target_arch = \"{arch}\"))'.{kind}]"


def sections(text: str) -> dict[str, str]:
    """The dependency tables of a manifest workspace_unify.py wrote, by their header line."""
    out: dict[str, str] = {}
    current = None
    for line in text.splitlines(keepends=True):
        if line.startswith("[target."):
            current = line.rstrip("\n")
            out[current] = ""
        elif current is not None and line.strip():
            out[current] += line
    return out


def lock_versions(root: Path) -> dict[str, set[str]]:
    """Every version the workspace's Cargo.lock at `root` resolves, by package name. One lock
    serves every architecture, so this is the same on each: a line names a version the workspace
    no longer resolves whichever machine reads it."""
    lock = tomllib.loads((root / "Cargo.lock").read_text())
    versions: dict[str, set[str]] = {}
    for package in lock["package"]:
        versions.setdefault(package["name"], set()).add(package["version"])
    return versions


def named(line: str) -> tuple[str, str | None]:
    """The package a dependency line names, and the version it asks for (`None` when it names a
    path, which is the workspace's whichever architecture builds it)."""
    key = json.loads(line.split(" = ", 1)[0])
    package = PACKAGE.search(line)
    version = VERSION.search(line)
    return (package.group(1) if package else key), (version.group(1) if version else None)


def stale(root: Path, text: str) -> list[tuple[str, str]]:
    """Each table of `text` for an architecture this machine does not resolve that names a package
    or version the workspace at `root` no longer has, and what it names: (architecture, problem).
    Only a write resolves such a table again, so `--check` fails here rather than compare a table
    this machine rewrote against the one it kept. Cargo.lock is one for every architecture, so this
    is the same check everywhere and needs no cargo run."""
    have = lock_versions(root)
    headers = {header(arch, kind): arch for arch in TARGETS for kind in ("dependencies", "build-dependencies")}
    out = []
    for section, body in sections(text).items():
        arch = headers.get(section)
        if arch is None or arch == ARCH:
            continue
        for line in body.splitlines(keepends=True):
            name, version = named(line)
            if name not in have:
                out.append((arch, f"names {name}, which the workspace no longer has"))
            elif version is not None and version not in have[name]:
                out.append((arch, f"names {name} {version}, which Cargo.lock no longer resolves "
                                  f"({', '.join(sorted(have[name]))})"))
    return out


def seeded(root: Path) -> str:
    """workspace-unify depending only on the members tools/ci/package_features.py names, with the
    features it gives their tests: what it starts from to resolve the workspace."""
    meta = json.loads(subprocess.run(
        ["cargo", "metadata", "--offline", "--no-deps", "--format-version", "1"],
        cwd=root, check=True, capture_output=True, text=True).stdout)
    members = {p["id"]: p for p in meta["packages"] if p["id"] in set(meta["workspace_members"])}
    wanted = package_features.NATIVE_TEST_FEATURES
    deps = lines(members, set(members), root,
                 lambda _, package: wanted.get(package["name"]) if package["name"] in wanted else None)
    return EMPTY + "\n[dependencies]\n" + "".join(deps[k] for k in sorted(deps))


def manifest(root: Path, current: str) -> str:
    """The manifest --write writes on this machine's architecture: `current`'s, with this
    architecture's tables resolved again in the workspace at `root`, workspace-unify depending
    there only on what tools/ci/package_features.py names (`seeded`), so that what it enabled
    before never counts as resolved. The other architecture's tables keep the features that
    architecture resolved, which only its own machine can compute; what a package is, its path or
    version, is the workspace's whichever architecture builds it, so their lines take this
    architecture's and a version the lock moved is written for both rather than dropped. Leaves
    `root` as it found it."""
    anchor = root / DIR.relative_to(ROOT) / "Cargo.toml"
    before = anchor.read_text() if anchor.exists() else None
    lock = (root / "Cargo.lock").read_text()
    anchor.parent.mkdir(parents=True, exist_ok=True)
    anchor.write_text(EMPTY)
    try:
        anchor.write_text(seeded(root.resolve()))
        built, host = resolved(root.resolve(), TARGETS[ARCH])
    finally:
        if before is not None:
            anchor.write_text(before)
        (root / "Cargo.lock").write_text(lock)
    # Only the tables it writes: any other is from an older layout of this file.
    known = {header(arch, kind) for arch in TARGETS for kind in ("dependencies", "build-dependencies")}
    tables = {h: body for h, body in sections(current).items() if h in known}
    # Cargo refuses a manifest that names a package by path for one architecture and from the
    # registry for another, or one crate and version under two names, so the other architecture's
    # lines take this architecture's line for the package and keep their own features. A package
    # the lock resolves at one version has one line for every architecture; one at several (two
    # majors, say) resolves apart, and this architecture's version is not the other's to take.
    versions = lock_versions(root)
    by_name = {named(line)[0]: line for line in {**built, **host}.values()}
    for arch in TARGETS:
        if arch == ARCH:
            continue
        for kind in ("dependencies", "build-dependencies"):
            section = header(arch, kind)
            if section not in tables:
                continue
            kept = []
            for line in tables[section].splitlines(keepends=True):
                name, version = named(line)
                features = FEATURES.search(line)
                if name not in versions:
                    # A line for a package the workspace no longer has keeps cargo from loading it.
                    continue
                if name in by_name and features and len(versions[name]) == 1:
                    kept.append(with_features(by_name[name], features.group(2)))
                elif version is not None and len(versions[name]) == 1 and version not in versions[name]:
                    kept.append(retargeted(line, name, next(iter(versions[name]))))
                else:
                    kept.append(line)
            tables[section] = "".join(kept)
    tables[header(ARCH, "dependencies")] = "".join(built[k] for k in sorted(built))
    tables[header(ARCH, "build-dependencies")] = "".join(host[k] for k in sorted(host))
    text = HEADER + EMPTY.replace("[features]", 'build = "build.rs"\n\n[features]', 1)
    for arch in TARGETS:
        for kind in ("dependencies", "build-dependencies"):
            if header(arch, kind) in tables:
                text += f"\n{header(arch, kind)}\n{tables[header(arch, kind)]}"
    return text


def members(root: Path, text: str) -> set[str]:
    """The workspace's members with workspace-unify's manifest at `root` being `text`: a package it
    names by a path inside the workspace's directory is one, by cargo's rule for path dependencies,
    unless the workspace excludes that directory, and a member resolves its dev-dependencies in
    every build of the workspace. Leaves `root` as it found it."""
    anchor = root / DIR.relative_to(ROOT) / "Cargo.toml"
    before = anchor.read_text() if anchor.exists() else None
    try:
        anchor.write_text(text)
        meta = json.loads(subprocess.run(
            ["cargo", "metadata", "--offline", "--no-deps", "--format-version", "1"],
            cwd=root, check=True, capture_output=True, text=True).stdout)
    finally:
        if before is not None:
            anchor.write_text(before)
    return {p["name"] for p in meta["packages"] if p["id"] in set(meta["workspace_members"])}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    mode = ap.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = ap.parse_args()
    have = (DIR / "Cargo.toml").read_text() if (DIR / "Cargo.toml").exists() else ""
    # A table for an architecture this machine does not resolve that names a version the lock no
    # longer has: --write here leaves its lines as they are, since only that machine resolves their
    # features again, so this machine's check fails rather than report a file both agree with.
    if args.check:
        problems = stale(ROOT, have)
        if problems:
            for arch, problem in problems:
                print(f"crates/dev/{NAME}'s {arch} table {problem}: run "
                      f"'python3 tools/ci/workspace_unify.py --write' on {arch} and commit the "
                      "result.", file=sys.stderr)
            return 1
    # Resolve in a copy of the tree, never in it: resolving rewrites workspace-unify's manifest,
    # and a run cut short there, or a second run reading it meanwhile, would take the seeded
    # manifest for the current one and lose the other architecture's tables, which only a machine
    # of that architecture can write again.
    with tempfile.TemporaryDirectory(prefix="workspace-unify-") as scratch:
        copy = Path(scratch) / "tree"
        shutil.copytree(ROOT, copy, symlinks=True, ignore=shutil.ignore_patterns(".git", "target"))
        want = manifest(copy, have)
        # The tables name libraries the workspace builds, never new members: a member's own
        # dev-dependencies resolve in every build of the workspace, so a member added here would
        # build crates no member asked for.
        added = members(copy, want) - members(copy, EMPTY)
        if added:
            print(f"workspace-unify would make {', '.join(sorted(added))} a workspace member by "
                  "naming it by path: add its directory to [workspace] exclude in Cargo.toml.",
                  file=sys.stderr)
            return 1
    if args.write:
        (DIR / "Cargo.toml").write_text(want)
        (DIR / "main.rs").write_text(MAIN)
        (DIR / "build.rs").write_text(BUILD)
        # Its entry in the lock names what it depends on; relocking the workspace moves no version.
        subprocess.run(["cargo", "metadata", "--offline", "--format-version", "1"],
                       cwd=ROOT, check=True, stdout=subprocess.DEVNULL)
        return 0
    def text(name: str) -> str:
        return (DIR / name).read_text() if (DIR / name).exists() else ""
    if have != want or text("main.rs") != MAIN or text("build.rs") != BUILD:
        with tempfile.NamedTemporaryFile("w", suffix=".toml", delete=False) as f:
            f.write(want)
        print(f"crates/dev/{NAME} is stale: the workspace's features and versions changed. Run "
              f"'python3 tools/ci/workspace_unify.py --write' and commit the result "
              f"(what it would write: {f.name}).", file=sys.stderr)
        subprocess.run(["diff", "-u", str(DIR / "Cargo.toml"), f.name], check=False)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
