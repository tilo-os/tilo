#!/usr/bin/env bash
# Check first-party manifests, including standalone tools, without rewriting
# imported dependencies to satisfy our heuristic unused-dependency scanner.
#
#   check-unused-dependencies.sh                          # every first-party crate
#   check-unused-dependencies.sh --changed BASE BEFORE    # crates a CI change touches
#
# A dependency can only become unused through an edit inside its crate (its
# manifest or its sources) or through the workspace manifest that crates
# inherit from. `--changed` therefore scans the crates that own a changed or
# deleted path. Pure literal workspace-member additions scan those new crates;
# inherited settings, structural changes, or checker changes scan every crate. BASE/BEFORE have the same pull-request/push meaning as the
# formatting and allow-reason gates.
set -euo pipefail
script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
repo=${TILO_REPO_ROOT:-$(cd "$script_dir/../.." && pwd)}
cd "$repo"
paths=$(mktemp)
scratch=
trap 'rm -f -- "$paths"; [[ -z $scratch ]] || rm -rf -- "$scratch"' EXIT
git ls-files -z --cached --others --exclude-standard -- \
    Cargo.toml '*/Cargo.toml' ':(top,exclude)vendor/**' >"$paths"
mapfile -d '' manifests <"$paths"
(( ${#manifests[@]} > 0 )) || { echo 'no first-party Cargo manifests found' >&2; exit 1; }

# The crates `cargo hakari` and tools/ci/workspace_unify.py generate name
# dependencies only to unify their features, so every one of them is unused by
# design; never scan them.
declare -A generated=()
for manifest in "${manifests[@]}"; do
    if [[ -f $manifest ]] && grep -qx -e '### BEGIN HAKARI SECTION' \
        -e '# Generated by tools/ci/workspace_unify.py: .*' "$manifest"; then
        generated[${manifest%/Cargo.toml}]=1
    fi
done
holds_generated() {
    local dir
    for dir in "${!generated[@]}"; do
        [[ $dir == "$1"/* ]] && return 0
    done
    return 1
}

scan=()
if [[ ${1:-} == --changed ]]; then
    range=$(python3 "$script_dir/check_changed_rust_allows.py" \
        --root "$repo" --comparison-range "${2:-}" "${3:-}")
    declare -A crate_dirs=()
    for manifest in "${manifests[@]}"; do
        [[ $manifest == Cargo.toml ]] || crate_dirs[${manifest%/Cargo.toml}]=1
    done
    # List both sides of renames: the crate a file left may lose its last use.
    git diff --name-only -z --no-renames "$range" >"$paths"
    mapfile -d '' changed <"$paths"
    declare -A selected=()
    full=0
    for path in "${changed[@]}"; do
        case $path in
            tools/ci/check-unused-dependencies.sh|tools/ci/workspace_member_additions.py)
                full=1; break ;;
            Cargo.toml)
                if python3 "$script_dir/workspace_member_additions.py" --root "$repo" "$range" >"$paths"; then
                    mapfile -d '' added_members <"$paths"
                    for member in "${added_members[@]}"; do
                        [[ -n ${generated[$member]:-} ]] || selected[$member]=1
                    done
                else
                    full=1; break
                fi
                continue ;;
        esac
        dir=$path
        while [[ $dir == */* ]]; do
            dir=${dir%/*}
            if [[ -n ${crate_dirs[$dir]:-} ]]; then
                [[ -n ${generated[$dir]:-} ]] || selected[$dir]=1
                break
            fi
        done
    done
    if (( ! full )); then
        if (( ${#selected[@]} == 0 )); then
            echo "unused dependencies OK (no first-party crate changed in $range)"
            exit 0
        fi
        printf '%s\0' "${!selected[@]}" | sort -z >"$paths"
        mapfile -d '' scan <"$paths"
    fi
fi

if (( ${#scan[@]} == 0 )); then
    # Scan each first-party subtree once so machete can analyze its crates in parallel.
    # Passing each manifest separately would serialize cargo metadata across the fleet.
    # A subtree holding the generated crate is scanned as its other subtrees.
    declare -A seen=()
    for manifest in "${manifests[@]}"; do
        dir=${manifest%/Cargo.toml}
        [[ -z ${generated[$dir]:-} ]] || continue
        root=${manifest%%/*}
        while [[ $root != "$dir" ]] && holds_generated "$root"; do
            rest=${manifest#"$root"/}
            root=$root/${rest%%/*}
        done
        if [[ -z ${seen[$root]:-} ]]; then
            scan+=("$root")
            seen[$root]=1
        fi
    done
fi
# Metadata for standalone workspaces may create Cargo.lock. Check an isolated,
# writable source snapshot instead of requiring a writable checkout (t mounts
# its source read-only). Keep relative path dependencies and Cargo configuration.
scratch=$(mktemp -d)
git ls-files -z --cached --others --exclude-standard >"$paths"
python3 - "$repo" "$scratch" "$paths" <<'PY'
import os
from pathlib import Path
import shutil
import sys

source, destination, listing = map(Path, sys.argv[1:])
for name in listing.read_bytes().split(b"\0"):
    if not name:
        continue
    relative = Path(os.fsdecode(name))
    original = source / relative
    if not original.exists() and not original.is_symlink():
        continue  # A locally deleted tracked file is not part of the snapshot.
    copied = destination / relative
    copied.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(original, copied, follow_symlinks=False)
    if not copied.is_symlink():
        copied.chmod(copied.stat().st_mode | 0o200)
PY
# machete reads only the sources under a crate's src/, but a crate may compile
# another crate's files with #[path]; their dependencies are the including
# crate's. Copy every file a crate includes from elsewhere, and the modules
# beside it, into the crate's src/ in the snapshot so machete reads them there.
# The workspace root is no crate's sources.
python3 - "$scratch" "${manifests[@]}" <<'PY'
import re
import shutil
import sys
from pathlib import Path

scratch = Path(sys.argv[1]).resolve()
include = re.compile(r'#\[path\s*=\s*"([^"]+)"\s*\]')
for manifest in sys.argv[2:]:
    crate = (scratch / manifest).parent
    if crate == scratch or not (scratch / manifest).is_file():
        continue
    todo = [path.resolve() for path in crate.rglob("*.rs")]
    seen = set(todo)
    outside = []
    while todo:
        source = todo.pop()
        for target in include.findall(source.read_text(errors="ignore")):
            found = (source.parent / target).resolve()
            # A file's child modules live in the directory named for it.
            candidates = [found] if found.is_dir() else [found, found.with_suffix("")]
            for candidate in candidates:
                files = candidate.rglob("*.rs") if candidate.is_dir() else [candidate]
                for path in files:
                    if path.is_file() and path not in seen:
                        seen.add(path)
                        todo.append(path)
                        if crate not in path.parents and scratch in path.parents:
                            outside.append(path)
    for path in outside:
        copied = crate / "src" / "machete-path-includes" / path.relative_to(scratch)
        copied.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, copied)
PY
cd "$scratch"
cargo machete --with-metadata "${scan[@]}"
