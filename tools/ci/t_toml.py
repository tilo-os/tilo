def policy_checks(root: Path = ROOT) -> str:
    """One `policy/<name>` check per step of tools/policy/steps.toml. A step another check of t.toml runs (`covered_by`) gets none; that check
    has to run the same command."""
    declared = {check["name"]: check for check in tomllib.loads(T_TOML.read_text(encoding="utf-8")).get("check", [])}
    blocks = []
    for step in policy_steps.expanded(root):
        if step.covered_by is not None:
            check = declared.get(step.covered_by)
            if check is None or step.run not in " ".join(check["run"].split()):
                raise ValueError(f"tools/policy/steps.toml: {step.name} says {step.covered_by} runs it, but t.toml's "
                                 f"{step.covered_by} doesn't run `{step.run}`")
            continue
        blocks.append("\n".join([
            "[[check]]",
            f"name = {json.dumps(step.check)}",
            'requires = ["arch=any"]',
            f"run = {json.dumps(step.t_command)}",
            # Those that read the commit's history (release contracts at HEAD) get t's own .git,
            # which keys their result per commit.
            *(["git = true"] if step.history else []),
        ]) + "\n")
    return "\n".join(blocks)


def array(values: list[str]) -> str:
    return "[" + ", ".join(json.dumps(value) for value in values) + "]"


def suite_checks(manifest: suites.Manifest) -> str:
    blocks = []
    for group in manifest.groups:
        fields = GROUP_FIELDS.get(group.name, {})
        run = f"python3 tools/ci/suites.py run --jobs 8 --group {group.name}"
        if "prepare" in fields:
            run = f"{fields['prepare']} && {run}"
        blocks.append("\n".join([
            *([f"# It {fields['why']}."] if fields else []),
            "[[check]]",
            f'name = "suite-{group.name}"',
            f"run = {json.dumps(run)}",
            f"image = {json.dumps(SUITE_IMAGE)}",
            "env = { " + ", ".join(f"{key} = {json.dumps(value)}" for key, value in
                                    {"PATH": SUITE_PATH, **fields.get("env", {})}.items()) + " }",
            'requires = ["arch=x86_64"]',
            *([f"isolation = {json.dumps(fields['isolation'])}"] if "isolation" in fields else []),
            *([f"needs = {array(fields['needs'])}"] if "needs" in fields else []),
            *([f"on = {array(fields['on'])}"] if "on" in fields else []),
            *(["default = false"] if fields.get("default") is False else []),
            *(["heavy = true"] if fields.get("heavy") else []),
        ]) + "\n")
    return "\n".join(blocks)


def goldens(image: str) -> str:
    """The goldens family: the golden filter over the packages it names, in their image. It stays
    on x86_64, where the baselines were rendered: on aarch64 seven of them come out different
    (nightly-arm64-goldens), so a result from there wouldn't stand for both."""
    sys.path.insert(0, str(ROOT / "tools/ci"))
    import nextest_filters
    golden = nextest_filters.filters()["GOLDEN_FILTER"]
    packages = sorted(set(re.findall(r"package\(([\w-]+)\)", golden)))
    return "\n".join([
        "[[cargo]]",
        'name = "goldens"',
        'tool = "nextest"',
        f"image = {json.dumps(image)}",
        'requires = ["arch=x86_64"]',
        # The pinned fonts tilo-font-catalog's build script prepares, cached in the build
        # directory, which t keeps across a build lineage (family env is taken literally).
        'wrapper = ["bash", "-c", "export TILO_FONT_ASSET_CACHE=\\"$CARGO_TARGET_DIR/font-artifacts\\"; '
        'exec bash tools/test-env.sh \\"$@\\"", "goldens"]',
        f"packages = {array(packages)}",
        f"args = {array(['--locked', '--profile', 'ci', '--tests', '--no-tests=pass', '-E', golden])}",
        'env = { TILO_REQUIRE_GPU = "1", TILO_TEST_NTFS_FIXTURES = "0" }',
        # Pushes to main don't run it: on main it took 21 job-hours a day. Main runs it when t has
        # room left after everything else (`idle`), and t bisects a failure to the commit that
        # broke it; release candidates run it too (visual-goldens below); `t test goldens` runs it
        # for a working tree.
        'on = ["idle"]',
        "default = false",
        "",
        "# The goldens family over all its packages, on every release candidate and on demand.",
        "[[check]]",
        'name = "visual-goldens"',
        f"image = {json.dumps(image)}",
        'requires = ["arch=x86_64"]',
        "run = " + json.dumps(f"bash tools/test-env.sh cargo nextest run --locked --profile ci --tests "
                              f"--no-tests=pass {' '.join(f'-p {name}' for name in packages)} -E '{golden}'"),
        'env = { TILO_REQUIRE_GPU = "1", TILO_TEST_NTFS_FIXTURES = "0" }',
        'on = ["stable", "dispatch"]',
        "default = false",
        "heavy = true",
    ]) + "\n"


