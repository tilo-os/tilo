#!/usr/bin/env python3
"""Keep the parts of t.toml that other repository files define in step with them.

t keys a cargo check by its package's own files and path dependencies, and a
shell check by its `inputs`. suites.toml already says which packages read
files outside their directory and which paths each hermetic suite group reads,
so t.toml carries both, generated between markers:

  * `package_inputs` of the cargo families, so a change to a file a package
    reads through include_str! or a test fixture path runs its checks again;
  * one `suite-<group>` check per suite group;
  * the `goldens` family, which runs .config/nextest-filters.toml's golden
    filter in the image .config/visual-goldens-image names.

  t_toml.py write   regenerate the marked blocks in t.toml
  t_toml.py check   fail when they differ from what suites.toml implies
"""
from __future__ import annotations

import json
from pathlib import Path
import re
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import suites  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
T_TOML = ROOT / "t.toml"
BLOCK = re.compile(r"(?ms)^# BEGIN generated by tools/ci/t_toml\.py: (?P<name>[\w-]+)\n.*?^# END generated\n")
GOLDENS_IMAGE = ROOT / ".config" / "visual-goldens-image"
# Every suite group runs in ci-fast, as check.yml's suites job does, with the
# toolchain's binaries ahead of rustup's proxies (see the hakari check).
SUITE_IMAGE = "registry.tilo.so/tilo/ci-fast@sha256:ecfe2c2abf7a48d9d00d71083aba6b7b9dfc11bc9de63b87e3144522daf6d97c"
# Groups that need what a t check does not offer yet, with what that is. They
# stay declared, out of the default set, until t provides it.
NOT_DEFAULT = {
    "os": "writes /var/lib and /var/tmp, starts nested bubblewrap sandboxes and reads Git history",
    "dist": "writes under target/ in the source tree and reads Git history",
    "vm-acceptance": "writes under target/ in the source tree",
    "mount-source-cache-keys": "lists files through Git",
    "browser-compute-web": "runs npm ci in scripts/moq-browser, in the source tree",
    "browser-runtime-web": "builds the MoQ library with npm in scripts/moq-browser, in the source tree",
}
SUITE_PATH = "/usr/local/rustup/toolchains/1.97.1-x86_64-unknown-linux-gnu/bin:/usr/local/cargo/bin:/usr/local/bin:/usr/bin:/bin"


def glob(pattern: str) -> str:
    """A suites.toml input as a t glob: "dir/" covers everything below it."""
    return pattern + "**" if pattern.endswith("/") else pattern


def array(values: list[str]) -> str:
    return "[" + ", ".join(json.dumps(value) for value in values) + "]"


def package_inputs(manifest: suites.Manifest) -> str:
    lines = ["[cargo.package_inputs]"]
    for reader in sorted(manifest.cargo, key=lambda reader: reader.package):
        key = reader.package if re.fullmatch(r"[A-Za-z0-9_-]+", reader.package) else json.dumps(reader.package)
        lines.append(f"{key} = {array([glob(path) for path in reader.inputs])}")
    return "\n".join(lines) + "\n"


def suite_checks(manifest: suites.Manifest) -> str:
    blocks = []
    for group in manifest.groups:
        inputs = sorted({glob(path) for path in (*group.inputs, *group.suites)}
                        | {suites.MANIFEST, "tools/ci/suites.py", "tools/with-test-environment.sh"})
        reason = NOT_DEFAULT.get(group.name)
        blocks.append("\n".join([
            *([f"# Not default: it {reason}; a t check has a read-only root and source tree and no Git."]
              if reason else []),
            "[[check]]",
            f'name = "suite-{group.name}"',
            f'run = "python3 tools/ci/suites.py run --jobs 8 --group {group.name}"',
            f"image = {json.dumps(SUITE_IMAGE)}",
            f"env = {{ PATH = {json.dumps(SUITE_PATH)} }}",
            'requires = ["arch=x86_64"]',
            f"inputs = {array(inputs)}",
            *(["default = false"] if reason else []),
        ]) + "\n")
    return "\n".join(blocks)


def goldens(image: str) -> str:
    """The goldens family: the golden filter over the packages it names, in their image."""
    sys.path.insert(0, str(ROOT / "tools/ci"))
    import nextest_filters
    golden = nextest_filters.filters()["GOLDEN_FILTER"]
    packages = sorted(set(re.findall(r"package\(([\w-]+)\)", golden)))
    return "\n".join([
        "[[cargo]]",
        'name = "goldens"',
        'tool = "nextest"',
        f"image = {json.dumps(image)}",
        'requires = ["arch=x86_64"]',
        'wrapper = ["bash", "tools/test-env.sh"]',
        f"packages = {array(packages)}",
        f"args = {array(['--locked', '--profile', 'ci', '--tests', '--no-tests=pass', '-E', golden])}",
        'inputs = [".config/nextest.toml", ".config/nextest-filters.toml", ".config/visual-goldens-image", '
        '"tools/test-env.sh", "tools/with-test-environment.sh", "tools/with-headless-audio.sh"]',
        'env = { TILO_REQUIRE_GPU = "1", TILO_TEST_NTFS_FIXTURES = "0" }',
        'cost = "minutes"',
    ]) + "\n"


def generated(manifest: suites.Manifest) -> dict[str, str]:
    inputs = package_inputs(manifest)
    return {"test-package-inputs": inputs, "clippy-package-inputs": inputs,
            "check-package-inputs": inputs, "suites": suite_checks(manifest),
            "goldens": goldens(GOLDENS_IMAGE.read_text(encoding="utf-8").strip())}


def render(text: str, blocks: dict[str, str]) -> str:
    seen = set()

    def replace(match: re.Match[str]) -> str:
        name = match["name"]
        if name not in blocks:
            raise ValueError(f"t.toml marks an unknown generated block: {name}")
        seen.add(name)
        return f"# BEGIN generated by tools/ci/t_toml.py: {name}\n{blocks[name]}# END generated\n"

    out = BLOCK.sub(replace, text)
    missing = sorted(set(blocks) - seen)
    if missing:
        raise ValueError(f"t.toml lacks the generated blocks: {', '.join(missing)}")
    return out


def main(argv: list[str]) -> int:
    if argv not in (["write"], ["check"]):
        print("usage: t_toml.py write|check", file=sys.stderr)
        return 2
    text = T_TOML.read_text(encoding="utf-8")
    expected = render(text, generated(suites.load(ROOT)))
    if argv == ["write"]:
        if expected != text:
            T_TOML.write_text(expected, encoding="utf-8")
        return 0
    if expected != text:
        print("t.toml is out of date with tools/ci/suites.toml or .config/: "
              "run python3 tools/ci/t_toml.py write",
              file=sys.stderr)
        return 1
    print("t.toml matches tools/ci/suites.toml and .config/")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
