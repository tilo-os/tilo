#!/usr/bin/env bash
# Format-check exactly the Rust files changed from a CI comparison base.
set -euo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
repo="${TILO_REPO_ROOT:-$(cd "$script_dir/../.." && pwd)}"
cd "$repo"

# Use the same PR-versus-push semantics and shallow-history recovery as the
# allow-reason gate; an unavailable comparison must fail both checks.
range=$(python3 "$script_dir/check_changed_rust_allows.py" \
    --root "$repo" --comparison-range "${1:-}" "${2:-}")

# Same rule as .githooks/pre-commit: a vendored crate under vendor/ is
# upstream's code, carried as it ships, and a generated source says so with an
# `@generated` marker in its first five lines; both keep their own formatting.
# Their native tests and dependency/security checks still run. The exception
# is what tilo-app generates (locale and screen registries): it runs them
# through rustfmt, and they are ordinary modules that `cargo fmt --check`
# formats, so a stale one is caught here rather than on the next full run.
changed_paths=$(mktemp)
trap 'rm -f -- "$changed_paths"' EXIT
git diff --name-only -z --diff-filter=ACMRTUXB "$range" -- \
    '*.rs' \
    ':(top,exclude)vendor/**' >"$changed_paths"
mapfile -d '' changed_rs <"$changed_paths"
rust_files=()
for f in "${changed_rs[@]}"; do
    [ -f "$f" ] || continue
    # Match against the head text, not a pipe into grep -q: under pipefail a
    # first-line match would leave head writing into a closed pipe.
    head5=$(head -n 5 -- "$f" || true)
    case "$head5" in
        *"@generated by tilo-app"*) ;;
        *@generated*) continue ;;
    esac
    rust_files+=("$f")
done
if [ "${#rust_files[@]}" -eq 0 ]; then
    echo "changed Rust formatting OK (no hand-written Rust files in $range)"
    exit 0
fi

rustfmt --edition 2024 --check -- "${rust_files[@]}"
echo "changed Rust formatting OK (${#rust_files[@]} files)"
