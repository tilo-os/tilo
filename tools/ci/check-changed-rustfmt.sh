#!/usr/bin/env bash
# Format-check exactly the Rust files changed from a CI comparison base.
set -euo pipefail

script_dir=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
repo="${TILO_REPO_ROOT:-$(cd "$script_dir/../.." && pwd)}"
cd "$repo"

# Use the same PR-versus-push semantics and shallow-history recovery as the
# other changed-file checks; an unavailable comparison fails the check.
range=$(python3 "$script_dir/comparison_range.py" --root "$repo" "${1:-}" "${2:-}")

# Same rule as .githooks/pre-commit: a vendored crate under vendor/ is
# upstream's code, carried as it ships, and a generated source says so with an
# `@generated` marker in its first five lines; both keep their own formatting.
# Their native tests and dependency/security checks still run. The exception
# is what tilolang generates (locale and screen registries): it runs them
# through rustfmt, and they are ordinary modules that `cargo fmt --check`
# formats, so a stale one is caught here rather than on the next full run.
changed_paths=$(mktemp)
trap 'rm -f -- "$changed_paths"' EXIT
git diff --name-only -z --diff-filter=ACMRTUXB "$range" -- \
    '*.rs' \
    ':(top,exclude)vendor/**' >"$changed_paths"
mapfile -d '' changed_rs <"$changed_paths"
rust_files=()
for f in "${changed_rs[@]}"; do
    [ -f "$f" ] || continue
    # Match against the head text, not a pipe into grep -q: under pipefail a
    # first-line match would leave head writing into a closed pipe.
    head5=$(head -n 5 -- "$f" || true)
    case "$head5" in
        *"@generated by tilolang"*) ;;
        *@generated*) continue ;;
    esac
    rust_files+=("$f")
done
if [ "${#rust_files[@]}" -eq 0 ]; then
    echo "changed Rust formatting OK (no hand-written Rust files in $range)"
    exit 0
fi

# rustfmt formats a file's child modules with it (`skip_children` is not stable), so a changed
# parent module would report a child it never touched, unformatted by someone else. Only the
# changed files' differences count.
status=0
rustfmt --edition 2024 --check -- "${rust_files[@]}" >"$changed_paths" 2>&1 || status=$?
if [ "$status" -ne 0 ] && ! grep -q '^Diff in ' "$changed_paths"; then
    cat "$changed_paths"  # rustfmt failed for a reason of its own, not a difference
    exit "$status"
fi
if ! python3 -I - "$repo" "$changed_paths" "${rust_files[@]}" <<'PY'
import os, re, sys
repo, report, files = sys.argv[1], sys.argv[2], sys.argv[3:]
changed = {os.path.realpath(os.path.join(repo, path)) for path in files}
keep, shown = False, False
for line in open(report, errors="replace"):
    heading = re.match(r"^Diff in (.+?):\d+:", line)
    if heading:
        keep = os.path.realpath(heading.group(1)) in changed
    elif line.strip() and not line.startswith((" ", "+", "-", "\\")):
        keep = True  # not part of a difference: an error of rustfmt's own
    if keep:
        sys.stdout.write(line)
        shown = True
sys.exit(1 if shown else 0)
PY
then
    exit 1
fi
[ "$status" -eq 0 ] || echo "(rustfmt also differs in modules these files declare, which this change did not touch)"
echo "changed Rust formatting OK (${#rust_files[@]} files)"
