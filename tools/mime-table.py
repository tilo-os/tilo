#!/usr/bin/env python3
"""Generate crates/platform/tilo-mime/src/table.rs from mime_guess's table.

    python3 tools/mime-table.py ~/.cargo/registry/src/*/mime_guess-2.0.5/src/mime_types.rs

mime_guess keeps its table as `&[(&str, &[&str])]`: about 1400 extensions,
each a string and a slice of strings, so every entry is pointers the loader
relocates in every process that maps it (122 KB of the shared runtime's
relocated data). The table this writes holds the same mapping, extension to
its first (most prevalent) MIME type, as byte offsets into one string: plain
integers and one literal, nothing to relocate.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / "crates/platform/tilo-mime/src/table.rs"


def main() -> int:
    if len(sys.argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    source = Path(sys.argv[1]).read_text()
    entries = re.findall(r'\(\s*"([^"]+)"\s*,\s*&\[\s*"([^"]+)"', source)
    if len(entries) < 1000:
        print(f"read {len(entries)} entries; is this mime_guess's mime_types.rs?", file=sys.stderr)
        return 1
    first: dict[str, str] = {}
    for extension, mime in entries:
        if not extension.isascii() or not mime.isascii():
            print(f"non-ASCII entry {extension!r}: {mime!r}", file=sys.stderr)
            return 1
        first.setdefault(extension.lower(), mime)
    extensions = sorted(first)
    blob = ""
    offsets: dict[str, int] = {}

    def place(text: str) -> int:
        nonlocal blob
        if text not in offsets:
            at = blob.find(text)
            if at < 0:
                at = len(blob)
                blob += text
            offsets[text] = at
        return offsets[text]

    rows = []
    for extension in extensions:
        mime = first[extension]
        rows.append((place(mime), len(mime), place(extension), len(extension)))
    if len(blob) >= 1 << 16 or any(length > 255 for _, length, _, _ in rows):
        print("the table outgrew u16 offsets or u8 lengths", file=sys.stderr)
        return 1
    # The blob as a string literal of short lines (a `\` line continuation
    # drops the newline and the next line's leading whitespace, so no line may
    # start with a space).
    lines = []
    line = ""
    for char in blob:
        line += char
        if len(line) >= 90 and char != " ":
            lines.append(line)
            line = ""
    lines.append(line)
    if any(part.startswith(" ") for part in lines):
        print("a blob line starts with a space", file=sys.stderr)
        return 1
    literal = "\\\n".join(part.replace("\\", "\\\\").replace('"', '\\"') for part in lines)
    out = [
        "// @generated by tools/mime-table.py from mime_guess 2.0.5's MIME_TYPES; do not edit.",
        "",
        "/// Every extension and MIME type of [`EXTENSIONS`], back to back.",
        f'pub(crate) const STRINGS: &str = "\\\n{literal}";',
        "",
        "/// Each known extension (ASCII lowercase, sorted) with its first MIME type:",
        "/// `(mime start, mime length, extension start, extension length)` in [`STRINGS`].",
        f"pub(crate) static EXTENSIONS: [(u16, u8, u16, u8); {len(rows)}] = [",
    ]
    out += [f"    ({m}, {ml}, {e}, {el})," for m, ml, e, el in rows]
    out += ["];", ""]
    OUT.write_text("\n".join(out))
    print(f"{len(rows)} extensions, {len(blob)} bytes of strings -> {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
