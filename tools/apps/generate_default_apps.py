#!/usr/bin/env python3
"""Compile the default app collection's package ids into app-fleet.

The default apps are the ones `dist/apps/app-collections.toml`'s
`collections.default` names: the same collection CI's `package-apps` builds and
the OS image bakes, resolved here exactly as the release planner resolves it
(`app_release.py`), so there is one list and this is a copy of it, never a
second one.

Writes `crates/packaging/app-fleet/src/default_apps.rs`. With `--check` it fails
when that file is out of date instead.
"""

from __future__ import annotations

import argparse
import pathlib
import sys

TOOLS = pathlib.Path(__file__).resolve().parents[1]
ROOT = TOOLS.parent
sys.path.append(str(TOOLS / "apps"))

import app_release  # noqa: E402

OUTPUT = ROOT / "crates/packaging/app-fleet/src/default_apps.rs"

HEADER = """\
//! @generated by `tools/apps/generate_default_apps.py` from `dist/apps/app-collections.toml`
//! and the app manifests. Do not edit; change the collection or the manifests and run the
//! generator.
"""


def default_apps() -> list[str]:
    catalog = app_release.app_catalog(ROOT)
    config = app_release.config()
    names = app_release.resolve_collection("default", catalog, config)
    return sorted({catalog[name]["id"] for name in names})


def render(ids: list[str]) -> str:
    lines = [
        HEADER,
        "",
        "/// The default collection's package ids, sorted: the apps a workspace is created with.",
        "pub(super) const DEFAULT: &[&str] = &[",
    ]
    lines.extend(f'    "{app}",' for app in ids)
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    try:
        text = render(default_apps())
    except (KeyError, OSError, ValueError) as error:
        print(f"default apps: {error}", file=sys.stderr)
        return 2
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != text:
            print(f"{OUTPUT.relative_to(ROOT)} is stale: run tools/apps/generate_default_apps.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
