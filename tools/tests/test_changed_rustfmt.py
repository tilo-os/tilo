from __future__ import annotations

import os
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path


SCRIPT = Path(__file__).parents[1] / "ci/check-changed-rustfmt.sh"


class ChangedRustfmtTests(unittest.TestCase):
    def setUp(self) -> None:
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        self.bin = self.root / "bin"
        self.bin.mkdir()
        subprocess.run(["git", "init", "-q"], cwd=self.root, check=True)
        subprocess.run(
            ["git", "config", "user.email", "ci@example.invalid"],
            cwd=self.root,
            check=True,
        )
        subprocess.run(["git", "config", "user.name", "CI"], cwd=self.root, check=True)
        (self.root / "base.rs").write_text("fn base() {}\n", encoding="utf-8")
        (self.root / "notes.txt").write_text("base\n", encoding="utf-8")
        self.commit("base")
        self.base = self.git("rev-parse", "HEAD")
        self.arguments = self.root / "rustfmt-arguments"
        fake = self.bin / "rustfmt"
        fake.write_text(
            "#!/usr/bin/env bash\n"
            "printf '<%s>\\n' \"$@\" > \"$RUSTFMT_ARGUMENTS\"\n",
            encoding="utf-8",
        )
        fake.chmod(0o755)

    def git(self, *args: str) -> str:
        return subprocess.check_output(["git", *args], cwd=self.root, text=True).strip()

    def commit(self, message: str) -> None:
        subprocess.run(["git", "add", "."], cwd=self.root, check=True)
        subprocess.run(["git", "commit", "-qm", message], cwd=self.root, check=True)

    def run_check(self, base: str = "", before: str = "") -> subprocess.CompletedProcess[str]:
        environment = os.environ.copy()
        environment.update(
            {
                "PATH": f"{self.bin}:{environment['PATH']}",
                "TILO_REPO_ROOT": str(self.root),
                "RUSTFMT_ARGUMENTS": str(self.arguments),
            }
        )
        return subprocess.run(
            ["bash", str(SCRIPT), base, before],
            text=True,
            capture_output=True,
            check=True,
            env=environment,
        )

    def test_rustfmt_receives_exactly_the_changed_first_party_rust_files(self) -> None:
        with self.subTest(phase='only changed rust files are passed with safe argument boundary'):
            self.doCleanups()
            self.setUp()
            (self.root / "base.rs").write_text("fn changed() {}\n", encoding="utf-8")
            (self.root / "space name.rs").write_text("fn spaced() {}\n", encoding="utf-8")
            (self.root / "notes.txt").write_text("changed\n", encoding="utf-8")
            self.commit("change")

            result = self.run_check(self.base)

            self.assertIn("changed Rust formatting OK (2 files)", result.stdout)
            self.assertEqual(
                self.arguments.read_text(encoding="utf-8").splitlines(),
                ["<--edition>", "<2024>", "<--check>", "<-->", "<base.rs>", "<space name.rs>"],
            )
        with self.subTest(phase='upstream vendor is excluded but first party nested vendor is checked'):
            self.doCleanups()
            self.setUp()
            for name in ("vendor/codec/src/lib.rs", "crates/demo/vendor/local.rs"):
                path = self.root / name
                path.parent.mkdir(parents=True)
                path.write_text("#[allow(dead_code)]\nfn f() {}\n", encoding="utf-8")
            self.commit("import")

            self.run_check(self.base)
            arguments = self.arguments.read_text(encoding="utf-8")
            self.assertNotIn("<vendor/codec/src/lib.rs>", arguments)
            self.assertIn("<crates/demo/vendor/local.rs>", arguments)
        with self.subTest(phase='@generated sources are excluded'):
            self.doCleanups()
            self.setUp()
            generated = self.root / "crates/runtime/demo/src/generated/demo_capnp.rs"
            generated.parent.mkdir(parents=True)
            generated.write_text(
                "// @generated by capnpc-rust\nfn generated() {}\n",
                encoding="utf-8",
            )
            unmarked = self.root / "crates/runtime/demo/src/generated/unmarked.rs"
            unmarked.write_text("// generated without marker\nfn unmarked() {}\n", encoding="utf-8")
            ordinary = self.root / "crates/runtime/demo/src/lib.rs"
            ordinary.write_text("fn checked() {}\n", encoding="utf-8")
            # tilolang formats its registries, and `cargo fmt` reaches them
            # as modules, so they are held to formatting like other code.
            registry = self.root / "apps/demo/src/locales.rs"
            registry.parent.mkdir(parents=True)
            registry.write_text(
                "// @generated by tilolang; locale registry.\n"
                'ui::embedded_catalog!(pub static CATALOG, ["en-US"]);\n',
                encoding="utf-8",
            )
            self.commit("generated bindings")

            self.run_check(self.base)
            arguments = self.arguments.read_text(encoding="utf-8")
            self.assertNotIn("<crates/runtime/demo/src/generated/demo_capnp.rs>", arguments)
            self.assertIn("<crates/runtime/demo/src/generated/unmarked.rs>", arguments)
            self.assertIn("<crates/runtime/demo/src/lib.rs>", arguments)
            self.assertIn("<apps/demo/src/locales.rs>", arguments)
        with self.subTest(phase='push zero base falls back to parent'):
            self.doCleanups()
            self.setUp()
            (self.root / "base.rs").write_text("fn changed() {}\n", encoding="utf-8")
            self.commit("change")

            self.run_check("", "0" * 40)

            self.assertIn("<base.rs>", self.arguments.read_text(encoding="utf-8"))
        with self.subTest(phase='non rust change skips rustfmt'):
            self.doCleanups()
            self.setUp()
            (self.root / "notes.txt").write_text("changed\n", encoding="utf-8")
            self.commit("docs")

            result = self.run_check(self.base)

            self.assertIn("no hand-written Rust files", result.stdout)
            self.assertFalse(self.arguments.exists())
        with self.subTest(phase='only @generated rust skips rustfmt'):
            self.doCleanups()
            self.setUp()
            generated = self.root / "crates/runtime/demo/src/generated/demo_capnp.rs"
            generated.parent.mkdir(parents=True)
            generated.write_text("// @generated\nfn generated() {}\n", encoding="utf-8")
            self.commit("generated only")

            result = self.run_check(self.base)

            self.assertIn("no hand-written Rust files", result.stdout)
            self.assertFalse(self.arguments.exists())


class ChildModuleTests(unittest.TestCase):
    """rustfmt formats the modules a file declares with it; only the changed files count."""

    def setUp(self) -> None:
        if shutil.which("rustfmt") is None:
            self.skipTest("needs rustfmt")
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        for command in (["init", "-q"], ["config", "user.email", "ci@example.invalid"],
                        ["config", "user.name", "CI"]):
            subprocess.run(["git", *command], cwd=self.root, check=True)
        (self.root / "src").mkdir()
        (self.root / "src/lib.rs").write_text("mod child;\npub fn parent() {}\n", encoding="utf-8")
        # Unformatted, by someone else, before this change.
        (self.root / "src/child.rs").write_text("pub fn   child( ) {}\n", encoding="utf-8")
        self.commit("base")
        self.base = subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=self.root, text=True).strip()

    def commit(self, message: str) -> None:
        subprocess.run(["git", "add", "."], cwd=self.root, check=True)
        subprocess.run(["git", "commit", "-qm", message], cwd=self.root, check=True)

    def check(self) -> subprocess.CompletedProcess[str]:
        return subprocess.run(["bash", str(SCRIPT), self.base, "HEAD"], text=True, capture_output=True,
                              env={**os.environ, "TILO_REPO_ROOT": str(self.root)})

    def test_an_untouched_child_module_is_not_the_changes_to_format(self) -> None:
        (self.root / "src/lib.rs").write_text("mod child;\npub fn parent() {}\npub fn more() {}\n",
                                              encoding="utf-8")
        self.commit("change the parent")
        result = self.check()
        self.assertEqual(result.returncode, 0, result.stdout + result.stderr)
        self.assertIn("modules these files declare", result.stdout)

    def test_a_changed_file_that_is_not_formatted_still_fails(self) -> None:
        (self.root / "src/lib.rs").write_text("mod child;\npub fn   parent( ) {}\n", encoding="utf-8")
        self.commit("unformat the parent")
        result = self.check()
        self.assertEqual(result.returncode, 1, result.stdout + result.stderr)
        self.assertIn("lib.rs", result.stdout)
        self.assertNotIn("child.rs", result.stdout)


if __name__ == "__main__":
    unittest.main()
