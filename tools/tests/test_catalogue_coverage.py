import importlib.util
import io
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path


TOOLS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOLS / "policy"))
spec = importlib.util.spec_from_file_location(
    "check_catalogue_coverage", TOOLS / "policy/check_catalogue_coverage.py")
coverage = importlib.util.module_from_spec(spec)
sys.modules["check_catalogue_coverage"] = coverage
spec.loader.exec_module(coverage)

SOURCE = """a = Title
    .doc = What it is.

b = Settings
"""
REGISTRY = """// @generated by tilo-app; locale registry.
// Edit Fluent catalogs under locales/; tilo-app maintains this registry.
// tilo-app:locale=en-US

ui::embedded_catalog!(pub static CATALOG, ["en-US"]);
"""


def tree(files: dict[str, str]) -> tempfile.TemporaryDirectory:
    directory = tempfile.TemporaryDirectory()
    for name, text in files.items():
        path = Path(directory.name) / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return directory


def missing(files: dict[str, str]) -> list[tuple[str, str, str]]:
    with tree(files) as root:
        return [(unit, locale, key)
                for unit, locale, _, key, _ in coverage.untranslated(Path(root))]


def twice(files: dict[str, str]) -> list[tuple[str, str, int, int]]:
    with tree(files) as root:
        return [(catalogue.relative_to(root).as_posix(), key, first, line)
                for catalogue, key, first, line in coverage.duplicated(Path(root))]


def stale(files: dict[str, str]) -> list[tuple[str, str]]:
    """Per (registry, what is behind it), and never a fix the check cannot name."""
    with tree(files) as root:
        found = coverage.stale_registries(Path(root))
        for _, _, _, fix in found:
            assert fix.startswith("tilo-app "), fix
        return [(registry.relative_to(root).as_posix(), reason)
                for _, registry, reason, _ in found]


def fix_for(files: dict[str, str]) -> list[str]:
    with tree(files) as root:
        return [fix for _, _, _, fix in coverage.stale_registries(Path(root))]


def run(files: dict[str, str], *arguments: str) -> tuple[int, str, str]:
    with tree(files) as root:
        original = coverage.ROOT
        coverage.ROOT = Path(root)
        out, err = io.StringIO(), io.StringIO()
        try:
            with redirect_stdout(out), redirect_stderr(err):
                code = coverage.main(["check", *arguments])
        finally:
            coverage.ROOT = original
        return code, out.getvalue(), err.getvalue()


class CatalogueCoverageTests(unittest.TestCase):
    def test_a_key_only_the_source_has_is_reported(self):
        found = missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n",
        })
        self.assertEqual(found, [("app", "de-DE", "b")])

    def test_an_attribute_is_a_key_of_its_own(self):
        found = missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n\nb = Einstellungen\n",
        })
        self.assertEqual(found, [("app", "de-DE", "a.doc")])

    def test_a_locale_may_add_its_own_words(self):
        self.assertEqual(missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n"
                                    "\nc = Nur auf Deutsch\n",
        }), [])

    def test_a_complete_translation_passes(self):
        self.assertEqual(missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n",
        }), [])

    def test_the_listing_names_each_untranslated_key_and_passes(self):
        code, out, _ = run({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n",
        }, "--list")
        self.assertEqual(code, 0)
        self.assertEqual(out, "app de-DE b\n")

    def test_a_partly_translated_catalogue_fails_and_names_the_key(self):
        code, out, err = run({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n",
        })
        self.assertEqual(code, 1)
        self.assertEqual(out, "app/locales/en-US.ftl:4: b has no de-DE text\n")
        self.assertIn("1 keys are untranslated", err)

    def test_a_key_defined_twice_is_reported_with_both_lines(self):
        self.assertEqual(twice({
            "app/locales/en-US.ftl": SOURCE + "\nb = Settings\n",
        }), [("app/locales/en-US.ftl", "b", 4, 6)])

    def test_a_translation_defining_a_key_twice_names_its_own_lines(self):
        self.assertEqual(twice({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n"
                                    "\n\nb = Optionen\n",
        }), [("app/locales/de-DE.ftl", "b", 4, 7)])

    def test_a_repeated_key_fails_even_when_the_translation_is_whole(self):
        code, out, err = run({
            "app/locales/en-US.ftl": SOURCE + "\nb = Settings\n",
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n"
                                     "\nb = Optionen\n",
        })
        self.assertEqual(code, 1)
        self.assertEqual(out, "")
        self.assertIn("app/locales/en-US.ftl:6: b is defined again; line 4 already defines it", err)
        self.assertIn("2 keys are defined twice", err)

    def test_the_listing_still_fails_on_a_repeated_key(self):
        code, _, err = run({
            "app/locales/en-US.ftl": SOURCE + "\nb = Settings\n",
        }, "--list")
        self.assertEqual(code, 1)
        self.assertIn("b is defined again", err)

    def test_a_registry_registering_every_catalog_passes(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": REGISTRY,
        }), [])

    def test_an_app_owned_registry_is_not_a_generated_one(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": "ui::embedded_catalog!(pub static CATALOG, [\"en-US\"]);\n",
        }), [])

    def test_a_catalog_the_registry_does_not_name_is_reported_with_add_locale(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n",
            "app/src/locales.rs": REGISTRY,
        }), [("app/src/locales.rs", "locales/de-DE.ftl is not registered")])
        self.assertEqual(fix_for({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n",
            "app/src/locales.rs": REGISTRY,
        }), ["tilo-app add locale de-DE"])

    def test_a_registered_locale_with_no_catalog_is_reported(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": REGISTRY.replace(
                "// tilo-app:locale=en-US", "// tilo-app:locale=de-DE\n// tilo-app:locale=en-US"
            ).replace('["en-US"]', '["de-DE", "en-US"]'),
        }), [("app/src/locales.rs", "registered locale 'de-DE' has no locales/de-DE.ftl")])

    def test_an_embedded_catalog_list_differing_from_the_registration_is_reported(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n",
            "app/src/locales.rs": REGISTRY.replace(
                "// tilo-app:locale=en-US", "// tilo-app:locale=de-DE\n// tilo-app:locale=en-US"
            ),
        }), [("app/src/locales.rs",
             "the embedded catalog does not hold exactly the registered locales")])

    def test_a_stale_registry_fails_with_the_command_that_writes_it(self):
        code, _, err = run({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": REGISTRY.replace('["en-US"]', '["en-US", "de-DE"]'),
        })
        self.assertEqual(code, 1)
        self.assertIn("app/src/locales.rs:", err)
        self.assertIn("run `tilo-app locale sync`", err)


if __name__ == "__main__":
    unittest.main()
