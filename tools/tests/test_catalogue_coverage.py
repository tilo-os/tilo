import importlib.util
import io
import sys
import tempfile
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path


TOOLS = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(TOOLS / "policy"))
spec = importlib.util.spec_from_file_location(
    "check_catalogue_coverage", TOOLS / "policy/check_catalogue_coverage.py")
coverage = importlib.util.module_from_spec(spec)
sys.modules["check_catalogue_coverage"] = coverage
spec.loader.exec_module(coverage)

SOURCE = """a = Title
    .doc = What it is.

b = Settings
"""
REGISTRY = """// @generated by tilolang; locale registry.
// Edit Fluent catalogs under locales/; tilolang maintains this registry.

ui::embedded_catalog!(pub static CATALOG, ["en-US"]);
"""


def tree(files: dict[str, str]) -> tempfile.TemporaryDirectory:
    directory = tempfile.TemporaryDirectory()
    for name, text in files.items():
        path = Path(directory.name) / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
    return directory


def missing(files: dict[str, str]) -> list[tuple[str, str, str]]:
    with tree(files) as root:
        return [(unit, locale, key)
                for unit, locale, _, key, _ in coverage.untranslated(Path(root))]


def twice(files: dict[str, str]) -> list[tuple[str, str, int, int]]:
    with tree(files) as root:
        return [(catalogue.relative_to(root).as_posix(), key, first, line)
                for catalogue, key, first, line in coverage.duplicated(Path(root))]


def stale(files: dict[str, str]) -> list[tuple[str, str]]:
    """Per (registry, what is behind it), and never a fix the check cannot name."""
    with tree(files) as root:
        found = coverage.stale_registries(Path(root))
        for _, _, _, fix in found:
            assert fix.startswith("tilolang "), fix
        return [(registry.relative_to(root).as_posix(), reason)
                for _, registry, reason, _ in found]


def fix_for(files: dict[str, str]) -> list[str]:
    with tree(files) as root:
        return [fix for _, _, _, fix in coverage.stale_registries(Path(root))]


def run(files: dict[str, str], *arguments: str) -> tuple[int, str, str]:
    with tree(files) as root:
        original = coverage.ROOT
        coverage.ROOT = Path(root)
        out, err = io.StringIO(), io.StringIO()
        try:
            with redirect_stdout(out), redirect_stderr(err):
                code = coverage.main(["check", *arguments])
        finally:
            coverage.ROOT = original
        return code, out.getvalue(), err.getvalue()


class CatalogueCoverageTests(unittest.TestCase):
    def test_a_key_only_the_source_has_is_reported(self):
        found = missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n",
        })
        self.assertEqual(found, [("app", "de-DE", "b")])

    def test_an_attribute_is_a_key_of_its_own(self):
        found = missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n\nb = Einstellungen\n",
        })
        self.assertEqual(found, [("app", "de-DE", "a.doc")])

    def test_a_locale_may_add_its_own_words(self):
        self.assertEqual(missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n"
                                    "\nc = Nur auf Deutsch\n",
        }), [])

    def test_a_complete_translation_passes(self):
        self.assertEqual(missing({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n",
        }), [])

    def test_a_tagline_a_language_words_for_itself_is_not_drift(self):
        code, out, err = run({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n\n"
                                     "d-test-app-tagline = Ein Satz auf Deutsch\n",
        })
        self.assertEqual(code, 0, (out, err))

    def test_the_listing_names_each_untranslated_key_and_passes(self):
        code, out, _ = run({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n",
        }, "--list")
        self.assertEqual(code, 0)
        self.assertEqual(out, "app de-DE b\n")

    def test_a_partly_translated_catalogue_fails_and_names_the_key(self):
        code, out, err = run({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n",
        })
        self.assertEqual(code, 1)
        self.assertEqual(out, "app/locales/en-US.ftl:4: b has no de-DE text\n")
        self.assertIn("1 keys are untranslated", err)

    def test_a_key_defined_twice_is_reported_with_both_lines(self):
        self.assertEqual(twice({
            "app/locales/en-US.ftl": SOURCE + "\nb = Settings\n",
        }), [("app/locales/en-US.ftl", "b", 4, 6)])

    def test_a_translation_defining_a_key_twice_names_its_own_lines(self):
        self.assertEqual(twice({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n"
                                    "\n\nb = Optionen\n",
        }), [("app/locales/de-DE.ftl", "b", 4, 7)])

    def test_a_repeated_key_fails_even_when_the_translation_is_whole(self):
        code, out, err = run({
            "app/locales/en-US.ftl": SOURCE + "\nb = Settings\n",
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n"
                                     "\nb = Optionen\n",
        })
        self.assertEqual(code, 1)
        self.assertEqual(out, "")
        self.assertIn("app/locales/en-US.ftl:6: b is defined again; line 4 already defines it", err)
        self.assertIn("2 keys are defined twice", err)

    def test_the_listing_still_fails_on_a_repeated_key(self):
        code, _, err = run({
            "app/locales/en-US.ftl": SOURCE + "\nb = Settings\n",
        }, "--list")
        self.assertEqual(code, 1)
        self.assertIn("b is defined again", err)

    def test_a_registry_registering_every_catalog_passes(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": REGISTRY,
        }), [])

    def test_an_app_owned_registry_is_not_a_generated_one(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": "ui::embedded_catalog!(pub static CATALOG, [\"en-US\"]);\n",
        }), [])

    def test_a_catalog_the_registry_does_not_name_is_reported_with_add_locale(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n",
            "app/src/locales.rs": REGISTRY,
        }), [("app/src/locales.rs", "locales/de-DE.ftl is not registered")])
        self.assertEqual(fix_for({
            "app/locales/en-US.ftl": SOURCE,
            "app/locales/de-DE.ftl": "a = Titel\n",
            "app/src/locales.rs": REGISTRY,
        }), ["tilolang add locale de-DE"])

    def test_a_registered_locale_with_no_catalog_is_reported(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": REGISTRY.replace(
                '["en-US"]', '["de-DE", "en-US"]'
            ),
        }), [("app/src/locales.rs", "registered locale 'de-DE' has no locales/de-DE.ftl")])

    def test_a_registry_wrapping_the_declaration_is_read_the_same(self):
        self.assertEqual(stale({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": REGISTRY.replace(
                '["en-US"]', '\n        ["en-US"]\n    '
            ),
        }), [])

    def test_a_stale_registry_fails_with_the_command_that_writes_it(self):
        code, _, err = run({
            "app/locales/en-US.ftl": SOURCE,
            "app/src/locales.rs": REGISTRY.replace('["en-US"]', '["en-US", "de-DE"]'),
        })
        self.assertEqual(code, 1)
        self.assertIn("app/src/locales.rs:", err)
        self.assertIn("run `tilolang locale sync`", err)


class PackageCatalogueCoverageTests(unittest.TestCase):
    """A tilolang package commits no source catalogue: its words are the compiler's, written from
    its sources."""

    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        # A compiler that writes the package's words from a file beside its sources, and answers
        # `catalogue --help` as one that has the command does.
        self.binary = self.root / "tilolang"
        self.binary.write_text(
            "#!/usr/bin/env python3\n"
            "import pathlib, sys\n"
            "if sys.argv[1:] == ['catalogue', '--help']:\n"
            "    print('usage: tilolang catalogue <package>')\n"
            "    raise SystemExit(0)\n"
            "print((pathlib.Path(sys.argv[2]) / 'source.ftl').read_text(), end='')\n"
        )
        self.binary.chmod(0o755)
        self.original = coverage.TILOLANG
        coverage.TILOLANG = str(self.binary)

    def tearDown(self):
        coverage.TILOLANG = self.original
        self.temporary.cleanup()

    def package(self, source: str = SOURCE, german: str | None = None,
                committed: bool = False) -> None:
        files = {
            "app/app.tl": 'app test.app "App"\n',
            "app/app.ids": "App = aaaa\n",
            "app/source.ftl": source,
        }
        if german is not None:
            files["app/locales/de-DE.ftl"] = german
        if committed:
            files["app/locales/en-US.ftl"] = source
        for name, text in files.items():
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)

    def test_a_source_word_its_translation_lacks_is_reported(self):
        self.package(german="a = Titel\n    .doc = Was es ist.\n")
        self.assertEqual(
            [(unit, locale, key) for unit, locale, _, key, _ in coverage.untranslated(self.root)],
            [("app", "de-DE", "b")])

    def test_a_complete_translation_passes(self):
        self.package(german="a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n")
        self.assertEqual(coverage.untranslated(self.root), [])

    def test_a_translation_word_the_source_lacks_is_reported(self):
        self.package(german="a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n\n"
                            "c = Nur auf Deutsch\n")
        self.assertEqual(
            [(unit, locale, key) for unit, locale, _, key, _ in coverage.unnamed(self.root)],
            [("app", "de-DE", "c")])

    def test_a_committed_source_catalogue_is_refused(self):
        self.package(german="a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n",
                     committed=True)
        self.assertEqual(
            [path.relative_to(self.root).as_posix()
             for path in coverage.committed_source(self.root)],
            ["app/locales/en-US.ftl"])

    def test_the_whole_tree_names_the_committed_catalogue_and_fails(self):
        self.package(german="a = Titel\n    .doc = Was es ist.\n\nb = Einstellungen\n",
                     committed=True)
        original = coverage.ROOT
        coverage.ROOT = self.root
        out, err = io.StringIO(), io.StringIO()
        try:
            with redirect_stdout(out), redirect_stderr(err):
                code = coverage.main(["check", "--tilolang", str(self.binary)])
        finally:
            coverage.ROOT = original
        self.assertEqual(code, 1)
        self.assertIn("a tilolang package's words are its sources'", err.getvalue())


class StagedCatalogueCoverageTests(unittest.TestCase):
    """The drift a commit's own catalogues add, judged in the index it stages."""

    def setUp(self):
        import subprocess
        self.subprocess = subprocess
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.git("init", "-q")
        self.git("config", "user.name", "test")
        self.git("config", "user.email", "test@example.invalid")

    def tearDown(self):
        self.temporary.cleanup()

    def git(self, *arguments: str) -> None:
        self.subprocess.run(
            ["git", "-C", str(self.root), *arguments], check=True, capture_output=True
        )

    def commit(self, files: dict[str, str]) -> None:
        for name, text in files.items():
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "state")

    def stage(self, files: dict[str, str]) -> None:
        for name, text in files.items():
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        self.git("add", "--", *files)

    def test_a_source_key_added_without_its_translation_is_refused(self):
        self.commit({"app/locales/en-US.ftl": SOURCE,
                     "app/locales/de-DE.ftl": "a = Titel\n    .doc = Was es ist.\n\n"
                                              "b = Einstellungen\n"})
        self.stage({"app/locales/en-US.ftl": SOURCE + "\nc = Close\n"})
        self.assertEqual(coverage.staged_drift(self.root), [
            "app/locales/en-US.ftl:6: c has no de-DE text",
        ])

    def test_a_source_key_added_with_its_translation_passes(self):
        self.commit({"app/locales/en-US.ftl": SOURCE,
                     "app/locales/de-DE.ftl": SOURCE})
        self.stage({"app/locales/en-US.ftl": SOURCE + "\nc = Close\n",
                    "app/locales/de-DE.ftl": SOURCE + "\nc = Schließen\n"})
        self.assertEqual(coverage.staged_drift(self.root), [])

    def test_a_translation_key_with_no_source_original_is_refused(self):
        self.commit({"app/locales/en-US.ftl": SOURCE,
                     "app/locales/de-DE.ftl": SOURCE})
        self.stage({"app/locales/de-DE.ftl": SOURCE + "\nd = Nur auf Deutsch\n"})
        problems = coverage.staged_drift(self.root)
        self.assertEqual(problems, [
            "app/locales/de-DE.ftl:6: d has no en-US text",
        ])

    def test_a_tag_line_a_language_words_for_itself_is_not_drift(self):
        self.commit({"app/locales/en-US.ftl": SOURCE,
                     "app/locales/de-DE.ftl": SOURCE})
        self.stage({"app/locales/de-DE.ftl": SOURCE + "\nd-test-app-tagline = Ein Satz\n"})
        self.assertEqual(coverage.staged_drift(self.root), [])

    def test_a_key_a_staged_catalogue_defines_twice_is_refused(self):
        self.commit({"app/locales/en-US.ftl": SOURCE,
                     "app/locales/de-DE.ftl": SOURCE})
        self.stage({"app/locales/en-US.ftl": SOURCE + "\nb = Settings again\n"})
        problems = coverage.staged_drift(self.root)
        self.assertTrue(any("b is defined again" in problem for problem in problems), problems)

    def test_a_commit_staging_no_catalogue_adds_no_drift(self):
        self.commit({"app/locales/en-US.ftl": SOURCE,
                     "app/locales/de-DE.ftl": "a = Titel\n"})
        self.stage({"app/src/main.rs": "fn main() {}\n"})
        self.assertEqual(coverage.staged_drift(self.root), [])


class RangeCatalogueCoverageTests(unittest.TestCase):
    """The drift a range's own catalogues add, judged at its head against its base.

    A cherry-pick or a rebase writes commits the commit hook never judges, so the
    push judges what the range as a whole left behind."""

    def setUp(self):
        import subprocess
        self.subprocess = subprocess
        self.temporary = tempfile.TemporaryDirectory()
        self.root = Path(self.temporary.name)
        self.git("init", "-q")
        self.git("config", "user.name", "test")
        self.git("config", "user.email", "test@example.invalid")
        self.commit({"app/locales/en-US.ftl": SOURCE,
                     "app/locales/de-DE.ftl": SOURCE})
        self.base = self.head()

    def tearDown(self):
        self.temporary.cleanup()

    def git(self, *arguments: str) -> None:
        self.subprocess.run(
            ["git", "-C", str(self.root), *arguments], check=True, capture_output=True
        )

    def head(self) -> str:
        return self.subprocess.run(
            ["git", "-C", str(self.root), "rev-parse", "HEAD"],
            check=True, capture_output=True, text=True).stdout.strip()

    def commit(self, files: dict[str, str]) -> None:
        for name, text in files.items():
            path = self.root / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        self.git("add", "-A")
        self.git("commit", "-q", "-m", "state")

    def drift(self) -> list[str]:
        return coverage.range_drift(self.root, self.base, self.head())

    def test_a_source_key_the_range_adds_without_its_translation_is_refused(self):
        self.commit({"app/locales/en-US.ftl": SOURCE + "\nc = Close\n"})
        self.assertEqual(self.drift(), ["app/locales/en-US.ftl:6: c has no de-DE text"])

    def test_a_source_key_the_range_adds_with_its_translation_passes(self):
        self.commit({"app/locales/en-US.ftl": SOURCE + "\nc = Close\n",
                     "app/locales/de-DE.ftl": SOURCE + "\nc = Schließen\n"})
        self.assertEqual(self.drift(), [])

    def test_a_translation_key_the_range_adds_with_no_original_is_refused(self):
        self.commit({"app/locales/de-DE.ftl": SOURCE + "\nd = Nur auf Deutsch\n"})
        self.assertEqual(self.drift(), ["app/locales/de-DE.ftl:6: d has no en-US text"])

    def test_a_key_the_range_leaves_defined_twice_is_refused(self):
        self.commit({"app/locales/en-US.ftl": SOURCE + "\nb = Settings again\n"})
        problems = self.drift()
        self.assertTrue(any("b is defined again" in problem for problem in problems), problems)

    def test_the_range_is_judged_as_one_change(self):
        # A commit that adds a word and a later one that translates it: the head the
        # range sends is whole, so neither the hook's per-commit view nor the push's
        # per-range one has anything to refuse.
        self.commit({"app/locales/en-US.ftl": SOURCE + "\nc = Close\n"})
        self.commit({"app/locales/de-DE.ftl": SOURCE + "\nc = Schließen\n"})
        self.assertEqual(self.drift(), [])

    def test_a_range_touching_no_catalogue_adds_no_drift(self):
        self.commit({"app/src/main.rs": "fn main() {}\n"})
        self.assertEqual(self.drift(), [])

    def test_the_range_fails_with_the_key_and_the_reason(self):
        self.commit({"app/locales/en-US.ftl": SOURCE + "\nc = Close\n"})
        original = coverage.ROOT
        coverage.ROOT = self.root
        out, err = io.StringIO(), io.StringIO()
        try:
            with redirect_stdout(out), redirect_stderr(err):
                code = coverage.main(["check", "--range", f"{self.base}..{self.head()}"])
        finally:
            coverage.ROOT = original
        self.assertEqual(code, 1)
        self.assertEqual(out.getvalue(), "app/locales/en-US.ftl:6: c has no de-DE text\n")
        self.assertIn("1 keys this range adds are untranslated", err.getvalue())


