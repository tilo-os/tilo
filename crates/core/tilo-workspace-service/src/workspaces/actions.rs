/// This host's dispatch, as an asked record's store hands it back the call it keeps.
struct HostAsked(std::sync::Weak<Shared>);

impl HostAsked {
    fn server(&self) -> Result<ServiceWorkspaceActions, ActionCallError> {
        self.0
            .upgrade()
            .map(|shared| ServiceWorkspaceActions { shared })
            .ok_or_else(|| ActionCallError::Unavailable {
                reason: "the host's actions are not running".into(),
            })
    }
}

/// What a call that no longer waits in its record is refused another answer with.
fn not_waiting() -> ActionCallError {
    ActionCallError::Refused {
        reason: "The call no longer waits for this answer".into(),
    }
}

/// What the record of a call its caller cancelled while it waited for its person says.
const TAKEN_BACK: &str = "Whoever asked took the question back";

/// The name the store knows this host's dispatch by, across its restarts.
pub(super) const HOST_DISPATCH: &str = "host";

/// The parameters the action `target` names is published with, where it is one of the host's
/// own: a workspace's governance verbs, its vault's, its mail accounts' and its model
/// providers', by their own provider or in the governance tree. `None` for any other.
#[cfg(not(target_arch = "wasm32"))]
pub(super) fn published_params(
    target: &tilo_actions::remote::RemoteActionTarget,
) -> Option<Vec<ActionParam>> {
    let address = &target.address;
    if let Some((_, action)) = vault::vault_action(address) {
        return vault::params_of(action);
    }
    if let Some((_, action)) = mail::account_action(address) {
        return mail::account_params_of(action);
    }
    if let Some((_, action)) = models::models_action(address) {
        return models::params_of(action);
    }
    match target.provider.as_str() {
        person_vault::PROVIDER => vault::params_of(&address.action),
        person_accounts::PROVIDER => mail::account_params_of(&address.action),
        model_providers::PROVIDER => models::params_of(&address.action),
        WORKSPACE_GOVERNANCE_PROVIDER => VERBS
            .iter()
            .find(|verb| verb.id == address.action)
            .map(|verb| (verb.params)()),
        _ => None,
    }
}

