        sign_device_cert(&mut f.device, &f.root).unwrap();
        let (challenge, server) = f.issue();
        assert_eq!(server.transcript.expires_at_ns, 1_000);
        let host = verify_server(&f.client_context(), [2; 32], &server).unwrap();
