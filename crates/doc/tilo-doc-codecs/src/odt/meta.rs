//! Document properties ⇄ ODF `meta.xml`. `office:document-meta > office:meta` holds
//! `dc:title`/`dc:creator`/`dc:subject`/`meta:keyword`/`dc:date`/`meta:creation-date`/
//! `meta:generator`, mapped onto the canonical `meta.props` map both directions, while
//! preserving any unmodeled child elements verbatim on export.

use crate::xml_escape::escape_text;
use quick_xml::events::{BytesStart, Event};
use quick_xml::reader::Reader;
use std::collections::BTreeSet;
use tilo_doc::model::{DocMut, DocRef, doc_prop};
use tilo_doc::schema::{
    DOC_PROP_KEYS, PROP_AUTHOR, PROP_CREATED, PROP_GENERATOR, PROP_KEYWORDS, PROP_MODIFIED,
    PROP_SUBJECT, PROP_TITLE,
};
// `write!` into a `String` cannot fail; the discarded `Result` is the
// `fmt::Write` contract, not a swallowed error.
use std::fmt::Write as _;

/// Map an ODF element local-name (within `office:meta`) onto a canonical document-property key.
fn prop_for_element(local: &[u8]) -> Option<&'static str> {
    match local {
        b"title" => Some(PROP_TITLE),
        b"creator" => Some(PROP_AUTHOR),
        b"subject" => Some(PROP_SUBJECT),
        b"keyword" => Some(PROP_KEYWORDS),
        b"date" => Some(PROP_MODIFIED),
        b"creation-date" => Some(PROP_CREATED),
        b"generator" => Some(PROP_GENERATOR),
        _ => None,
    }
}

/// The element local-name (after any `prefix:`).
fn local_name(name: &[u8]) -> &[u8] {
    match name.iter().rposition(|&b| b == b':') {
        Some(i) => name.get(i.saturating_add(1)..).unwrap_or(name),
        None => name,
    }
}

/// Parse `meta.xml` into well-known document properties in `meta.props`; unknown elements
/// round-trip verbatim since the whole part is regenerated by merging into the original.
pub(super) fn import_meta(xml: &[u8], doc: &mut DocMut) {
    let mut reader = Reader::from_reader(xml);
    reader.config_mut().trim_text(false);
    let mut buf = Vec::new();
    let mut current: Option<&'static str> = None;
    let mut text = String::new();
    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) => {
                if let Some(prop) = prop_for_element(local_name(e.name().as_ref())) {
                    current = Some(prop);
                    text.clear();
                }
            }
            Ok(Event::Text(t)) => {
                if current.is_some()
                    && let Ok(s) = t.xml10_content()
                {
                    text.push_str(&s);
                }
            }
            Ok(Event::GeneralRef(r)) if current.is_some() => {
                text.extend(crate::resolve_general_ref(&r));
            }
            Ok(Event::End(e)) => {
                if let Some(prop) = prop_for_element(local_name(e.name().as_ref()))
                    && current == Some(prop)
                {
                    if !text.is_empty() {
                        doc.set_doc_prop(prop, &text);
                    }
                    current = None;
                    text.clear();
                }
            }
            Ok(Event::Eof) | Err(_) => break,
            _ => {}
        }
        buf.clear();
    }
}

/// The ODF element (with prefix) a canonical property maps onto inside `office:meta`.
fn element_for_prop(prop: &str) -> Option<&'static str> {
    match prop {
        PROP_TITLE => Some("dc:title"),
        PROP_AUTHOR => Some("dc:creator"),
        PROP_SUBJECT => Some("dc:subject"),
        PROP_KEYWORDS => Some("meta:keyword"),
        PROP_MODIFIED => Some("dc:date"),
        PROP_CREATED => Some("meta:creation-date"),
        PROP_GENERATOR => Some("meta:generator"),
        _ => None,
    }
}

/// Re-serialize the modeled child elements (`dc:title`, …) from the document's properties, in canonical key order.
fn modeled_children(doc: &DocRef) -> String {
    let mut out = String::new();
    for key in DOC_PROP_KEYS {
        let Some(val) = doc_prop(doc.doc, doc.c, key) else {
            continue;
        };
        let Some(el) = element_for_prop(key) else {
            continue;
        };
        let _ = write!(out, "<{el}>{}</{el}>", escape_text(&val));
    }
    out
}

/// Strip modeled child elements from an existing `office:meta` inner XML, keeping the unmodeled ones verbatim so they survive the round-trip.
fn unmodeled_children(meta_inner: &[u8]) -> String {
    let modeled: BTreeSet<&[u8]> = [
        b"title".as_slice(),
        b"creator".as_slice(),
        b"subject".as_slice(),
        b"keyword".as_slice(),
        b"date".as_slice(),
        b"creation-date".as_slice(),
        b"generator".as_slice(),
    ]
    .into_iter()
    .collect();

    let mut reader = Reader::from_reader(meta_inner);
    reader.config_mut().trim_text(false);
    let mut buf = Vec::new();
    let mut out: Vec<u8> = Vec::new();
    // Depth of the modeled element we're currently skipping (0 = not skipping).
    let mut skip_depth = 0usize;
    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) => {
                let is_modeled = modeled.contains(local_name(e.name().as_ref()));
                if skip_depth > 0 {
                    skip_depth = skip_depth.saturating_add(1);
                } else if is_modeled {
                    skip_depth = 1;
                } else {
                    append_start(&mut out, &e, false);
                }
            }
            Ok(Event::Empty(e)) => {
                let is_modeled = modeled.contains(local_name(e.name().as_ref()));
                if skip_depth == 0 && !is_modeled {
                    append_start(&mut out, &e, true);
                }
            }
            Ok(Event::End(e)) => {
                if skip_depth > 0 {
                    skip_depth = skip_depth.saturating_sub(1);
                } else {
                    out.extend_from_slice(b"</");
                    out.extend_from_slice(e.name().as_ref());
                    out.push(b'>');
                }
            }
            Ok(Event::Text(t)) => {
                if skip_depth == 0 {
                    out.extend_from_slice(t.into_inner().as_ref());
                }
            }
            // Copied through still escaped: `&amp;` has to stay `&amp;` in the output.
            Ok(Event::GeneralRef(r)) => {
                if skip_depth == 0 {
                    out.push(b'&');
                    out.extend_from_slice(&r);
                    out.push(b';');
                }
            }
            Ok(Event::Eof) | Err(_) => break,
            _ => {}
        }
        buf.clear();
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Re-emit a start tag verbatim (name + attributes), self-closing if `empty`.
fn append_start(out: &mut Vec<u8>, e: &BytesStart, empty: bool) {
    out.push(b'<');
    out.extend_from_slice(e.name().as_ref());
    for attr in e.attributes().flatten() {
        out.push(b' ');
        out.extend_from_slice(attr.key.as_ref());
        out.extend_from_slice(b"=\"");
        out.extend_from_slice(&attr.value);
        out.push(b'"');
    }
    if empty {
        out.extend_from_slice(b"/>");
    } else {
        out.push(b'>');
    }
}

/// The XML namespaces a freshly-generated `meta.xml` declares.
const META_NS: &str = concat!(
    r#"xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" "#,
    r#"xmlns:meta="urn:oasis:names:tc:opendocument:xmlns:meta:1.0" "#,
    r#"xmlns:dc="http://purl.org/dc/elements/1.1/""#,
);

/// Extract the inner XML of the first `office:meta` element from an existing `meta.xml`, if present.
fn meta_inner(xml: &[u8]) -> Option<Vec<u8>> {
    let s = xml;
    // The element is shallow (a flat list of children), so a substring search suffices.
    let text = String::from_utf8_lossy(s);
    let open = text.find("office:meta")?;
    let after_name = text.get(open..)?;
    let gt = after_name.find('>')?;
    if after_name.as_bytes().get(gt.wrapping_sub(1)) == Some(&b'/') {
        return Some(Vec::new());
    }
    let inner_start = open.checked_add(gt)?.checked_add(1)?;
    let close = text.get(inner_start..)?.find("</office:meta>")?;
    Some(
        text.get(inner_start..inner_start.checked_add(close)?)?
            .as_bytes()
            .to_vec(),
    )
}

/// Build the `meta.xml` bytes for export, preserving unmodeled `office:meta` children from
/// `original`; `None` with no properties and no original avoids a synthesized empty part.
pub(super) fn export_meta(doc: &DocRef, original: Option<&[u8]>) -> Option<Vec<u8>> {
    let modeled = modeled_children(doc);
    let preserved = original
        .and_then(meta_inner)
        .map(|inner| unmodeled_children(&inner))
        .unwrap_or_default();

    if modeled.is_empty() && preserved.trim().is_empty() && original.is_none() {
        return None;
    }
    let xml = format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<office:document-meta {META_NS}><office:meta>{preserved}{modeled}</office:meta></office:document-meta>"#
    );
    Some(xml.into_bytes())
}
