//! Document properties ⇄ ODF `meta.xml`. `office:document-meta > office:meta` holds
//! `dc:title`/`dc:creator`/`dc:subject`/`meta:keyword`/`dc:date`/`meta:creation-date`/
//! `meta:generator`, mapped onto the canonical `meta.props` map both directions, while
//! preserving any unmodeled child elements verbatim on export.

use crate::office_meta::{import_elements, unmodeled_inner};
use crate::office_props::odf::{META_NS, modeled_children, prop_for_element};
use tilo_doc::model::{DocMut, DocRef, doc_prop};

/// Parse `meta.xml` into well-known document properties in `meta.props`; unknown elements
/// round-trip verbatim since the whole part is regenerated by merging into the original.
pub(super) fn import_meta(xml: &[u8], doc: &mut DocMut) {
    import_elements(xml, doc, prop_for_element);
}

/// The `office:meta` children (by local name) the properties own.
const MODELED: [&[u8]; 7] = [
    b"title",
    b"creator",
    b"subject",
    b"keyword",
    b"date",
    b"creation-date",
    b"generator",
];

/// Build the `meta.xml` bytes for export, preserving unmodeled `office:meta` children from
/// `original`; `None` with no properties and no original avoids a synthesized empty part.
pub(super) fn export_meta(doc: &DocRef, original: Option<&[u8]>) -> Option<Vec<u8>> {
    let modeled = modeled_children(|key| doc_prop(doc.doc, doc.c, key));
    let preserved = original
        .map(|xml| unmodeled_inner(xml, "meta", &MODELED))
        .unwrap_or_default();

    if modeled.is_empty() && preserved.trim().is_empty() && original.is_none() {
        return None;
    }
    let xml = format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<office:document-meta {META_NS}><office:meta>{preserved}{modeled}</office:meta></office:document-meta>"#
    );
    Some(xml.into_bytes())
}
