//! Document properties ⇄ ODF `meta.xml`. ODF stores document metadata in a
//! `meta.xml` part: `office:document-meta > office:meta` holding `dc:title`,
//! `dc:creator`, `dc:subject`, `meta:keyword`, `dc:date` (modified),
//! `meta:creation-date` (created), and `meta:generator`. This maps those onto
//! the canonical `meta.props` document properties, both directions, while
//! preserving any unmodeled child elements verbatim on export.

use crate::model::{doc_prop, DocMut, DocRef};
use crate::schema::*;
use quick_xml::events::{BytesStart, Event};
use quick_xml::reader::Reader;
use std::collections::BTreeMap;

/// Map an ODF element local-name (within `office:meta`) onto a canonical
/// document-property key, or `None` if the element isn't one we model.
fn prop_for_element(local: &[u8]) -> Option<&'static str> {
    match local {
        b"title" => Some(PROP_TITLE),
        b"creator" => Some(PROP_AUTHOR),
        b"subject" => Some(PROP_SUBJECT),
        b"keyword" => Some(PROP_KEYWORDS),
        b"date" => Some(PROP_MODIFIED),
        b"creation-date" => Some(PROP_CREATED),
        b"generator" => Some(PROP_GENERATOR),
        _ => None,
    }
}

/// The element local-name (after any `prefix:`).
fn local_name(name: &[u8]) -> &[u8] {
    match name.iter().rposition(|&b| b == b':') {
        Some(i) => &name[i + 1..],
        None => name,
    }
}

/// Parse `meta.xml` bytes into well-known document properties, writing each into
/// the document's `meta.props` map. Unknown elements are ignored (they round-trip
/// verbatim because the whole part is regenerated by merging into the original).
pub(super) fn import_meta(xml: &[u8], doc: &mut DocMut) {
    let mut reader = Reader::from_reader(xml);
    reader.config_mut().trim_text(false);
    let mut buf = Vec::new();
    // The canonical prop name we're currently collecting text for.
    let mut current: Option<&'static str> = None;
    let mut text = String::new();
    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) => {
                if let Some(prop) = prop_for_element(local_name(e.name().as_ref())) {
                    current = Some(prop);
                    text.clear();
                }
            }
            Ok(Event::Text(t)) => {
                if current.is_some() {
                    if let Ok(s) = t.xml10_content() {
                        text.push_str(&s);
                    }
                }
            }
            Ok(Event::End(e)) => {
                if let Some(prop) = prop_for_element(local_name(e.name().as_ref())) {
                    if current == Some(prop) {
                        // Only record non-empty values, but always clear state.
                        if !text.is_empty() {
                            doc.set_doc_prop(prop, &text);
                        }
                        current = None;
                        text.clear();
                    }
                }
            }
            Ok(Event::Eof) => break,
            Err(_) => break,
            _ => {}
        }
        buf.clear();
    }
}

/// Escape text for XML element content.
fn escape_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            _ => out.push(c),
        }
    }
    out
}

/// The ODF element (with prefix) a canonical property maps onto inside
/// `office:meta`.
fn element_for_prop(prop: &str) -> Option<&'static str> {
    match prop {
        PROP_TITLE => Some("dc:title"),
        PROP_AUTHOR => Some("dc:creator"),
        PROP_SUBJECT => Some("dc:subject"),
        PROP_KEYWORDS => Some("meta:keyword"),
        PROP_MODIFIED => Some("dc:date"),
        PROP_CREATED => Some("meta:creation-date"),
        PROP_GENERATOR => Some("meta:generator"),
        _ => None,
    }
}

/// Re-serialize the modeled child elements (`dc:title`, …) of `office:meta` from
/// the document's properties, in the canonical key order.
fn modeled_children(doc: &DocRef) -> String {
    let mut out = String::new();
    for key in DOC_PROP_KEYS {
        let Some(val) = doc_prop(doc.doc, doc.c, key) else { continue };
        let Some(el) = element_for_prop(key) else { continue };
        out.push_str(&format!("<{el}>{}</{el}>", escape_text(&val)));
    }
    out
}

/// Strip any modeled child elements from an existing `office:meta` inner XML,
/// keeping the unmodeled ones verbatim (so they survive the round-trip even
/// though we regenerate the part). Returns the surviving inner XML.
fn unmodeled_children(meta_inner: &[u8]) -> String {
    let modeled: BTreeMap<&[u8], ()> = [
        b"title".as_slice(),
        b"creator".as_slice(),
        b"subject".as_slice(),
        b"keyword".as_slice(),
        b"date".as_slice(),
        b"creation-date".as_slice(),
        b"generator".as_slice(),
    ]
    .into_iter()
    .map(|k| (k, ()))
    .collect();

    let mut reader = Reader::from_reader(meta_inner);
    reader.config_mut().trim_text(false);
    let mut buf = Vec::new();
    let mut out: Vec<u8> = Vec::new();
    // Depth of the modeled element we're currently skipping (0 = not skipping).
    let mut skip_depth = 0usize;
    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) => {
                let is_modeled = modeled.contains_key(local_name(e.name().as_ref()));
                if skip_depth > 0 {
                    skip_depth += 1;
                } else if is_modeled {
                    skip_depth = 1;
                } else {
                    append_start(&mut out, &e, false);
                }
            }
            Ok(Event::Empty(e)) => {
                let is_modeled = modeled.contains_key(local_name(e.name().as_ref()));
                if skip_depth == 0 && !is_modeled {
                    append_start(&mut out, &e, true);
                }
            }
            Ok(Event::End(e)) => {
                if skip_depth > 0 {
                    skip_depth -= 1;
                } else {
                    out.extend_from_slice(b"</");
                    out.extend_from_slice(e.name().as_ref());
                    out.push(b'>');
                }
            }
            Ok(Event::Text(t)) => {
                if skip_depth == 0 {
                    out.extend_from_slice(t.into_inner().as_ref());
                }
            }
            Ok(Event::Eof) => break,
            Err(_) => break,
            _ => {}
        }
        buf.clear();
    }
    String::from_utf8_lossy(&out).into_owned()
}

/// Re-emit a start tag verbatim (name + attributes), self-closing if `empty`.
fn append_start(out: &mut Vec<u8>, e: &BytesStart, empty: bool) {
    out.push(b'<');
    out.extend_from_slice(e.name().as_ref());
    for attr in e.attributes().flatten() {
        out.push(b' ');
        out.extend_from_slice(attr.key.as_ref());
        out.extend_from_slice(b"=\"");
        out.extend_from_slice(&attr.value);
        out.push(b'"');
    }
    if empty {
        out.extend_from_slice(b"/>");
    } else {
        out.push(b'>');
    }
}

/// The XML namespaces a freshly-generated `meta.xml` declares.
const META_NS: &str = concat!(
    r#"xmlns:office="urn:oasis:names:tc:opendocument:xmlns:office:1.0" "#,
    r#"xmlns:meta="urn:oasis:names:tc:opendocument:xmlns:meta:1.0" "#,
    r#"xmlns:dc="http://purl.org/dc/elements/1.1/""#,
);

/// Extract the inner XML of the first `office:meta` element from an existing
/// `meta.xml`, if present.
fn meta_inner(xml: &[u8]) -> Option<Vec<u8>> {
    let s = xml;
    // Find `<...office:meta...>` open tag end and the matching close. The element
    // is shallow (a flat list of children) so a simple substring search suffices.
    let text = String::from_utf8_lossy(s);
    let open = text.find("office:meta")?;
    // Locate the '>' that ends that opening tag.
    let after_name = &text[open..];
    let gt = after_name.find('>')?;
    // If the opening tag is self-closing there are no children.
    if after_name.as_bytes().get(gt.wrapping_sub(1)) == Some(&b'/') {
        return Some(Vec::new());
    }
    let inner_start = open + gt + 1;
    let close = text[inner_start..].find("</office:meta>")?;
    Some(text[inner_start..inner_start + close].as_bytes().to_vec())
}

/// Build the `meta.xml` bytes for export: regenerate the modeled properties from
/// the document, preserving any unmodeled `office:meta` children from `original`.
/// Returns `None` when there are no properties to write *and* no original part
/// (so we don't synthesise an empty metadata part for documents that never had
/// one — keeps the minimal-doc round-trip byte-stable).
pub(super) fn export_meta(doc: &DocRef, original: Option<&[u8]>) -> Option<Vec<u8>> {
    let modeled = modeled_children(doc);
    let preserved = original.and_then(meta_inner).map(|inner| unmodeled_children(&inner)).unwrap_or_default();

    if modeled.is_empty() && preserved.trim().is_empty() && original.is_none() {
        return None;
    }
    let xml = format!(
        r#"<?xml version="1.0" encoding="UTF-8"?>
<office:document-meta {META_NS}><office:meta>{preserved}{modeled}</office:meta></office:document-meta>"#
    );
    Some(xml.into_bytes())
}
