# Sourced by every web runtime build step. The core and each app side module
# must be compiled with exactly these settings: they are part of the runtime
# ABI id (abi.mjs), and a unit built differently has other symbol names.

web_scripts=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
repo=$(cd "$web_scripts/../../../../.." && pwd)
web_crate="$repo/crates/browser/tilo-browser-runtime"
web_target=wasm32-unknown-unknown
# The release profile, in its own artifact directory, with what dynamic
# linking cannot use overridden (no separate profile duplicating the graph):
#   LTO internalises the toolkit symbols side modules import; the symbol-size
#   profile needs the name section, which wasm-opt drops afterwards; debug info
#   only costs disk. panic=abort stays, and is part of the runtime ABI id.
web_profile=release
export CARGO_PROFILE_RELEASE_LTO=false
export CARGO_PROFILE_RELEASE_STRIP=none
export CARGO_PROFILE_RELEASE_DEBUG=0
# Size over speed: the core is downloaded before anything runs.
export CARGO_PROFILE_RELEASE_OPT_LEVEL=${TILO_WEB_OPT_LEVEL:-z}
# The native runtime bundle this web runtime corresponds to; tilo-app.toml's
# `runtime` names the same string.
web_runtime_name=tilo-runtime/2026.07
# Read Cargo's ordinary artifact location without changing its cache key.
web_artifacts="${CARGO_TARGET_DIR:-$repo/target}/$web_target/$web_profile"

# Every crate is position independent so side modules can reference the
# core's data through their GOT; the core itself is linked non-PIE.
unset CARGO_ENCODED_RUSTFLAGS CARGO_BUILD_RUSTFLAGS
export RUSTFLAGS="-C relocation-model=pic"
export CARGO_TARGET_WASM32_UNKNOWN_UNKNOWN_RUSTFLAGS="$RUSTFLAGS"
# The core's link keeps these toolkit crates whole: apps may call any of
# their functions, not only those the core happens to use.
export CARGO_TARGET_WASM32_UNKNOWN_UNKNOWN_LINKER="$web_scripts/tilo-wasm-ld"
export TILO_WEB_WHOLE_CRATES="tilo_app tilo_ui tilo_resource tilo_actions"
export TILO_WEB_LINK_STASH="$web_artifacts/web-core-link"
web_jobs=${TILO_WEB_JOBS:-4}

# The web app collection. As runtime-dylib must be the superset of what every
# thin app needs, the core is built in one Cargo invocation with these apps, so
# every crate they share with it has the features all of them need; an app
# built later in the same invocation then shares the core's units exactly.
# An app outside it that needs more is refused until it joins, which changes
# the runtime ABI id.
read -r -a web_collection <<<"${TILO_WEB_COLLECTION:-ebook word-processor}"
# Cargo arguments selecting the core, the collection and any extra packages.
web_roots() {
  local roots=(-p tilo-browser-runtime) package
  for package in "${web_collection[@]}" "$@"; do roots+=(-p "$package"); done
  printf '%s\n' "${roots[@]}"
}

web_cargo() {
  (cd "$repo" && cargo "$1" --locked --profile "$web_profile" --target "$web_target" -j "$web_jobs" "${@:2}")
}

# Package ids (name@version) in each root's graph: {"<root>": [...]}. Proc
# macros and what they depend on build for the host, so they are no part of
# the core a side module links against.
web_graph() {
  (cd "$repo" && cargo tree --locked --target "$web_target" -e normal,no-proc-macro --prefix none --no-dedupe -f '{p}' "$@") |
    node "$web_scripts/side-module.mjs" graph
}

# json FIELD < JSON: one field (dotted path) as text; arrays space-separated.
web_json() {
  node -e 'const v=JSON.parse(require("fs").readFileSync(0,"utf8"));const r=process.argv[1].split(".").reduce((o,k)=>o[k],v);console.log(Array.isArray(r)?r.join(" "):r)' "$1"
}

# web_link_side_module PLAN_JSON INFO_JSON WORK OUT_WASM: compile the
# registration shim, the only generated code and all an app needs, and link
# it with the objects of the app's own crates (the plan's `link`) into a
# position-independent side module whose unresolved symbols are imports.
web_link_side_module() {
  local plan=$1 info=$2 work=$3 out=$4 crate app_rlib index=0 rlib dir
  crate=$(web_json crate <<<"$info")
  app_rlib=$(web_json appRlib <<<"$plan")
  mkdir -p "$work/objects"
  cat >"$work/shim.rs" <<RS
//! Generated by build-web-app.sh: installs ${crate}'s definition in the web core.
unsafe extern "C" {
    fn tilo_runtime_register_app(definition: *const core::ffi::c_void) -> u32;
}

#[unsafe(no_mangle)]
pub extern "C" fn tilo_app_register() -> u32 {
    let definition = ::${crate}::definition();
    // SAFETY: the loader instantiates this module only against a core of the
    // runtime ABI it was built for, and the definition is 'static.
    unsafe { tilo_runtime_register_app(core::ptr::from_ref(definition).cast()) }
}
RS
  # shellcheck disable=SC2086 # RUSTFLAGS is a flag list.
  (cd "$repo" && rustc --edition 2024 --crate-name tilo_app_shim --crate-type rlib --emit "obj=$work/shim.o" \
    --target "$web_target" -C "opt-level=$CARGO_PROFILE_RELEASE_OPT_LEVEL" -C panic=abort -C codegen-units=1 $RUSTFLAGS \
    -L "dependency=$web_artifacts/deps" -L "dependency=${CARGO_TARGET_DIR:-$repo/target}/$web_profile/deps" \
    --extern "$crate=$app_rlib" "$work/shim.rs")
  for rlib in $(web_json link <<<"$plan"); do
    dir="$work/objects/$index-$(basename "$rlib" .rlib)"
    mkdir -p "$dir"
    (cd "$dir" && ar x "$rlib")
    rm -f "$dir/lib.rmeta"
    index=$((index + 1))
  done
  echo "== $(web_json id <<<"$info"): linking $index crate(s) of its own:" \
    $(for dir in "$work"/objects/*; do basename "$dir" | sed -E 's/^[0-9]+-lib//; s/-[0-9a-f]+$//'; done) >&2
  wasm-ld --experimental-pic -shared --unresolved-symbols=import-dynamic -Bsymbolic --no-export-dynamic \
    --export=tilo_app_register -o "$out" "$work/shim.o" "$work"/objects/*/*.o
  rm -rf "$work/objects" "$work/shim.o"
}

need_tool() {
  command -v "$1" >/dev/null || { echo "missing tool: $1 ($2)" >&2; exit 2; }
}
