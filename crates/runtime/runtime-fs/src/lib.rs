#[cfg(test)]
mod tests {
    use super::*;
    use std::env;

    fn clear_tilo_env() -> tilo_test_env::ScopedEnv {
        let mut scoped = tilo_test_env::ScopedEnv::new();
        for (key, _) in env::vars() {
            if key.starts_with("TILO_") {
                scoped.remove(&key);
            }
        }
        scoped
    }

    #[test]
    fn try_connect_without_env_returns_service_fd_missing() {
        let _env = clear_tilo_env();
        match try_connect() {
            Err(NotAvailable::ServiceFdMissing) => {}
            Err(other) => panic!("unexpected error: {other:?}"),
            Ok(_) => panic!("expected ServiceFdMissing"),
        }
    }

    #[test]
    fn open_mode_maps_to_wire_enum() {
        // The conversion preserves each wire variant; a schema reorder would
        // fail to compile.
        assert!(matches!(
            fs_capnp::OpenMode::from(OpenMode::Read),
            fs_capnp::OpenMode::Read
        ));
        assert!(matches!(
            fs_capnp::OpenMode::from(OpenMode::Write),
            fs_capnp::OpenMode::Write
        ));
        assert!(matches!(
            fs_capnp::OpenMode::from(OpenMode::Append),
            fs_capnp::OpenMode::Append
        ));
    }
}
