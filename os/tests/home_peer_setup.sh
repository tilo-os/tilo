#!/usr/bin/env bash
set -euo pipefail
root="$(cd "$(dirname "$0")/../.." && pwd)"
helper="$root/crates/hosting/qos-relay/src/home_peer_control.rs"
enroll="$root/crates/hosting/qos-relay/src/enroll.rs"
firstboot="$root/os/usr/libexec/qos-relay-firstboot"
policy="$root/os/usr/share/polkit-1/actions/org.qos.home-peer.policy"
rule="$root/os/etc/polkit-1/rules.d/49-qos-home-peer.rules"
firstboot_unit="$root/os/usr/lib/systemd/system/qos-relay-firstboot.service"
replica_unit="$root/os/usr/lib/systemd/system/qos-fs-replica.service"
relay_unit="$root/os/usr/lib/systemd/system/qos-relay.service"
grep -q 'serde(deny_unknown_fields)' "$helper"
grep -q 'MAX_REQUEST' "$helper"
grep -q 'configuration was rolled back' "$helper"
grep -q 'PKEXEC_UID' "$helper"
grep -q 'identity root must be the requesting user' "$helper"
grep -q 'export-home-peer' "$helper"
grep -q '\.mode(0o700)' "$helper"
grep -q 'qos-enroll join' "$firstboot"
grep -q 'qos-enroll pair' "$firstboot"
grep -q 'home-peer-output /etc/qos/home-peer.toml' "$firstboot"
grep -q '\[\[ -s "\$cert" && -s "\$home_peer" \]\]' "$firstboot"
cert_check_line="$(grep -n '\[\[ -s "\$cert" && -s "\$home_peer" \]\]' "$firstboot" | cut -d: -f1)"
pair_line="$(grep -n 'qos-enroll pair' "$firstboot" | cut -d: -f1)"
(( cert_check_line < pair_line ))
grep -q 'atomic_file::write_with_mode' "$enroll"
grep -q '0o644' "$enroll"
grep -q 'relay_service_node_id' "$enroll"
grep -q '/usr/libexec/qos-home-peer-control' "$policy"
! grep -q 'allow_active>yes' "$policy"
grep -q 'subject.local && subject.active && subject.isInGroup("wheel")' "$rule"
grep -q 'Before=qos-relay.service qos-fs-replica.service' "$firstboot_unit"
! grep -q '^ConditionPathExists=/etc/qos/enrollment-token.txt' "$firstboot_unit"
grep -q 'After=network-online.target qos-relay-firstboot.service' "$replica_unit"
grep -q 'Requires=qos-relay-firstboot.service' "$replica_unit"
grep -q 'After=network-online.target qos-relay-firstboot.service' "$relay_unit"
grep -q 'Requires=qos-relay-firstboot.service' "$relay_unit"
grep -q 'qos-relay-firstboot.service /usr/lib/systemd/system/qos-relay-firstboot.service' "$root/os/Containerfile"
echo "home-peer setup boundary: ok"
