#!/usr/bin/env python3
"""The RPM packages the production image builder installs, one per line.

    builder-packages.py            print them
    builder-packages.py --write    regenerate os/scripts/builder-packages.txt

The dev image (os/Containerfile.dev) compiles its binaries with, and ships for
in-VM builds, the production image's `builder` stage toolchain: the same C
toolchain, -devel libraries and sccache, from the same frozen RPM snapshot.
os/Containerfile is deliberately not in the build context, so the dev image
installs the list from builder-packages.txt, which this script generates from
the builder stage. tools/policy/check_dev_image_contract.py fails when the two
differ. Parsing is shared with os/dev/derive-rpm-package-set.py, which decides
what the snapshot contains.

The one exception is the Rust compiler. The dev image takes the release
rust-toolchain.toml pins, not Fedora's rust and cargo packages, whose version
moves whenever the snapshot is refreshed; so those two are left out.
"""

from __future__ import annotations

import argparse
import importlib.util
import platform
import re
import sys
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
LIST = REPO / "os/scripts/builder-packages.txt"
# Fedora's Rust compiler packages. The dev image installs the toolchain
# rust-toolchain.toml pins instead (os/Containerfile.dev, rust-toolchain stage).
RUST_COMPILER_PACKAGES = frozenset({"rust", "cargo"})
HEADER = ("# Generated by os/scripts/builder-packages.py from os/Containerfile's builder\n"
          "# stage; regenerate with `python3 os/scripts/builder-packages.py --write`.\n")


def derive_module():
    path = REPO / "os/dev/derive-rpm-package-set.py"
    spec = importlib.util.spec_from_file_location("derive_rpm_package_set", path)
    module = importlib.util.module_from_spec(spec)
    assert spec.loader is not None
    spec.loader.exec_module(module)
    return module


def stage_text(text: str, stage: str) -> str:
    """The instructions of `FROM ... AS <stage>`, up to the next FROM."""
    lines = text.splitlines(keepends=True)
    start = next((i for i, line in enumerate(lines)
                  if re.match(rf"^FROM\s+\S+\s+AS\s+{re.escape(stage)}\s*$", line, re.I)), None)
    if start is None:
        raise SystemExit(f"builder-packages: no `FROM ... AS {stage}` stage in the Containerfile")
    end = next((i for i in range(start + 1, len(lines)) if re.match(r"^FROM\s", lines[i], re.I)), len(lines))
    return "".join(lines[start:end])


def builder_packages(containerfile: Path, stage: str = "builder-base", arch: str = "x86_64") -> list[str]:
    derive = derive_module()
    with tempfile.NamedTemporaryFile("w", suffix=".Containerfile") as handle:
        handle.write(stage_text(containerfile.read_text(encoding="utf-8"), stage))
        handle.flush()
        specs = sorted(set(derive.packages(Path(handle.name), arch)) - RUST_COMPILER_PACKAGES)
    if not specs:
        raise SystemExit(f"builder-packages: stage {stage!r} installs no packages")
    return specs


def render(specs: list[str]) -> str:
    return HEADER + "".join(f"{spec}\n" for spec in specs)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--containerfile", type=Path, default=REPO / "os/Containerfile")
    parser.add_argument("--stage", default="builder-base")
    parser.add_argument("--write", action="store_true", help=f"regenerate {LIST.relative_to(REPO)}")
    args = parser.parse_args()
    arch = platform.machine().lower()
    arch = {"amd64": "x86_64", "arm64": "aarch64"}.get(arch, arch)
    specs = builder_packages(args.containerfile, args.stage, arch)
    if args.write:
        LIST.write_text(render(specs), encoding="utf-8")
    else:
        print("\n".join(specs))
    return 0


if __name__ == "__main__":
    sys.exit(main())
