//! Live system integration — translating the in-memory [`FirewallConfig`]
//! into `firewall-cmd` invocations and (optionally) applying them.
//!
//! This is **gated**: nothing here runs during `--shots` or in the headless
//! renderer. The live app calls [`Backend::detect`] once at startup; if
//! `firewall-cmd` is on `$PATH` *and* `QOS_FIREWALL_APPLY=1` is set, applies
//! are executed for real. Otherwise the backend stays in **dry-run** mode
//! and only records the commands it *would* run, which the UI surfaces in
//! the apply preview. This keeps the app safe to demo on any machine while
//! still being a genuine firewalld front-end when explicitly armed.
//!
//! We deliberately model the firewalld "runtime vs permanent" split with a
//! `--permanent` flag and a trailing `--reload`, matching how an operator
//! would persist changes.

use std::process::Command;

use crate::model::{Action, FirewallConfig, Matcher, Proto, Rule, Target, Zone, ZoneKind};

/// How the backend will treat apply requests.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    /// `firewall-cmd` present and `QOS_FIREWALL_APPLY=1` — commands run.
    Live,
    /// Commands are generated but never executed.
    DryRun,
}

pub struct Backend {
    mode: Mode,
    /// The last command plan generated by [`Backend::plan`]. Surfaced in
    /// the UI's apply preview.
    last_plan: Vec<String>,
}

impl Backend {
    /// Inspect the environment and decide the operating mode.
    pub fn detect() -> Self {
        let has_cmd = which_firewall_cmd();
        let armed = std::env::var("QOS_FIREWALL_APPLY").as_deref() == Ok("1");
        let mode = if has_cmd && armed {
            Mode::Live
        } else {
            Mode::DryRun
        };
        Self {
            mode,
            last_plan: Vec::new(),
        }
    }

    pub fn mode(&self) -> Mode {
        self.mode
    }

    pub fn last_plan(&self) -> &[String] {
        &self.last_plan
    }

    /// Generate the full `firewall-cmd` plan for `cfg` without running it.
    /// Stores the plan in `last_plan` and returns a reference to it.
    pub fn plan(&mut self, cfg: &FirewallConfig) -> &[String] {
        self.last_plan = plan_commands(cfg);
        &self.last_plan
    }

    /// Apply the plan for `cfg`. In [`Mode::DryRun`] this only regenerates
    /// the plan (no side effects) and returns `Ok(())`. In [`Mode::Live`]
    /// it executes each command, stopping at the first failure.
    pub fn apply(&mut self, cfg: &FirewallConfig) -> Result<(), String> {
        let plan = plan_commands(cfg);
        self.last_plan = plan.clone();
        if self.mode == Mode::DryRun {
            return Ok(());
        }
        for line in &plan {
            let parts: Vec<&str> = line.split_whitespace().collect();
            let Some((bin, args)) = parts.split_first() else {
                continue;
            };
            let status = Command::new(bin)
                .args(args)
                .status()
                .map_err(|e| format!("spawn {bin}: {e}"))?;
            if !status.success() {
                return Err(format!("`{line}` exited with {status}"));
            }
        }
        Ok(())
    }
}

/// Whether `firewall-cmd` is resolvable on `$PATH`.
fn which_firewall_cmd() -> bool {
    let Ok(path) = std::env::var("PATH") else {
        return false;
    };
    std::env::split_paths(&path).any(|p| p.join("firewall-cmd").is_file())
}

/// Run a read-only `firewall-cmd` query and return its trimmed stdout.
/// Every argument set passed here is a query (`--get-*`, `--list-all`,
/// `--query-*`, `--state`) — never a mutation — so importing the live
/// firewall has no side effects and needs no elevation on a normal
/// polkit-configured host.
fn query(args: &[&str]) -> Result<String, String> {
    let out = Command::new("firewall-cmd")
        .args(args)
        .output()
        .map_err(|e| format!("spawn firewall-cmd: {e}"))?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).trim().to_string());
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Read the **real** current firewall from the host via `firewall-cmd`.
///
/// Returns `None` when firewalld is not installed or not running — the
/// caller then shows an honest "unavailable" state rather than any
/// fabricated ruleset. When firewalld is running this reflects exactly what
/// the host has configured: the default zone, panic mode, and — for each of
/// the nine stock zones that exists — its interfaces, services, simple
/// port openings, masquerade flag, and rich rules.
pub fn import() -> Option<FirewallConfig> {
    if !which_firewall_cmd() {
        return None;
    }
    // firewalld must actually be running; `--state` prints "running".
    if query(&["--state"]).ok().as_deref() != Some("running") {
        return None;
    }

    let default_name = query(&["--get-default-zone"]).ok()?;
    let default_zone = ZoneKind::from_name(&default_name).unwrap_or(ZoneKind::Public);
    let panic_mode = query(&["--query-panic"]).is_ok_and(|s| s == "yes");

    let zone_names = query(&["--get-zones"]).unwrap_or_default();
    let mut zones = Vec::new();
    for name in zone_names.split_whitespace() {
        let Some(kind) = ZoneKind::from_name(name) else {
            continue;
        };
        if let Ok(text) = query(&["--zone", name, "--list-all"]) {
            zones.push(parse_list_all(kind, &text));
        }
    }

    Some(FirewallConfig {
        enabled: true,
        panic_mode,
        default_zone,
        zones,
    })
}

/// Parse the block emitted by `firewall-cmd --zone=<z> --list-all` into a
/// [`Zone`]. Pure — no IO — so it is unit-testable against captured output.
pub fn parse_list_all(kind: ZoneKind, text: &str) -> Zone {
    let mut zone = Zone::new(kind, Target::Default);
    let mut in_rich = false;
    for raw in text.lines() {
        // Rich-rule lines are indented under the `rich rules:` header; once
        // we've seen that header every subsequent `rule ...` line is one.
        let trimmed = raw.trim();
        if in_rich {
            if let Some(rule) = parse_rich_rule(trimmed) {
                zone.rules.push(rule);
                continue;
            }
            // A non-rule, non-empty line ends the rich-rule block.
            if !trimmed.is_empty() && !trimmed.starts_with("rule ") {
                in_rich = false;
            }
        }
        let Some((key, value)) = trimmed.split_once(':') else {
            continue;
        };
        let key = key.trim();
        let value = value.trim();
        match key {
            "target" => zone.target = parse_target(value),
            "interfaces" => {
                zone.interfaces = value.split_whitespace().map(str::to_string).collect();
            }
            "services" => zone.services = value.split_whitespace().map(str::to_string).collect(),
            "ports" => {
                for spec in value.split_whitespace() {
                    if let Some(m) = parse_port_spec(spec) {
                        zone.rules.push(Rule::new(m, Action::Allow, ""));
                    }
                }
            }
            "masquerade" => zone.masquerade = value == "yes",
            "rich rules" => in_rich = true,
            _ => {}
        }
    }
    zone
}

/// Map a firewalld target string to a [`Target`].
fn parse_target(s: &str) -> Target {
    match s {
        "ACCEPT" => Target::Accept,
        "DROP" => Target::Drop,
        "%%REJECT%%" | "REJECT" => Target::Reject,
        _ => Target::Default,
    }
}

/// Parse a `port/proto` spec (e.g. `8080/tcp`) into a [`Matcher::Port`].
fn parse_port_spec(spec: &str) -> Option<Matcher> {
    let (port, proto) = spec.split_once('/')?;
    let proto = match proto {
        "udp" => Proto::Udp,
        _ => Proto::Tcp,
    };
    Some(Matcher::Port {
        port: port.to_string(),
        proto,
    })
}

/// Parse a single firewalld rich-rule line into a [`Rule`]. Understands the
/// subset the app can represent: an accept/reject verb, an optional
/// `source address`, and either a `service name` or a `port`/`protocol`.
/// Returns `None` for rich rules outside that subset (e.g. masquerade or
/// icmp-type rules) so they're skipped rather than misrepresented.
pub fn parse_rich_rule(line: &str) -> Option<Rule> {
    if !line.starts_with("rule ") {
        return None;
    }
    let action = if line.contains(" accept") {
        Action::Allow
    } else if line.contains(" reject") || line.contains(" drop") {
        Action::Deny
    } else {
        return None;
    };
    let source = quoted_after(line, "source address=").unwrap_or_default();
    let matcher = if let Some(svc) = quoted_after(line, "service name=") {
        Matcher::Service(svc)
    } else {
        let port = quoted_after(line, "port port=")?;
        let proto = match quoted_after(line, "protocol=").as_deref() {
            Some("udp") => Proto::Udp,
            _ => Proto::Tcp,
        };
        Matcher::Port { port, proto }
    };
    Some(Rule::new(matcher, action, source))
}

/// Read the double-quoted value immediately following `needle` in `hay`.
fn quoted_after(hay: &str, needle: &str) -> Option<String> {
    let rest = &hay[hay.find(needle)? + needle.len()..];
    let rest = rest.strip_prefix('"')?;
    let end = rest.find('"')?;
    Some(rest[..end].to_string())
}

/// Build the ordered list of `firewall-cmd` commands that would realise
/// `cfg`. Pure — no IO — so it is unit-testable.
pub fn plan_commands(cfg: &FirewallConfig) -> Vec<String> {
    let mut out = Vec::new();

    out.push(format!(
        "firewall-cmd --set-default-zone={}",
        cfg.default_zone.name()
    ));
    if cfg.panic_mode {
        out.push("firewall-cmd --panic-on".to_string());
    } else {
        out.push("firewall-cmd --panic-off".to_string());
    }

    for z in &cfg.zones {
        plan_zone(z, &mut out);
    }

    out.push("firewall-cmd --reload".to_string());
    out
}

fn plan_zone(z: &Zone, out: &mut Vec<String>) {
    let zone = z.kind.name();
    for iface in &z.interfaces {
        out.push(format!(
            "firewall-cmd --permanent --zone={zone} --change-interface={iface}"
        ));
    }
    if z.masquerade {
        out.push(format!(
            "firewall-cmd --permanent --zone={zone} --add-masquerade"
        ));
    }
    for svc in &z.services {
        out.push(format!(
            "firewall-cmd --permanent --zone={zone} --add-service={svc}"
        ));
    }
    for r in &z.rules {
        if !r.enabled {
            continue;
        }
        out.push(rich_rule(zone, r.matcher.clone(), r.action, &r.source));
    }
}

/// Render a single rule as either a simple `--add-port` (allow, anywhere,
/// port matcher) or a full firewalld rich-rule string otherwise.
fn rich_rule(zone: &str, matcher: Matcher, action: Action, source: &str) -> String {
    let has_source = !source.trim().is_empty();
    // Simple fast-path: allow a port from anywhere → plain --add-port.
    if action == Action::Allow
        && !has_source
        && let Matcher::Port { port, proto } = &matcher
    {
        return format!(
            "firewall-cmd --permanent --zone={zone} --add-port={port}/{}",
            proto.label()
        );
    }

    let mut rule = String::from("rule family=\"ipv4\"");
    if has_source {
        rule.push_str(&format!(" source address=\"{}\"", source.trim()));
    }
    match &matcher {
        Matcher::Service(s) => rule.push_str(&format!(" service name=\"{s}\"")),
        Matcher::Port { port, proto } => rule.push_str(&format!(
            " port port=\"{port}\" protocol=\"{}\"",
            proto.label()
        )),
    }
    let verb = match action {
        Action::Allow => "accept",
        Action::Deny => "reject",
    };
    rule.push_str(&format!(" {verb}"));
    format!("firewall-cmd --permanent --zone={zone} --add-rich-rule='{rule}'")
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Proto, Target, ZoneKind};

    #[test]
    fn plan_sets_default_zone_and_reloads() {
        let cfg = crate::sample::sample_config();
        let plan = plan_commands(&cfg);
        assert_eq!(
            plan.first().unwrap(),
            "firewall-cmd --set-default-zone=public"
        );
        assert_eq!(plan.last().unwrap(), "firewall-cmd --reload");
    }

    #[test]
    fn allow_port_anywhere_uses_add_port_fastpath() {
        let s = rich_rule(
            "public",
            Matcher::Port {
                port: "51820".into(),
                proto: Proto::Udp,
            },
            Action::Allow,
            "",
        );
        assert_eq!(
            s,
            "firewall-cmd --permanent --zone=public --add-port=51820/udp"
        );
    }

    #[test]
    fn deny_with_source_uses_rich_rule() {
        let s = rich_rule(
            "public",
            Matcher::Port {
                port: "3389".into(),
                proto: Proto::Tcp,
            },
            Action::Deny,
            "0.0.0.0/0",
        );
        assert!(s.contains("--add-rich-rule="));
        assert!(s.contains("source address=\"0.0.0.0/0\""));
        assert!(s.contains("port port=\"3389\" protocol=\"tcp\""));
        assert!(s.contains("reject"));
    }

    #[test]
    fn service_allow_with_source_is_rich_rule() {
        let s = rich_rule(
            "work",
            Matcher::Service("ipp".into()),
            Action::Allow,
            "192.168.0.0/16",
        );
        assert!(s.contains("service name=\"ipp\""));
        assert!(s.contains("accept"));
        assert!(s.contains("192.168.0.0/16"));
    }

    #[test]
    fn masquerade_zone_emits_add_masquerade() {
        let mut z = Zone::new(ZoneKind::External, Target::Default);
        z.masquerade = true;
        let mut out = Vec::new();
        plan_zone(&z, &mut out);
        assert!(out.iter().any(|l| l.contains("--add-masquerade")));
    }

    const LIST_ALL: &str = "\
public (active)
  target: default
  icmp-block-inversion: no
  interfaces: wlan0 eth0
  sources:
  services: dhcpv6-client mdns ssh
  ports: 8080/tcp 51820/udp
  protocols:
  masquerade: no
  forward-ports:
  source-ports:
  icmp-blocks:
  rich rules:
\trule family=\"ipv4\" source address=\"192.168.1.0/24\" service name=\"https\" accept
\trule family=\"ipv4\" port port=\"23\" protocol=\"tcp\" reject
";

    #[test]
    fn parse_list_all_reads_real_zone_fields() {
        let z = parse_list_all(ZoneKind::Public, LIST_ALL);
        assert_eq!(z.target, Target::Default);
        assert_eq!(z.interfaces, vec!["wlan0", "eth0"]);
        assert_eq!(z.services, vec!["dhcpv6-client", "mdns", "ssh"]);
        assert!(!z.masquerade);
        // Two simple ports become allow-from-anywhere rules...
        assert!(z.rules.iter().any(|r| r.matcher
            == Matcher::Port {
                port: "8080".into(),
                proto: Proto::Tcp
            }
            && r.action == Action::Allow
            && r.source.is_empty()));
        assert!(z.rules.iter().any(|r| r.matcher
            == Matcher::Port {
                port: "51820".into(),
                proto: Proto::Udp
            }));
        // ...plus the two rich rules.
        assert!(
            z.rules
                .iter()
                .any(|r| r.matcher == Matcher::Service("https".into())
                    && r.action == Action::Allow
                    && r.source == "192.168.1.0/24")
        );
        assert!(z.rules.iter().any(|r| r.matcher
            == Matcher::Port {
                port: "23".into(),
                proto: Proto::Tcp
            }
            && r.action == Action::Deny));
    }

    #[test]
    fn parse_rich_rule_service_accept_with_source() {
        let r = parse_rich_rule(
            "rule family=\"ipv4\" source address=\"10.8.0.0/24\" service name=\"cockpit\" accept",
        )
        .unwrap();
        assert_eq!(r.matcher, Matcher::Service("cockpit".into()));
        assert_eq!(r.action, Action::Allow);
        assert_eq!(r.source, "10.8.0.0/24");
    }

    #[test]
    fn parse_rich_rule_skips_unrepresentable() {
        // A masquerade rich rule has no accept/reject verb we model.
        assert!(parse_rich_rule("rule family=\"ipv4\" masquerade").is_none());
        // Non-rule lines are ignored.
        assert!(parse_rich_rule("  services: ssh").is_none());
    }

    #[test]
    fn parse_target_maps_firewalld_strings() {
        assert_eq!(parse_target("ACCEPT"), Target::Accept);
        assert_eq!(parse_target("DROP"), Target::Drop);
        assert_eq!(parse_target("%%REJECT%%"), Target::Reject);
        assert_eq!(parse_target("default"), Target::Default);
    }

    #[test]
    fn detect_defaults_to_dry_run_without_env() {
        // Without QOS_FIREWALL_APPLY=1 we must never be Live, regardless of
        // whether firewall-cmd happens to exist on this host.
        let prev = std::env::var("QOS_FIREWALL_APPLY").ok();
        unsafe { std::env::remove_var("QOS_FIREWALL_APPLY") };
        let b = Backend::detect();
        assert_eq!(b.mode(), Mode::DryRun);
        if let Some(v) = prev {
            unsafe { std::env::set_var("QOS_FIREWALL_APPLY", v) };
        }
    }
}
