    #[test]
    fn apply_sends_the_plan_through_the_broker() {
        // The end-to-end app-level proof: a Live backend, wired to a real
        // broker over a socket pair, sends its computed plan and the broker
        // — having checked the manifest declaration and a consenting user —
        // applies it. Only the nft boundary (the broker's applier) is mocked.
        use qos_privileged_broker::{
            serve_connection, Broker, BrokerClient, Capabilities, FixedConsent,
            PrivilegedCapability, PrivilegedRequest, RecordingFirewall,
        };
        use std::os::unix::net::UnixStream;
        use std::thread;

        let (app_end, broker_end) = UnixStream::pair().unwrap();

        let server = thread::spawn(move || {
            let mut broker_end = broker_end;
            let mut broker = Broker::new(RecordingFirewall::default());
            let declared = Capabilities {
                privileged: vec![PrivilegedRequest::new(PrivilegedCapability::FirewallAdmin)],
            };
            serve_connection(
                &mut broker_end,
                &mut broker,
                "dev.qos.firewall",
                &declared,
                &FixedConsent(true),
            )
            .unwrap();
            broker.into_firewall_for_test()
        });

        let mut b = Backend {
            mode: Mode::Live,
            broker: Some(BrokerTransport::Fd(BrokerClient::from_stream(app_end))),
            last_plan: Vec::new(),
        };
        let cfg = crate::sample::sample_config();
        assert_eq!(b.apply(&cfg), Ok(()));

        // Drop the backend (and its client) so the broker's serve loop hits
        // EOF and hands the recorder back.
        drop(b);
        let recorder = server.join().unwrap();
        assert_eq!(
            recorder.applied.len(),
            1,
            "the broker's applier ran exactly once for the app's plan"
        );
        assert_eq!(
            recorder.applied[0],
            plan_commands(&cfg),
            "the broker applied exactly the plan the app computed"
        );
    }

