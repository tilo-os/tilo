//! Live system integration — translating the in-memory [`FirewallConfig`]
//! into `firewall-cmd` invocations and (optionally) applying them.
//!
//! This is **gated**: nothing here runs during `--shots` or in the headless
//! renderer. The live app calls [`Backend::detect`] once at startup; if
//! `firewall-cmd` is on `$PATH` *and* `TILO_FIREWALL_APPLY=1` is set, applies
//! are executed for real. Otherwise the backend stays in **dry-run** mode
//! and only records the commands it *would* run, which the UI surfaces in
//! the apply preview. This keeps the app safe to demo on any machine while
//! still being a genuine firewalld front-end when explicitly armed.
//!
//! We deliberately model the firewalld "runtime vs permanent" split with a
//! `--permanent` flag and a trailing `--reload`, matching how an operator
//! would persist changes.

use std::process::Command;
use std::time::Duration;

use crate::model::{Action, FirewallConfig, Matcher, Proto, Rule, Target, Zone, ZoneKind};

const COMMAND_OUTPUT_LIMIT: usize = 1024 * 1024;
const QUERY_TIMEOUT: Duration = Duration::from_secs(3);
const APPLY_TIMEOUT: Duration = Duration::from_secs(2 * 60);

/// How the backend will treat apply requests.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Mode {
    /// `firewall-cmd` present and `TILO_FIREWALL_APPLY=1` — commands run.
    Live,
    /// Commands are generated but never executed.
    DryRun,
}

pub struct Backend {
    mode: Mode,
    /// The last command plan generated by [`Backend::plan`]. Surfaced in
    /// the UI's apply preview.
    last_plan: Vec<String>,
}

/// An argv-preserving system invocation. Display text is kept separate from
/// execution so a rich rule remains one argument even though it contains
/// spaces and quotes. Never rebuild argv by splitting a display string.
#[derive(Clone, Debug, PartialEq, Eq)]
struct Invocation {
    program: &'static str,
    args: Vec<String>,
}

impl Invocation {
    fn new(program: &'static str, args: impl IntoIterator<Item = String>) -> Self {
        Self {
            program,
            args: args.into_iter().collect(),
        }
    }

    fn display(&self) -> String {
        let args = self
            .args
            .iter()
            .map(|arg| {
                if arg.contains(char::is_whitespace) {
                    format!("'{}'", arg.replace('\'', "'\\\"'\\\"'"))
                } else {
                    arg.clone()
                }
            })
            .collect::<Vec<_>>()
            .join(" ");
        format!("{} {args}", self.program)
    }
}

impl Backend {
    /// Inspect the environment and decide the operating mode.
    pub fn detect() -> Self {
        let has_cmd = which_firewall_cmd();
        let armed = std::env::var("TILO_FIREWALL_APPLY").as_deref() == Ok("1");
        let mode = if has_cmd && armed {
            Mode::Live
        } else {
            Mode::DryRun
        };
        Self {
            mode,
            last_plan: Vec::new(),
        }
    }

    pub fn mode(&self) -> Mode {
        self.mode
    }

    pub fn last_plan(&self) -> &[String] {
        &self.last_plan
    }

    /// Apply the plan for `cfg`. In [`Mode::DryRun`] this only regenerates
    /// the plan (no side effects) and returns `Ok(())`. In [`Mode::Live`]
    /// it executes each command, stopping at the first failure.
    ///
    /// # Errors
    ///
    /// Returns `Err` if a command in the plan fails to spawn, or exits with
    /// a non-zero status — execution stops at that command, and anything
    /// after it in the plan is not run.
    pub fn apply(&mut self, cfg: &FirewallConfig) -> Result<(), String> {
        let plan = build_invocations(cfg)?;
        self.last_plan = plan.iter().map(Invocation::display).collect();
        if self.mode == Mode::DryRun {
            return Ok(());
        }
        for invocation in &plan {
            let mut command = Command::new(invocation.program);
            command.args(&invocation.args);
            let output =
                bounded_command::run_prepared(command, None, COMMAND_OUTPUT_LIMIT, APPLY_TIMEOUT)
                    .map_err(|error| format!("could not run {}: {error}", invocation.program))?;
            if !output.status.success() {
                return Err(command_failure(invocation, &output));
            }
        }
        Ok(())
    }
}

fn command_failure(invocation: &Invocation, output: &bounded_command::Output) -> String {
    let detail = String::from_utf8_lossy(&output.stderr).trim().to_string();
    let guidance = if detail.contains("Access denied")
        || detail.contains("not authorized")
        || detail.contains("Authorization")
    {
        " Check your administrator authorization, then retry."
    } else if detail.contains("not running") || detail.contains("Failed to connect") {
        " firewalld is not running; start it and use Refresh before retrying."
    } else {
        " The live firewall was left at its last confirmed state; inspect the service and retry."
    };
    format!(
        "{} failed ({}): {}.{}",
        invocation.display(),
        output.status,
        if detail.is_empty() {
            "no diagnostic returned"
        } else {
            &detail
        },
        guidance
    )
}

/// Whether `firewall-cmd` is resolvable on `$PATH`.
fn which_firewall_cmd() -> bool {
    let Ok(path) = std::env::var("PATH") else {
        return false;
    };
    std::env::split_paths(&path).any(|p| p.join("firewall-cmd").is_file())
}

/// Run a read-only `firewall-cmd` query and return its trimmed stdout.
/// Every argument set passed here is a query (`--get-*`, `--list-all`,
/// `--query-*`, `--state`) — never a mutation — so importing the live
/// firewall has no side effects and needs no elevation on a normal
/// polkit-configured host.
fn query(args: &[&str]) -> Result<String, String> {
    let out = bounded_command::run(
        "firewall-cmd",
        args,
        None,
        COMMAND_OUTPUT_LIMIT,
        QUERY_TIMEOUT,
    )
    .map_err(|e| format!("run firewall-cmd: {e}"))?;
    if !out.status.success() {
        return Err(String::from_utf8_lossy(&out.stderr).trim().to_string());
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Read the **real** current firewall from the host via `firewall-cmd`.
///
/// Returns `None` when firewalld is not installed or not running — the
/// caller then shows an honest "unavailable" state rather than any
/// fabricated ruleset. When firewalld is running this reflects exactly what
/// the host has configured: the default zone, panic mode, and — for each of
/// the nine stock zones that exists — its interfaces, services, simple
/// port openings, masquerade flag, and rich rules.
pub fn import() -> Option<FirewallConfig> {
    if !which_firewall_cmd() {
        return None;
    }
    // firewalld must actually be running; `--state` prints "running".
    if query(&["--state"]).ok().as_deref() != Some("running") {
        return None;
    }

    let default_name = query(&["--get-default-zone"]).ok()?;
    let default_zone = ZoneKind::from_name(&default_name).unwrap_or(ZoneKind::Public);
    let panic_mode = query(&["--query-panic"]).is_ok_and(|s| s == "yes");

    let zone_names = query(&["--get-zones"]).unwrap_or_default();
    let mut zones = Vec::new();
    for name in zone_names.split_whitespace() {
        let Some(kind) = ZoneKind::from_name(name) else {
            continue;
        };
        if let Ok(text) = query(&["--zone", name, "--list-all"]) {
            zones.push(parse_list_all(kind, &text));
        }
    }

    Some(FirewallConfig {
        enabled: true,
        panic_mode,
        default_zone,
        zones,
    })
}

/// Parse the block emitted by `firewall-cmd --zone=<z> --list-all` into a
/// [`Zone`]. Pure — no IO — so it is unit-testable against captured output.
pub fn parse_list_all(kind: ZoneKind, text: &str) -> Zone {
    let mut zone = Zone::new(kind, Target::Default);
    let mut in_rich = false;
    for raw in text.lines() {
        // Rich-rule lines are indented under the `rich rules:` header; once
        // we've seen that header every subsequent `rule ...` line is one.
        let trimmed = raw.trim();
        if in_rich {
            if let Some(rule) = parse_rich_rule(trimmed) {
                zone.rules.push(rule);
                continue;
            }
            // A non-rule, non-empty line ends the rich-rule block.
            if !trimmed.is_empty() && !trimmed.starts_with("rule ") {
                in_rich = false;
            }
        }
        let Some((key, value)) = trimmed.split_once(':') else {
            continue;
        };
        let key = key.trim();
        let value = value.trim();
        match key {
            "target" => zone.target = parse_target(value),
            "interfaces" => {
                zone.interfaces = value.split_whitespace().map(str::to_string).collect();
            }
            "services" => zone.services = value.split_whitespace().map(str::to_string).collect(),
            "ports" => {
                for spec in value.split_whitespace() {
                    if let Some(m) = parse_port_spec(spec) {
                        zone.rules.push(Rule::new(m, Action::Allow, ""));
                    }
                }
            }
            "masquerade" => zone.masquerade = value == "yes",
            "rich rules" => in_rich = true,
            _ => {}
        }
    }
    zone
}

/// Map a firewalld target string to a [`Target`].
fn parse_target(s: &str) -> Target {
    match s {
        "ACCEPT" => Target::Accept,
        "DROP" => Target::Drop,
        "%%REJECT%%" | "REJECT" => Target::Reject,
        _ => Target::Default,
    }
}

/// Parse a `port/proto` spec (e.g. `8080/tcp`) into a [`Matcher::Port`].
fn parse_port_spec(spec: &str) -> Option<Matcher> {
    let (port, proto) = spec.split_once('/')?;
    let proto = match proto {
        "udp" => Proto::Udp,
        _ => Proto::Tcp,
    };
    Some(Matcher::Port {
        port: port.to_string(),
        proto,
    })
}

/// Parse a single firewalld rich-rule line into a [`Rule`]. Understands the
/// subset the app can represent: an accept/reject verb, an optional
/// `source address`, and either a `service name` or a `port`/`protocol`.
/// Returns `None` for rich rules outside that subset (e.g. masquerade or
/// icmp-type rules) so they're skipped rather than misrepresented.
pub fn parse_rich_rule(line: &str) -> Option<Rule> {
    if !line.starts_with("rule ") {
        return None;
    }
    let action = if line.contains(" accept") {
        Action::Allow
    } else if line.contains(" reject") || line.contains(" drop") {
        Action::Deny
    } else {
        return None;
    };
    let source = quoted_after(line, "source address=").unwrap_or_default();
    let matcher = if let Some(svc) = quoted_after(line, "service name=") {
        Matcher::Service(svc)
    } else {
        let port = quoted_after(line, "port port=")?;
        let proto = match quoted_after(line, "protocol=").as_deref() {
            Some("udp") => Proto::Udp,
            _ => Proto::Tcp,
        };
        Matcher::Port { port, proto }
    };
    Some(Rule::new(matcher, action, source))
}

/// Read the double-quoted value immediately following `needle` in `hay`.
fn quoted_after(hay: &str, needle: &str) -> Option<String> {
    let rest = hay.get(hay.find(needle)? + needle.len()..)?;
    let rest = rest.strip_prefix('"')?;
    let end = rest.find('"')?;
    Some(rest.get(..end)?.to_string())
}

/// Build the ordered list of `firewall-cmd` commands that would realise
/// `cfg`, as the tests read it.
#[cfg(test)]
fn plan_commands(cfg: &FirewallConfig) -> Vec<String> {
    build_invocations(cfg).map_or_else(
        |error| vec![format!("Blocked: invalid configuration — {error}")],
        |plan| plan.iter().map(Invocation::display).collect(),
    )
}

/// Build a safe argv plan. The representation is intentionally private: users
/// see a readable plan, while execution receives the exact original arguments.
fn build_invocations(cfg: &FirewallConfig) -> Result<Vec<Invocation>, String> {
    cfg.validate()?;
    if !cfg.enabled {
        return Ok(vec![Invocation::new(
            "systemctl",
            ["stop".to_string(), "firewalld".to_string()],
        )]);
    }

    let mut out = vec![Invocation::new(
        "systemctl",
        ["start".to_string(), "firewalld".to_string()],
    )];
    out.push(firewall_cmd([format!(
        "--set-default-zone={}",
        cfg.default_zone.name()
    )]));
    out.push(firewall_cmd([if cfg.panic_mode {
        "--panic-on".to_string()
    } else {
        "--panic-off".to_string()
    }]));
    for zone in &cfg.zones {
        plan_zone_args(zone, &mut out);
    }
    out.push(firewall_cmd(["--reload".to_string()]));
    Ok(out)
}

fn firewall_cmd(args: impl IntoIterator<Item = String>) -> Invocation {
    Invocation::new("firewall-cmd", args)
}

fn plan_zone_args(zone: &Zone, out: &mut Vec<Invocation>) {
    let name = zone.kind.name();
    out.push(firewall_cmd([
        "--permanent".to_string(),
        format!("--zone={name}"),
        format!(
            "--set-target={}",
            match zone.target {
                Target::Default => "default",
                Target::Accept => "ACCEPT",
                Target::Drop => "DROP",
                Target::Reject => "%%REJECT%%",
            }
        ),
    ]));
    for iface in &zone.interfaces {
        out.push(firewall_cmd([
            "--permanent".to_string(),
            format!("--zone={name}"),
            format!("--change-interface={iface}"),
        ]));
    }
    if zone.masquerade {
        out.push(firewall_cmd([
            "--permanent".to_string(),
            format!("--zone={name}"),
            "--add-masquerade".to_string(),
        ]));
    }
    for service in &zone.services {
        out.push(firewall_cmd([
            "--permanent".to_string(),
            format!("--zone={name}"),
            format!("--add-service={service}"),
        ]));
    }
    for rule in &zone.rules {
        if rule.enabled {
            out.push(rule_invocation(
                name,
                &rule.matcher,
                rule.action,
                &rule.source,
            ));
        }
    }
}

fn rule_invocation(zone: &str, matcher: &Matcher, action: Action, source: &str) -> Invocation {
    let has_source = !source.trim().is_empty();
    if action == Action::Allow
        && !has_source
        && let Matcher::Port { port, proto } = matcher
    {
        return firewall_cmd([
            "--permanent".to_string(),
            format!("--zone={zone}"),
            format!("--add-port={port}/{}", proto.label()),
        ]);
    }
    firewall_cmd([
        "--permanent".to_string(),
        format!("--zone={zone}"),
        format!(
            "--add-rich-rule={}",
            rich_rule_body(matcher, action, source)
        ),
    ])
}

/// Render a single rule as either a simple `--add-port` (allow, anywhere,
/// port matcher) or a full firewalld rich-rule string otherwise.
#[cfg(test)]
fn rich_rule(zone: &str, matcher: &Matcher, action: Action, source: &str) -> String {
    let invocation = rule_invocation(zone, matcher, action, source);
    invocation.display()
}

fn rich_rule_body(matcher: &Matcher, action: Action, source: &str) -> String {
    use std::fmt::Write as _;

    let has_source = !source.trim().is_empty();
    // Simple fast-path: allow a port from anywhere → plain --add-port.
    if action == Action::Allow
        && !has_source
        && let Matcher::Port { port, proto } = matcher
    {
        return format!("port port=\"{port}\" protocol=\"{}\" accept", proto.label());
    }

    let mut rule = String::from("rule family=\"ipv4\"");
    if has_source {
        let _ = write!(rule, " source address=\"{}\"", source.trim());
    }
    match matcher {
        Matcher::Service(s) => {
            let _ = write!(rule, " service name=\"{s}\"");
        }
        Matcher::Port { port, proto } => {
            let _ = write!(rule, " port port=\"{port}\" protocol=\"{}\"", proto.label());
        }
    }
    let verb = match action {
        Action::Allow => "accept",
        Action::Deny => "reject",
    };
    let _ = write!(rule, " {verb}");
    rule
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::model::{Proto, Target, ZoneKind};

    #[test]
    fn apply_includes_each_zones_default_policy_before_reload() {
        for (target, wire_target) in [
            (Target::Default, "default"),
            (Target::Accept, "ACCEPT"),
            (Target::Drop, "DROP"),
            (Target::Reject, "%%REJECT%%"),
        ] {
            let mut config = crate::sample::sample_config();
            config.zone_mut(ZoneKind::Public).unwrap().target = target;
            let mut backend = Backend {
                mode: Mode::DryRun,
                last_plan: Vec::new(),
            };
            backend.apply(&config).unwrap();
            let expected =
                format!("firewall-cmd --permanent --zone=public --set-target={wire_target}");
            let policy = backend
                .last_plan()
                .iter()
                .position(|line| line == &expected)
                .expect("applying a policy must send it to firewalld");
            let reload = backend
                .last_plan()
                .iter()
                .position(|line| line == "firewall-cmd --reload")
                .unwrap();
            assert!(policy < reload);
        }
    }

    /// Planned changes become the right firewall-cmd invocations (fast paths, rich rules as one argument), and detection defaults to dry-run.
    #[test]
    fn plan_translates_changes_into_firewall_cmd_invocations() {
        // --- phase: plan_sets_default_zone_and_reloads ---
        {
            let cfg = crate::sample::sample_config();
            let plan = plan_commands(&cfg);
            assert_eq!(plan.first().unwrap(), "systemctl start firewalld");
            assert!(
                plan.iter()
                    .any(|line| line == "firewall-cmd --set-default-zone=public")
            );
            assert_eq!(plan.last().unwrap(), "firewall-cmd --reload");
        }

        // --- phase: allow_port_anywhere_uses_add_port_fastpath ---
        {
            let s = rich_rule(
                "public",
                &Matcher::Port {
                    port: "51820".into(),
                    proto: Proto::Udp,
                },
                Action::Allow,
                "",
            );
            assert_eq!(
                s,
                "firewall-cmd --permanent --zone=public --add-port=51820/udp"
            );
        }

        // --- phase: deny_with_source_uses_rich_rule ---
        {
            let s = rich_rule(
                "public",
                &Matcher::Port {
                    port: "3389".into(),
                    proto: Proto::Tcp,
                },
                Action::Deny,
                "0.0.0.0/0",
            );
            assert!(s.contains("--add-rich-rule="));
            assert!(s.contains("source address=\"0.0.0.0/0\""));
            assert!(s.contains("port port=\"3389\" protocol=\"tcp\""));
            assert!(s.contains("reject"));
        }

        // --- phase: service_allow_with_source_is_rich_rule ---
        {
            let s = rich_rule(
                "work",
                &Matcher::Service("ipp".into()),
                Action::Allow,
                "192.168.0.0/16",
            );
            assert!(s.contains("service name=\"ipp\""));
            assert!(s.contains("accept"));
            assert!(s.contains("192.168.0.0/16"));
        }

        // --- phase: masquerade_zone_emits_add_masquerade ---
        {
            let mut z = Zone::new(ZoneKind::External, Target::Default);
            z.masquerade = true;
            let mut out = Vec::new();
            plan_zone_args(&z, &mut out);
            assert!(
                out.iter()
                    .any(|invocation| invocation.args.iter().any(|arg| arg == "--add-masquerade"))
            );
        }

        // --- phase: rich_rule_is_one_argument_at_execution_time ---
        {
            let invocation = rule_invocation(
                "public",
                &Matcher::Port {
                    port: "3389".into(),
                    proto: Proto::Tcp,
                },
                Action::Deny,
                "10.0.0.0/8",
            );
            assert_eq!(invocation.program, "firewall-cmd");
            assert_eq!(invocation.args.len(), 3);
            assert!(invocation.args[2].starts_with("--add-rich-rule=rule family="));
        }

        // --- phase: detect_defaults_to_dry_run_without_env ---
        {
            // Without TILO_FIREWALL_APPLY=1 we must never be Live, regardless of
            // whether firewall-cmd happens to exist on this host.
            let mut env = tilo_test_env::ScopedEnv::new();
            env.remove("TILO_FIREWALL_APPLY");
            let b = Backend::detect();
            assert_eq!(b.mode(), Mode::DryRun);
        }
    }

    const LIST_ALL: &str = "\
public (active)
  target: default
  icmp-block-inversion: no
  interfaces: wlan0 eth0
  sources:
  services: dhcpv6-client mdns ssh
  ports: 8080/tcp 51820/udp
  protocols:
  masquerade: no
  forward-ports:
  source-ports:
  icmp-blocks:
  rich rules:
\trule family=\"ipv4\" source address=\"192.168.1.0/24\" service name=\"https\" accept
\trule family=\"ipv4\" port port=\"23\" protocol=\"tcp\" reject
";

    /// firewalld list-all output, rich rules and targets parse faithfully, skipping what cannot be represented.
    #[test]
    fn parse_reads_firewalld_output_faithfully() {
        // --- phase: parse_list_all_reads_real_zone_fields ---
        {
            let z = parse_list_all(ZoneKind::Public, LIST_ALL);
            assert_eq!(z.target, Target::Default);
            assert_eq!(z.interfaces, vec!["wlan0", "eth0"]);
            assert_eq!(z.services, vec!["dhcpv6-client", "mdns", "ssh"]);
            assert!(!z.masquerade);
            // Two simple ports become allow-from-anywhere rules...
            assert!(z.rules.iter().any(|r| r.matcher
                == Matcher::Port {
                    port: "8080".into(),
                    proto: Proto::Tcp
                }
                && r.action == Action::Allow
                && r.source.is_empty()));
            assert!(z.rules.iter().any(|r| r.matcher
                == Matcher::Port {
                    port: "51820".into(),
                    proto: Proto::Udp
                }));
            // ...plus the two rich rules.
            assert!(
                z.rules
                    .iter()
                    .any(|r| r.matcher == Matcher::Service("https".into())
                        && r.action == Action::Allow
                        && r.source == "192.168.1.0/24")
            );
            assert!(z.rules.iter().any(|r| r.matcher
                == Matcher::Port {
                    port: "23".into(),
                    proto: Proto::Tcp
                }
                && r.action == Action::Deny));
        }

        // --- phase: parse_rich_rule_service_accept_with_source ---
        {
            let r = parse_rich_rule(
            "rule family=\"ipv4\" source address=\"10.8.0.0/24\" service name=\"cockpit\" accept",
        )
        .unwrap();
            assert_eq!(r.matcher, Matcher::Service("cockpit".into()));
            assert_eq!(r.action, Action::Allow);
            assert_eq!(r.source, "10.8.0.0/24");
        }

        // --- phase: parse_rich_rule_skips_unrepresentable ---
        {
            // A masquerade rich rule has no accept/reject verb we model.
            assert!(parse_rich_rule("rule family=\"ipv4\" masquerade").is_none());
            // Non-rule lines are ignored.
            assert!(parse_rich_rule("  services: ssh").is_none());
        }

        // --- phase: parse_target_maps_firewalld_strings ---
        {
            assert_eq!(parse_target("ACCEPT"), Target::Accept);
            assert_eq!(parse_target("DROP"), Target::Drop);
            assert_eq!(parse_target("%%REJECT%%"), Target::Reject);
            assert_eq!(parse_target("default"), Target::Default);
        }
    }
}
